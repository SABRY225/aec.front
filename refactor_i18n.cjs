const fs = require('fs');
const path = require('path');

const targetFile = process.argv[2];

if (!targetFile) {
    console.error('Please provide a target file');
    process.exit(1);
}

let content = fs.readFileSync(targetFile, 'utf8');

const regex = /(isRtl|isRTL)\s*\?\s*(['"`])((?:(?!\2)[^\\]|\\.)*?)\2\s*:\s*(['"`])((?:(?!\4)[^\\]|\\.)*?)\4/g;

let match;
let matchCount = 0;
const translations = [];

let newContent = content.replace(regex, (match, p1, q1, arText, q2, enText) => {
    matchCount++;
    let key = enText
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '_')
        .replace(/^_+|_+$/g, '')
        .substring(0, 30);
    
    if (!key) {
        key = 'text_' + Math.random().toString(36).substr(2, 5);
    }
    
    translations.push({ key, ar: arText, en: enText });

    return `t('autoGenerated.${key}', \`${enText.replace(/`/g, "\\`")}\`)`;
});

fs.writeFileSync(targetFile, newContent, 'utf8');

console.log(`Replaced ${matchCount} matches in ${targetFile}`);

let existingTranslations = [];
try {
    existingTranslations = JSON.parse(fs.readFileSync('translations_dump.json', 'utf8'));
} catch (e) {
    // Ignore if not exists
}

existingTranslations = existingTranslations.concat(translations);
fs.writeFileSync('translations_dump.json', JSON.stringify(existingTranslations, null, 2), 'utf8');
