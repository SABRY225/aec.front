function updateLocalesFile(filePath, newTranslations) {
    let content = fs.readFileSync(filePath, 'utf8');
    
    // Replace "export default" to "module.exports =" temporarily
    const tempFile = filePath + '.temp.cjs';
    fs.writeFileSync(tempFile, content.replace('export default', 'module.exports ='));
    
    const obj = require('./' + tempFile);
    
    if (!obj.autoGenerated) obj.autoGenerated = {};
    for (const key in newTranslations) {
        obj.autoGenerated[key] = newTranslations[key];
    }
    
    fs.unlinkSync(tempFile);
    
    const newContent = 'export default ' + JSON.stringify(obj, null, 4) + ';\n';
    fs.writeFileSync(filePath, newContent);
    console.log("Updated", filePath);
}

updateLocalesFile('src/locales/ar/autoGenerated.js', arTranslations);
updateLocalesFile('src/locales/en/autoGenerated.js', enTranslations);
