const fs = require('fs');
const path = require('path');
const babelParser = require('@babel/parser');
const traverse = require('@babel/traverse').default;
const MagicString = require('magic-string').default;

const filesToProcess = [
    'src/components/Cart.jsx',
    'src/components/CourseCard.jsx',
    'src/components/explore/CourseCategories.jsx',
    'src/components/Footer.jsx',
    'src/components/Header.jsx',
    'src/components/homepage/AdvertisementSection.jsx',
    'src/components/main/AskForHelp.jsx',
    'src/components/main/CategoriesSection.jsx',
    'src/components/main/FeaturedCourses.jsx',
    'src/components/main/HeroSection.jsx',
    'src/components/main/TestimonialsSection.jsx',
    'src/components/main/TopRunningCourses.jsx',
    'src/components/Navigation.jsx',
    'src/components/shared/NotificationBell.jsx',
    'src/components/UserProfileMenu.jsx'
];

let globalDict = {};
let keyCounter = 1000;

function hasArabic(text) {
    return /[\u0600-\u06FF]/.test(text);
}

filesToProcess.forEach(file => {
    const fullPath = path.join(__dirname, file);
    if (!fs.existsSync(fullPath)) return;
    const code = fs.readFileSync(fullPath, 'utf8');
    
    const hasTranslationImport = code.includes('useTranslation');

    try {
        const ast = babelParser.parse(code, {
            sourceType: 'module',
            plugins: ['jsx']
        });

        const magicString = new MagicString(code);
        let needsTranslationHook = false;
        let changesMade = false;

        traverse(ast, {
            JSXText(path) {
                const text = path.node.value;
                if (hasArabic(text) && text.trim()) {
                    const cleanText = text.trim();
                    const key = `compText${keyCounter++}`;
                    globalDict[key] = cleanText;
                    
                    const beforeSpace = text.match(/^\s*/)[0];
                    const afterSpace = text.match(/\s*$/)[0];
                    const escapedText = cleanText.replace(/'/g, "\\'");
                    magicString.overwrite(path.node.start, path.node.end, `${beforeSpace}{t('autoGenerated.${key}', '${escapedText}')}${afterSpace}`);
                    changesMade = true;
                    needsTranslationHook = true;
                }
            },
            StringLiteral(path) {
                if (path.parent.type === 'ImportDeclaration') return;
                
                const text = path.node.value;
                if (hasArabic(text)) {
                    const key = `compText${keyCounter++}`;
                    globalDict[key] = text;
                    const escapedText = text.replace(/'/g, "\\'");
                    
                    if (path.parent.type === 'JSXAttribute') {
                        magicString.overwrite(path.node.start, path.node.end, `{t('autoGenerated.${key}', '${escapedText}')}`);
                    } else {
                        magicString.overwrite(path.node.start, path.node.end, `t('autoGenerated.${key}', '${escapedText}')`);
                    }
                    changesMade = true;
                    needsTranslationHook = true;
                }
            }
        });

        if (changesMade) {
            let result = magicString.toString();
            
            if (needsTranslationHook) {
                if (!hasTranslationImport) {
                    const importMatch = result.match(/import.*?from.*?;?\n/g);
                    const lastImportIndex = importMatch ? result.lastIndexOf(importMatch[importMatch.length - 1]) + importMatch[importMatch.length - 1].length : 0;
                    
                    result = result.slice(0, lastImportIndex) + "import { useTranslation } from 'react-i18next';\n" + result.slice(lastImportIndex);
                }

                if (!result.includes('const { t } = useTranslation()') && !result.includes('const { t, i18n } = useTranslation()')) {
                    const returnIndex = result.indexOf('return (');
                    if (returnIndex !== -1) {
                        result = result.slice(0, returnIndex) + "const { t } = useTranslation();\n    " + result.slice(returnIndex);
                    }
                }
            }

            fs.writeFileSync(fullPath, result, 'utf8');
            console.log(`Processed: ${file}`);
        }
    } catch (e) {
        console.error(`Failed on ${file}:`, e);
    }
});

fs.writeFileSync(path.join(__dirname, 'components_translations.json'), JSON.stringify(globalDict, null, 2), 'utf8');
console.log('Done!');
