import { useState, useEffect, useRef } from 'react';
import { Link, useNavigate, useLocation } from 'react-router-dom';
import { useTranslation } from 'react-i18next';
import logo from '/assets/logo.png';
import UserProfileMenu from './UserProfileMenu';
import { useAuth } from '../context/AuthContext';
import { useCart } from '../context/CartContext';
import { courseService } from '../services/new-api';
import LanguageSwitcher from './LanguageSwitcher';
import NotificationBell from './shared/NotificationBell';
import {
    Search,
    ShoppingCart,
    Phone,
    Mail,
    Menu,
    X,
    Sparkles,
    GraduationCap,
    BookOpen,
    Home,
    Info,
    MessageSquare,
    PhoneCall,
    Loader2,
    UserPlus,
    ChevronLeft
} from 'lucide-react';

const Header = () => {
    const { t, i18n } = useTranslation();
    const { user, isAuthenticated } = useAuth();
    const { getCartItemsCount, toggleCart } = useCart();

    const [isMobileMenuOpen, setIsMobileMenuOpen] = useState(false);
    const [searchQuery, setSearchQuery] = useState('');
    const [searchResults, setSearchResults] = useState([]);
    const [isSearching, setIsSearching] = useState(false);
    const [showSearchResults, setShowSearchResults] = useState(false);
    const [isSearchInputOpen, setIsSearchInputOpen] = useState(false);

    const searchRef = useRef(null);
    const navigate = useNavigate();
    const location = useLocation();

    // Debounced search effect
    useEffect(() => {
        const timeoutId = setTimeout(() => {
            if (searchQuery.trim()) {
                performSearch(searchQuery);
            } else {
                setSearchResults([]);
                setShowSearchResults(false);
            }
        }, 300);

        return () => clearTimeout(timeoutId);
    }, [searchQuery]);

    const performSearch = async (query) => {
        try {
            setIsSearching(true);
            const response = await courseService.getAllCourses({
                search: query,
                limit: 5,
                status: 'approved'
            });
            setSearchResults(response.courses || []);
            setShowSearchResults(true);
        } catch (error) {
            console.error('Search error:', error);
            setSearchResults([]);
        } finally {
            setIsSearching(false);
        }
    };

    const handleSearchSubmit = (e) => {
        e.preventDefault();
        if (searchQuery.trim()) {
            navigate(`/explore?search=${encodeURIComponent(searchQuery)}`);
            setShowSearchResults(false);
            setIsSearchInputOpen(false);
            setSearchQuery('');
        }
    };

    const handleCourseSelect = (courseId) => {
        navigate(`/course/${courseId}`);
        setShowSearchResults(false);
        setIsSearchInputOpen(false);
        setSearchQuery('');
    };

    // Close search dropdown on click outside
    useEffect(() => {
        const handleClickOutside = (event) => {
            if (searchRef.current && !searchRef.current.contains(event.target)) {
                setShowSearchResults(false);
            }
        };

        document.addEventListener('mousedown', handleClickOutside);
        return () => document.removeEventListener('mousedown', handleClickOutside);
    }, []);

    const toggleMobileMenu = () => {
        setIsMobileMenuOpen(!isMobileMenuOpen);
    };

    const closeMobileMenu = () => {
        setIsMobileMenuOpen(false);
    };

    const cartCount = getCartItemsCount ? getCartItemsCount() : 0;

    const navItems = [
        { path: '/', label: t('autoGenerated.compText1146', 'الرئيسية'), icon: Home },
        { path: '/explore', label: t('autoGenerated.compText1147', 'دوراتنا'), icon: BookOpen },
        { path: '/about', label: t('autoGenerated.compText1148', 'من نحن'), icon: Info },
        { path: '/contact', label: t('autoGenerated.compText1149', 'تواصل معنا'), icon: PhoneCall },
    ];

    return (
        <div className="w-full font-arabic relative z-50">
            {/* Top Navy Blue Contact & Direct Hotline Bar */}
            <div className="bg-[#06102b] text-white py-2 text-xs font-medium border-b border-blue-900/50 shadow-inner" dir={i18n.language === 'ar' ? 'rtl' : 'ltr'}>
                <div className="container mx-auto px-4 sm:px-6 lg:px-8 flex items-center justify-between">
                    {/* Right Side Info: Branch Phone Numbers & Email */}
                    <div className="flex items-center gap-3 sm:gap-6">
                        <a
                            href="tel:+966540098736"
                            className="flex items-center gap-1.5 bg-blue-950/80 hover:bg-blue-900/80 px-2.5 py-1 rounded-full border border-blue-800/40 hover:border-blue-500/50 transition-all text-slate-200 hover:text-white"
                        >
                            <span className="text-xs">🇸🇦</span>
                            <span dir="ltr" className="font-sans font-bold text-[11px] sm:text-xs tracking-wide">+966 54 009 8736</span>
                        </a>
                        <a
                            href="mailto:info@aectraining.com"
                            className="hidden md:flex items-center gap-1.5 text-slate-300 hover:text-blue-300 transition-colors"
                        >
                            <Mail className="w-3.5 h-3.5 text-blue-400 shrink-0" />
                            <span className="text-[11px] sm:text-xs">info@aectraining.com</span>
                        </a>
                    </div>

                    {/* Left Side Tagline Badge */}
                    <div className="flex items-center gap-2 text-blue-200 font-bold text-[11px] sm:text-xs">
                        <span className="hidden lg:inline text-slate-300">{t('autoGenerated.compText1150', 'منصتك الشاملة لكافة التخصصات والمسارات المهنية')}</span>
                    </div>
                </div>
            </div>

            {/* Main Navbar Header */}
            <header className="bg-white/95 backdrop-blur-xl shadow-sm border-b border-slate-200/80 sticky top-0 z-40 transition-all" dir={i18n.language === 'ar' ? 'rtl' : 'ltr'}>
                <div className="container mx-auto px-4 sm:px-6 lg:px-8 py-2.5 sm:py-3">
                    <nav className="flex items-center justify-between gap-3 lg:gap-6">

                        {/* Right: Brand Logo */}
                        <Link to="/" className="flex items-center group shrink-0">
                            <img
                                src={logo}
                                alt={t('autoGenerated.compText1151', 'AEC Academy | أكاديمية التدريب والتطوير المهني الشامل')}
                                className="h-10 sm:h-12 w-auto transition-transform duration-300 group-hover:scale-105 drop-shadow-sm"
                            />
                        </Link>

                        {/* Center: Navigation Links */}
                        <div className="hidden lg:flex items-center gap-1 xl:gap-2">
                            {navItems.map((item) => {
                                const isActive = location.pathname === item.path;
                                const IconComponent = item.icon;
                                return (
                                    <Link
                                        key={item.path}
                                        to={item.path}
                                        className={`flex items-center gap-1.5 text-xs xl:text-sm font-bold px-3.5 py-2 rounded-full transition-all duration-200 ${isActive
                                                ? 'bg-blue-50 text-blue-700 shadow-sm border border-blue-200/60'
                                                : 'text-slate-700 hover:text-blue-600 hover:bg-slate-100/70'
                                            }`}
                                    >
                                        <IconComponent className={`w-4 h-4 ${isActive ? 'text-blue-600' : 'text-slate-400'}`} />
                                        <span>{item.label}</span>
                                    </Link>
                                );
                            })}
                        </div>

                        {/* Center/Left Desktop Search Input with Autocomplete */}
                        <div ref={searchRef} className="relative hidden md:block max-w-xs xl:max-w-sm w-full">
                            <form onSubmit={handleSearchSubmit} className="relative">
                                <input
                                    type="text"
                                    value={searchQuery}
                                    onChange={(e) => setSearchQuery(e.target.value)}
                                    placeholder={t('autoGenerated.compText1152', 'ابحث عن تخصص، مسار مهني، أو دورة تدريبية...')}
                                    className="w-full ps-10 pe-9 py-2 bg-slate-100/80 hover:bg-slate-100 focus:bg-white border border-slate-200 focus:border-blue-600 focus:ring-4 focus:ring-blue-500/10 rounded-full text-xs font-medium outline-none transition-all shadow-inner"
                                />
                                <Search className="w-4 h-4 text-slate-400 absolute start-3 top.1/2 -translate-y-1/2 top-3 pointer-events-none" />
                                {isSearching ? (
                                    <Loader2 className="w-4 h-4 text-blue-600 animate-spin absolute end-3 top-2.5" />
                                ) : searchQuery && (
                                    <button
                                        type="button"
                                        onClick={() => setSearchQuery('')}
                                        className="absolute end-3 top-2.5 text-slate-400 hover:text-slate-600"
                                    >
                                        <X className="w-3.5 h-3.5" />
                                    </button>
                                )}
                            </form>

                            {/* Live Search Results Dropdown */}
                            {showSearchResults && (
                                <div className="absolute top-full start-0 w-full mt-2 bg-white rounded-2xl shadow-2xl border border-slate-200/80 overflow-hidden z-50 animate-in fade-in slide-in-from-top-2 duration-200">
                                    <div className="p-2.5 text-[11px] font-bold text-slate-400 bg-slate-50 border-b border-slate-100 flex items-center justify-between">
                                        <span>{t('autoGenerated.compText1153', 'نتائج البحث المباشرة')}</span>
                                        <span className="text-blue-600 font-normal">{searchResults.length} {t('autoGenerated.compText1154', 'دورات')}</span>
                                    </div>
                                    <div className="divide-y divide-slate-100 max-h-72 overflow-y-auto">
                                        {searchResults.length > 0 ? (
                                            searchResults.map((course) => (
                                                <div
                                                    key={course._id || course.id}
                                                    onClick={() => handleCourseSelect(course._id || course.id)}
                                                    className="p-3 hover:bg-blue-50/80 cursor-pointer transition-colors flex items-center gap-3 group"
                                                >
                                                    {course.image ? (
                                                        <img src={course.image} alt={course.title} className="w-11 h-11 rounded-xl object-cover shadow-sm group-hover:scale-105 transition-transform" />
                                                    ) : (
                                                        <div className="w-11 h-11 rounded-xl bg-blue-100 flex items-center justify-center text-blue-600">
                                                            <BookOpen className="w-5 h-5" />
                                                        </div>
                                                    )}
                                                    <div className="flex-1 overflow-hidden">
                                                        <h4 className="text-xs font-bold text-slate-800 truncate group-hover:text-blue-600 transition-colors">{course.title}</h4>
                                                        <div className="flex items-center gap-2 mt-0.5">
                                                            <span className="text-[11px] text-blue-600 font-bold">
                                                                {course.price ? `${course.price} ريال` : t('autoGenerated.compText1155', 'مجاناً')}
                                                            </span>
                                                            {course.level && (
                                                                <span className="text-[10px] bg-slate-100 text-slate-600 px-1.5 py-0.5 rounded">
                                                                    {course.level}
                                                                </span>
                                                            )}
                                                        </div>
                                                    </div>
                                                    <ChevronLeft className="w-4 h-4 text-slate-400 group-hover:text-blue-600 group-hover:-translate-x-1 transition-all" />
                                                </div>
                                            ))
                                        ) : (
                                            <div className="p-4 text-center text-xs text-slate-500">
                                                {t('autoGenerated.compText1156', 'لا توجد دورات تطابق بحثك، جرّب مجالات مثل: هندسة، برمجة، إدارة، محاسبة، لغات')}
                                            </div>
                                        )}
                                    </div>
                                </div>
                            )}
                        </div>

                        {/* Left: Action Controls */}
                        <div className="flex items-center gap-2 sm:gap-3 shrink-0">

                            {/* Mobile Search Icon Toggle */}
                            <button
                                onClick={() => setIsSearchInputOpen(!isSearchInputOpen)}
                                className="md:hidden p-2 text-slate-600 hover:text-blue-600 hover:bg-slate-100 rounded-full transition-colors"
                                title={t('autoGenerated.compText1157', 'بحث')}
                                aria-label={t('autoGenerated.compText1158', 'فتح البحث')}
                            >
                                <Search className="w-5 h-5" />
                            </button>

                            {/* Cart Icon */}
                            {toggleCart && (
                                <button
                                    onClick={toggleCart}
                                    className="relative p-2.5 text-slate-700 hover:text-blue-600 hover:bg-blue-50 rounded-full transition-colors border border-transparent hover:border-blue-100"
                                    title={t('autoGenerated.compText1159', 'سلة الدورات')}
                                    aria-label={t('autoGenerated.compText1160', 'سلة التسوق')}
                                >
                                    <ShoppingCart className="w-5 h-5" />
                                    {cartCount > 0 && (
                                        <span className="absolute -top-0.5 -end-0.5 bg-red-600 text-white font-bold text-[10px] min-w-[18px] h-[18px] px-1 rounded-full flex items-center justify-center shadow-sm animate-pulse">
                                            {cartCount}
                                        </span>
                                    )}
                                </button>
                            )}

                            {/* Language Switcher */}
                            <LanguageSwitcher />

                            {/* In-app Notification Bell */}
                            {isAuthenticated && (
                                <NotificationBell />
                            )}

                            {/* Register Now button / User Profile */}
                            {isAuthenticated ? (
                                <UserProfileMenu />
                            ) : (
                                <Link
                                    to="/login"
                                    className="inline-flex items-center gap-1.5 bg-gradient-to-r from-red-600 via-red-500 to-rose-600 hover:from-red-700 hover:to-rose-700 text-white font-bold px-4 sm:px-5 py-2 sm:py-2.5 rounded-full text-xs sm:text-sm shadow-md shadow-red-600/20 hover:shadow-lg hover:shadow-red-600/30 transition-all transform hover:-translate-y-0.5 active:translate-y-0 whitespace-nowrap"
                                >
                                    <UserPlus className="w-4 h-4 shrink-0" />
                                    <span>{t('autoGenerated.compText1161', 'سجل الآن')}</span>
                                </Link>
                            )}

                            {/* Mobile Hamburger Menu Button */}
                            <button
                                onClick={toggleMobileMenu}
                                className="lg:hidden p-2 text-slate-700 hover:bg-slate-100 rounded-xl transition-colors border border-slate-200/60"
                                aria-label="Toggle Navigation Menu"
                            >
                                {isMobileMenuOpen ? (
                                    <X className="w-6 h-6 text-slate-800" />
                                ) : (
                                    <Menu className="w-6 h-6 text-slate-800" />
                                )}
                            </button>
                        </div>
                    </nav>

                    {/* Mobile Expandable Search Bar */}
                    {isSearchInputOpen && (
                        <div className="md:hidden pt-3 border-t border-slate-100 mt-2.5 animate-in fade-in slide-in-from-top-1 duration-200">
                            <form onSubmit={handleSearchSubmit} className="relative">
                                <input
                                    type="text"
                                    value={searchQuery}
                                    onChange={(e) => setSearchQuery(e.target.value)}
                                    placeholder={t('autoGenerated.compText1162', 'ابحث عن تخصص، مسار مهني، أو دورة...')}
                                    className="w-full ps-10 pe-4 py-2.5 bg-slate-100 border border-slate-200 rounded-xl text-xs font-medium outline-none focus:border-blue-600"
                                />
                                <Search className="w-4 h-4 text-slate-400 absolute start-3 top-3 pointer-events-none" />
                            </form>
                        </div>
                    )}

                    {/* Mobile Navigation Drawer */}
                    {isMobileMenuOpen && (
                        <div className="lg:hidden mt-3 pt-3 border-t border-slate-100 space-y-1.5 pb-2 animate-in fade-in slide-in-from-top-2 duration-200">
                            {navItems.map((item) => {
                                const isActive = location.pathname === item.path;
                                const IconComponent = item.icon;
                                return (
                                    <Link
                                        key={item.path}
                                        to={item.path}
                                        onClick={closeMobileMenu}
                                        className={`flex items-center gap-3 px-4 py-2.5 rounded-xl text-xs sm:text-sm font-bold transition-all ${isActive
                                                ? 'bg-blue-600 text-white shadow-md shadow-blue-600/20'
                                                : 'text-slate-800 hover:bg-blue-50 hover:text-blue-600'
                                            }`}
                                    >
                                        <IconComponent className={`w-4 h-4 ${isActive ? 'text-white' : 'text-slate-500'}`} />
                                        <span>{item.label}</span>
                                    </Link>
                                );
                            })}

                            <button
                                type="button"
                                onClick={() => {
                                    closeMobileMenu();
                                    toggleCart();
                                }}
                                className="w-full flex items-center justify-between px-4 py-2.5 rounded-xl text-xs sm:text-sm font-bold text-slate-800 hover:bg-blue-50 hover:text-blue-600 transition"
                            >
                                <div className="flex items-center gap-3">
                                    <ShoppingCart className="w-4 h-4 text-slate-500" />
                                    <span>{t('cart.title', t('autoGenerated.compText1163', 'سلة التسوق'))}</span>
                                </div>
                                {cartCount > 0 && (
                                    <span className="bg-red-600 text-white text-[10px] font-bold px-2 py-0.5 rounded-full">
                                        {cartCount}
                                    </span>
                                )}
                            </button>

                            <div className="pt-2 mt-2 border-t border-slate-100 flex items-center justify-around text-xs font-semibold text-slate-600">
                                <a href="tel:+966540098736" className="flex items-center gap-1 text-slate-700 hover:text-blue-600">
                                    <span>🇸🇦</span>
                                    <span dir="ltr">+966 54 009 8736</span>
                                </a>
                            </div>
                        </div>
                    )}
                </div>
            </header>
        </div>
    );
};

export default Header;

