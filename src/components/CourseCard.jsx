import React, { useState, useEffect, useMemo } from 'react';
import { motion } from 'framer-motion';
import { useNavigate, Link } from 'react-router-dom';
import { useTranslation } from 'react-i18next';
import {
    Star,
    Users,
    Clock,
    Tag,
    ShoppingCart,
    Eye,
    Play,
    Lock,
    CheckCircle2,
    Video,
    Building,
    Check
} from 'lucide-react';
import { toast } from 'react-toastify';
import { useCart } from '../context/CartContext';
import { useAuth } from '../context/AuthContext';
import { useCategoryLookup } from '../context/CategoryLookupContext';
import { normalizeCourseType } from '../constants/courseTypes';
import api from '../services/new-api';
import RichTextDisplay from './RichTextDisplay/RichTextDisplay';

const CourseCard = ({ course, className = '' }) => {
    const { t, i18n } = useTranslation();
    const isRTL = i18n.language === 'ar';
    const navigate = useNavigate();
    const { addToCart, isInCart } = useCart();
    const { user } = useAuth();
    const { localizeCategoryPath } = useCategoryLookup();
    const [enrollmentStatus, setEnrollmentStatus] = useState(null);
    const [checkingEnrollment, setCheckingEnrollment] = useState(false);

    useEffect(() => {
        // Enrollment status is only for students/instructors — admins get 403 from the API
        if (user && course._id && (user.role === 'student' || user.role === 'instructor')) {
            checkEnrollmentStatus();
        } else {
            setEnrollmentStatus(null);
        }
    }, [user, course._id]);

    const checkEnrollmentStatus = async () => {
        try {
            setCheckingEnrollment(true);
            const response = await api.get(`/enrollment/status/${course._id}`);
            setEnrollmentStatus(response.data);
        } catch (error) {
            const status = error.response?.status;
            // 404 = not enrolled; 403 = role not allowed — both are expected on catalog cards
            if (status === 404 || status === 403) {
                setEnrollmentStatus(null);
            } else {
                console.error('Error checking enrollment:', error);
            }
        } finally {
            setCheckingEnrollment(false);
        }
    };

    const handleCourseClick = (courseId) => {
        navigate(`/course/${courseId}`);
    };

    const handleAddToCart = (e, course) => {
        e.stopPropagation();

        if (isInCart(course._id)) {
            toast.info(t('course.toast.alreadyInCart', t('autoGenerated.compText1025', 'الدورة موجودة بالفعل في سلة التسوق')));
        } else {
            addToCart(course);
            toast.success(t('course.toast.addedToCart', t('autoGenerated.compText1026', 'تمت إضافة الدورة إلى سلة التسوق بنجاح')));
        }
    };

    const handleEnrollClick = (e, course) => {
        e.stopPropagation();

        if (!isInCart(course._id)) {
            addToCart(course);
        }

        // Always use relative path for navigation to avoid URL doubling in production
        navigate('/checkout');
    };

    const handleContinueCourse = (e) => {
        e.stopPropagation();
        navigate(`/course/${course._id}/study`);
    };

    const formatDuration = (minutes) => {
        if (!minutes) return t('course.card.durationDefault', t('autoGenerated.compText1027', 'تدريب مرن'));
        const hours = Math.floor(minutes / 60);
        const mins = minutes % 60;
        if (isRTL) {
            return hours > 0 ? `${hours} س ${mins > 0 ? `${mins} د` : ''}` : `${mins} دقيقة`;
        }
        return hours > 0 ? `${hours}h ${mins > 0 ? `${mins}m` : ''}` : `${mins}m`;
    };

    const getCourseLevelLabel = (level) => {
        const levelMap = {
            beginner: t('course.card.level.beginner', t('autoGenerated.compText1028', 'مبتدئ')),
            intermediate: t('course.card.level.intermediate', t('autoGenerated.compText1029', 'متوسط')),
            advanced: t('course.card.level.advanced', t('autoGenerated.compText1030', 'متقدم')),
            'all-levels': t('course.card.level.allLevels', t('autoGenerated.compText1031', 'كافة المستويات')),
        };
        return levelMap[level?.toLowerCase?.()] || t('course.card.level.beginner', t('autoGenerated.compText1032', 'مبتدئ'));
    };

    const getCourseTypeConfig = (type) => {
        const canonical = normalizeCourseType(type);
        if (canonical === 'live') {
            return {
                label: t('course.card.courseType.live', t('autoGenerated.compText1033', 'أونلاين مباشر')),
                icon: Video,
                badgeClasses: 'bg-rose-50 text-rose-700 border-rose-200/80',
                dotClass: 'bg-rose-500 animate-pulse'
            };
        }
        if (canonical === 'onsite') {
            return {
                label: t('course.card.courseType.onsite', t('autoGenerated.compText1034', 'حضوري')),
                icon: Building,
                badgeClasses: 'bg-emerald-50 text-emerald-700 border-emerald-200/80',
                dotClass: 'bg-emerald-500'
            };
        }
        return {
            label: t('course.card.courseType.recorded', t('autoGenerated.compText1035', 'مسجل ذاتي')),
            icon: Play,
            badgeClasses: 'bg-blue-50 text-blue-700 border-blue-200/80',
            dotClass: 'bg-blue-500'
        };
    };

    const courseTypeConfig = getCourseTypeConfig(course.courseType);
    const categoryPath = localizeCategoryPath(course.category, course.subCategory);
    const coursePrice = Number(course.displayPrice ?? course.price ?? 0);
    const originalPrice = Number(course.originalPrice || 0);
    const hasDiscount = originalPrice > coursePrice && coursePrice > 0;
    const discountPercent = hasDiscount ? Math.round(((originalPrice - coursePrice) / originalPrice) * 100) : 0;

    const instructorId = course.instructor?._id || (typeof course.instructor === 'string' ? course.instructor : null) || course.instructorId;

    const instructorName = course.instructor
        ? `${course.instructor.firstName || ''} ${course.instructor.lastName || ''}`.trim()
        : (isRTL ? t('autoGenerated.compText1036', 'أكاديمية AEC') : 'AEC Academy');

    const handleInstructorClick = (e) => {
        if (!instructorId) return;
        e.stopPropagation();
        e.preventDefault();
        navigate(`/profile/${instructorId}`);
    };

    const inCart = isInCart(course._id);

    return (
        <motion.div
            onClick={() => handleCourseClick(course._id)}
            whileHover={{ y: -6 }}
            transition={{ duration: 0.25 }}
            className={`group relative bg-white rounded-3xl border border-slate-200/85 hover:border-blue-500/50 shadow-sm hover:shadow-2xl hover:shadow-blue-900/10 transition-all duration-300 cursor-pointer overflow-hidden flex flex-col h-full ${className}`}
        >
            {/* Top Accent Gradient Border on Hover */}
            <div className="h-1 w-full bg-gradient-to-r from-[#004C97] via-[#F7931E] to-[#004C97] opacity-0 group-hover:opacity-100 transition-opacity duration-300 absolute top-0 inset-x-0 z-30" />

            {/* Course Thumbnail Image */}
            <div className="relative aspect-[16/10] w-full overflow-hidden bg-slate-900 shrink-0">
                {course.thumbnail ? (
                    <img
                        src={course.thumbnail}
                        alt={course.title}
                        loading="lazy"
                        className="w-full h-full object-cover transition-transform duration-700 ease-out group-hover:scale-108"
                    />
                ) : (
                    <div className="w-full h-full bg-gradient-to-br from-[#071942] to-[#004C97] flex flex-col items-center justify-center p-4 text-center">
                        <span className="text-white text-3xl font-black mb-1">
                            {course.title ? course.title.charAt(0).toUpperCase() : 'AEC'}
                        </span>
                        <span className="text-blue-200 text-xs font-semibold">AEC Academy</span>
                    </div>
                )}

                {/* Subtle Image Vignette Scrim */}
                <div className="absolute inset-0 bg-gradient-to-t from-slate-950/70 via-transparent to-black/25 pointer-events-none" />

                {/* Top Floating Badges (Start side) */}
                <div className="absolute top-3 start-3 z-10 flex flex-wrap items-center gap-1.5">
                    {/* Course Delivery Type Badge */}
                    <span className={`inline-flex items-center gap-1.5 px-2.5 py-1 rounded-xl text-xs font-bold border backdrop-blur-md shadow-sm ${courseTypeConfig.badgeClasses}`}>
                        <span className={`w-1.5 h-1.5 rounded-full ${courseTypeConfig.dotClass}`} />
                        <span>{courseTypeConfig.label}</span>
                    </span>

                    {/* Course Level Badge */}
                    <span className="inline-flex items-center px-2.5 py-1 rounded-xl text-xs font-bold bg-slate-900/80 backdrop-blur-md text-white border border-white/15 shadow-sm">
                        {getCourseLevelLabel(course.courseLevel)}
                    </span>
                </div>

                {/* Top Floating Badges (End side): Discount or Full */}
                <div className="absolute top-3 end-3 z-10 flex items-center gap-1.5">
                    {course.isFull ? (
                        <span className="inline-flex items-center px-2.5 py-1 rounded-xl text-xs font-bold bg-amber-500 text-white shadow-md">
                            {t('course.card.full', t('autoGenerated.compText1037', 'مكتمل'))}
                        </span>
                    ) : hasDiscount ? (
                        <span className="inline-flex items-center px-2.5 py-1 rounded-xl text-xs font-black bg-rose-600 text-white shadow-md">
                            {isRTL ? `خصم ${discountPercent}%` : `${discountPercent}% OFF`}
                        </span>
                    ) : null}
                </div>

                {/* Bottom Verified Strip on Thumbnail */}
                <div className="absolute bottom-2.5 start-3 end-3 z-10 flex items-center justify-between text-white/95">
                    <span className="inline-flex items-center gap-1 text-[11px] font-semibold drop-shadow">
                        <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
                        <span>{isRTL ? t('autoGenerated.compText1038', 'شهادة إتمام معتمدة') : 'Accredited Certificate'}</span>
                    </span>

                    {/* Review Rating Pill */}
                    <div className="inline-flex items-center gap-1 bg-slate-900/85 backdrop-blur-md text-amber-300 text-xs font-bold px-2.5 py-0.5 rounded-lg border border-white/10 shadow-sm">
                        <Star className="w-3 h-3 text-amber-400 fill-amber-400" />
                        <span>{course.averageRating ? course.averageRating.toFixed(1) : '5.0'}</span>
                    </div>
                </div>
            </div>

            {/* Course Card Body */}
            <div className="p-5 sm:p-6 flex flex-col flex-1">
                {/* Category & Subcategory Tag */}
                {categoryPath && (
                    <div className="mb-2">
                        <span className="inline-flex items-center gap-1.5 text-xs font-bold text-blue-700 bg-blue-50/80 border border-blue-100 px-2.5 py-1 rounded-lg line-clamp-1 max-w-full">
                            <Tag className="w-3 h-3 text-blue-500 shrink-0" />
                            <span className="truncate">{categoryPath}</span>
                        </span>
                    </div>
                )}

                {/* Course Title */}
                <h3 className="text-base sm:text-lg font-bold text-slate-900 group-hover:text-blue-600 transition-colors line-clamp-2 leading-snug mb-3 min-h-[2.85rem]">
                    {course.title}
                </h3>

                {/* Instructor Row */}
                <div
                    onClick={instructorId ? handleInstructorClick : undefined}
                    className={`flex items-center gap-2.5 mb-3.5 group/instructor ${
                        instructorId ? 'cursor-pointer' : ''
                    }`}
                    title={instructorId ? (isRTL ? `عرض الملف الشخصي لـ ${instructorName}` : `View ${instructorName}'s Profile`) : undefined}
                >
                    {course.instructor?.photo ? (
                        <img
                            src={course.instructor.photo}
                            alt={instructorName}
                            className={`w-7 h-7 rounded-full object-cover ring-1 ring-slate-200 shrink-0 transition-all ${
                                instructorId ? 'group-hover/instructor:ring-2 group-hover/instructor:ring-blue-500 group-hover/instructor:scale-105' : ''
                            }`}
                        />
                    ) : (
                        <div className={`w-7 h-7 rounded-full bg-blue-100 border border-blue-200 flex items-center justify-center shrink-0 transition-all ${
                            instructorId ? 'group-hover/instructor:bg-blue-200 group-hover/instructor:border-blue-400 group-hover/instructor:scale-105' : ''
                        }`}>
                            <span className="text-blue-700 font-bold text-xs">
                                {course.instructor?.firstName?.[0] || 'A'}
                            </span>
                        </div>
                    )}
                    <div className="min-w-0 flex-1">
                        <span className={`text-xs font-semibold text-slate-700 truncate block transition-colors ${
                            instructorId ? 'group-hover/instructor:text-blue-600 group-hover/instructor:underline' : ''
                        }`}>
                            {instructorName}
                        </span>
                    </div>
                </div>

                {/* Key Metrics Strip (Rating, Duration, Enrolled) */}
                <div className="grid grid-cols-3 gap-2 py-2 px-3 rounded-2xl bg-slate-50/90 border border-slate-100/90 text-center mb-4">
                    {/* Rating */}
                    <div className="flex flex-col items-center justify-center">
                        <div className="flex items-center gap-1 text-xs font-bold text-slate-800">
                            <Star className="w-3.5 h-3.5 text-amber-500 fill-amber-500" />
                            <span>{course.averageRating ? course.averageRating.toFixed(1) : '5.0'}</span>
                        </div>
                        <span className="text-[10px] text-slate-400 font-medium mt-0.5">
                            ({course.reviewCount || 0} {isRTL ? t('autoGenerated.compText1039', 'تقييم') : 'reviews'})
                        </span>
                    </div>

                    {/* Duration */}
                    <div className="flex flex-col items-center justify-center border-x border-slate-200/60">
                        <div className="flex items-center gap-1 text-xs font-bold text-slate-800">
                            <Clock className="w-3.5 h-3.5 text-blue-600" />
                            <span>{formatDuration(course.duration)}</span>
                        </div>
                        <span className="text-[10px] text-slate-400 font-medium mt-0.5">
                            {isRTL ? t('autoGenerated.compText1040', 'مدة الدورة') : 'Duration'}
                        </span>
                    </div>

                    {/* Enrolled Students */}
                    <div className="flex flex-col items-center justify-center">
                        <div className="flex items-center gap-1 text-xs font-bold text-slate-800">
                            <Users className="w-3.5 h-3.5 text-emerald-600" />
                            <span>{course.enrollmentCount || 0}</span>
                        </div>
                        <span className="text-[10px] text-slate-400 font-medium mt-0.5">
                            {isRTL ? t('autoGenerated.compText1041', 'طالب مسجل') : 'Students'}
                        </span>
                    </div>
                </div>

                {/* Description Snippet
                {course.description && (
                    <div className="text-xs sm:text-sm text-slate-500 line-clamp-2 leading-relaxed min-h-[36px] mb-4">
                        <RichTextDisplay
                            content={course.description}
                            maxLength={130}
                            showFull={false}
                            className="line-clamp-2"
                        />
                    </div>
                )} */}

                {/* Card Footer: Pricing & Action Buttons */}
                <div className="border-t border-slate-100 pt-4 mt-auto">
                    <div className="flex items-center justify-between gap-3">
                        
                        {/* Price Area: Before & After Display */}
                        <div className="min-w-0">
                            {hasDiscount ? (
                                <div className="flex flex-col gap-0.5">
                                    {/* Price Before (Original) */}
                                    <div className="flex items-center gap-1.5 flex-wrap">
                                        <span className="text-[11px] font-medium text-slate-400">
                                            {isRTL ? 'قبل:' : 'Before:'}
                                        </span>
                                        <span className="text-xs font-semibold text-slate-400 line-through tracking-tight">
                                            {originalPrice.toLocaleString()} {t('common.sar', t('autoGenerated.compText1044', 'ر.س'))}
                                        </span>
                                        <span className="inline-flex items-center text-[10px] font-black px-1.5 py-0.5 rounded-md bg-rose-50 text-rose-600 border border-rose-200/60 leading-none">
                                            {isRTL ? `خصم ${discountPercent}%` : `-${discountPercent}%`}
                                        </span>
                                    </div>

                                    {/* Price After (Current) */}
                                    <div className="flex items-baseline gap-1.5 flex-wrap">
                                        <span className="text-[11px] font-bold text-[#004C97] bg-blue-50 px-1.5 py-0.5 rounded">
                                            {isRTL ? 'بعد:' : 'Now:'}
                                        </span>
                                        <span className="text-lg sm:text-xl font-black text-slate-900 tracking-tight">
                                            {coursePrice === 0
                                                ? t('course.card.price.free', t('autoGenerated.compText1042', 'مجاناً'))
                                                : `${coursePrice.toLocaleString()} ${t('common.sar', t('autoGenerated.compText1043', 'ر.س'))}`}
                                        </span>
                                    </div>

                                    <span className="text-[10px] text-emerald-600 font-semibold block mt-0.5">
                                        {isRTL ? t('autoGenerated.compText1045', 'شامل الشهادة والضريبة') : 'Includes Certificate'}
                                    </span>
                                </div>
                            ) : (
                                <div>
                                    <div className="flex items-baseline gap-1.5 flex-wrap">
                                        <span className="text-lg sm:text-xl font-black text-slate-900 tracking-tight">
                                            {coursePrice === 0
                                                ? t('course.card.price.free', t('autoGenerated.compText1042', 'مجاناً'))
                                                : `${coursePrice.toLocaleString()} ${t('common.sar', t('autoGenerated.compText1043', 'ر.س'))}`}
                                        </span>
                                    </div>
                                    <span className="text-[10px] text-emerald-600 font-semibold block mt-0.5">
                                        {isRTL ? t('autoGenerated.compText1045', 'شامل الشهادة والضريبة') : 'Includes Certificate'}
                                    </span>
                                </div>
                            )}
                        </div>

                        {/* Action Buttons */}
                        <div className="flex items-center gap-1.5">
                            {user && enrollmentStatus?.isInstructor ? (
                                /* Instructor: Manage Course */
                                <button
                                    onClick={(e) => {
                                        e.stopPropagation();
                                        navigate(`/instructor/courses/${course._id}/edit`);
                                    }}
                                    className="bg-purple-600 hover:bg-purple-700 active:bg-purple-800 text-white px-3.5 py-2 rounded-xl font-bold text-xs shadow-md shadow-purple-600/20 transition-all"
                                >
                                    {t('course.card.actions.manageCourse', t('autoGenerated.compText1047', 'إدارة'))}
                                </button>
                            ) : user && enrollmentStatus ? (
                                /* Enrolled Student: Continue Learning */
                                <button
                                    onClick={handleContinueCourse}
                                    className="inline-flex items-center gap-1.5 bg-emerald-600 hover:bg-emerald-700 active:bg-emerald-800 text-white px-3.5 py-2 rounded-xl font-bold text-xs shadow-md shadow-emerald-600/20 transition-all"
                                >
                                    <Play className="w-3.5 h-3.5 fill-current" />
                                    <span>{t('course.card.actions.continueCourse', t('autoGenerated.compText1048', 'متابعة'))}</span>
                                </button>
                            ) : (
                                /* Public / Not Enrolled */
                                <>
                                    {/* Add to Cart Icon Button */}
                                    <button
                                        onClick={(e) => handleAddToCart(e, course)}
                                        disabled={checkingEnrollment}
                                        title={inCart ? t('course.toast.alreadyInCart', t('autoGenerated.compText1049', 'في السلة')) : t('course.card.actions.addToCart', t('autoGenerated.compText1050', 'أضف للسلة'))}
                                        className={`p-2 rounded-xl border transition-all duration-200 flex items-center justify-center ${
                                            inCart
                                                ? 'bg-emerald-50 border-emerald-300 text-emerald-600 shadow-sm'
                                                : 'bg-slate-50 border-slate-200 text-slate-600 hover:text-blue-600 hover:border-blue-300 hover:bg-white'
                                        }`}
                                    >
                                        {inCart ? (
                                            <Check className="w-4 h-4 text-emerald-600 stroke-[2.5]" />
                                        ) : (
                                            <ShoppingCart className="w-4 h-4" />
                                        )}
                                    </button>

                                    {/* Primary CTA: Enroll Now */}
                                    <button
                                        onClick={(e) => handleEnrollClick(e, course)}
                                        disabled={checkingEnrollment}
                                        className="bg-[#004C97] hover:bg-[#071942] active:bg-[#061435] text-white px-3.5 py-2 rounded-xl font-bold text-xs shadow-md shadow-blue-900/15 transition-all flex items-center justify-center gap-1"
                                    >
                                        <span>{checkingEnrollment ? t('course.card.actions.loading', t('autoGenerated.compText1051', 'جاري...')) : t('course.card.actions.enrollNow', t('autoGenerated.compText1052', 'سجل الآن'))}</span>
                                    </button>
                                </>
                            )}

                            {/* View Details Eye Button */}
                            <button
                                onClick={(e) => {
                                    e.stopPropagation();
                                    handleCourseClick(course._id);
                                }}
                                title={t('common.view', t('autoGenerated.compText1053', 'عرض التفاصيل'))}
                                className="p-2 rounded-xl border border-slate-200 text-slate-500 hover:text-blue-600 hover:border-blue-300 hover:bg-slate-50 transition-all flex items-center justify-center"
                            >
                                <Eye className="w-4 h-4" />
                            </button>
                        </div>

                    </div>
                </div>

            </div>
        </motion.div>
    );
};

export default CourseCard;