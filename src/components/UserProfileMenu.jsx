import { useState, useRef, useEffect } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import { useTranslation } from 'react-i18next';
import { useAuth } from '../context/AuthContext';


const UserProfileMenu = ({ user: propUser }) => {
    const { t } = useTranslation();
    const [isOpen, setIsOpen] = useState(false);
    const dropdownRef = useRef(null);
    const { logout, user: authUser } = useAuth();
    const navigate = useNavigate();
    const user = propUser || authUser;

    useEffect(() => {
        const handleClickOutside = (event) => {
            if (dropdownRef.current && !dropdownRef.current.contains(event.target)) {
                setIsOpen(false);
            }
        };

        document.addEventListener('mousedown', handleClickOutside);
        return () => document.removeEventListener('mousedown', handleClickOutside);
    }, []);

    const getInitials = () => {
        const firstName = user?.firstName || '';
        const lastName = user?.lastName || '';
        return `${firstName[0] || ''}${lastName[0] || ''}`.toUpperCase();
    };

    if (!user) return null;

    const mainDestination = user.role === 'admin'
        ? '/admin/dashboard'
        : user.role === 'instructor'
            ? (user.isVerified ? '/instructor/dashboard' : (user.hasInstructorApplication || user.instructorApplicationStatus === 'pending' ? '/instructor/pending-approval' : '/instructor/apply'))
            : '/student/dashboard';

    const mainLabel = user.role === 'instructor' && !user.isVerified
        ? (user.hasInstructorApplication || user.instructorApplicationStatus === 'pending' ? t('autoGenerated.compText1402', 'متابعة حالة الطلب') : t('autoGenerated.compText1403', 'تقديم طلب الانضمام'))
        : t('nav.userProfileMenu.dashboard');

    return (
        <div className="relative" ref={dropdownRef}>
            <button
                onClick={() => setIsOpen(!isOpen)}
                className="flex items-center gap-2 focus:outline-none"
            >
                <div className="relative">
                    {user?.photo ? (
                        <img
                            src={user.photo}
                            alt={user.firstName}
                            className="w-10 h-10 rounded-full border-2 border-blue-200 hover:border-blue-400 transition-colors cursor-pointer"
                        />
                    ) : (
                        <div className="w-10 h-10 rounded-full bg-gradient-to-br from-blue-500 to-purple-600 flex items-center justify-center text-white font-bold text-sm cursor-pointer hover:scale-105 transition-transform">
                            {getInitials()}
                        </div>
                    )}
                </div>
                <svg
                    className={`w-4 h-4 text-gray-600 transform transition-transform ${isOpen ? 'rotate-180' : ''
                        }`}
                    fill="none"
                    stroke="currentColor"
                    viewBox="0 0 24 24"
                >
                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M19 9l-7 7-7-7" />
                </svg>
            </button>

            {isOpen && (
                <div className="absolute end-0 mt-2 w-48 bg-white rounded-md shadow-lg py-1 z-50">
                    <Link
                        to={mainDestination}
                        className="block px-4 py-2 text-sm text-gray-700 hover:bg-gray-100 font-medium"
                        onClick={() => setIsOpen(false)}
                    >
                        {mainLabel}
                    </Link>
                    <Link
                        to={`/${user.role.toLowerCase()}/account-settings`}
                        className="block px-4 py-2 text-sm text-gray-700 hover:bg-gray-100"
                        onClick={() => setIsOpen(false)}
                    >
                        {t('nav.userProfileMenu.accountSettings')}
                    </Link>
                    <Link
                        to={`/${user.role.toLowerCase()}/profile-settings`}
                        className="block px-4 py-2 text-sm text-gray-700 hover:bg-gray-100"
                        onClick={() => setIsOpen(false)}
                    >
                        {t('nav.userProfileMenu.profileSettings')}
                    </Link>
                    <button
                        onClick={async () => {
                            const result = await logout();
                            setIsOpen(false);
                            if (result?.redirectPath) {
                                navigate(result.redirectPath);
                            }
                        }}
                        className="block w-full text-start px-4 py-2 text-sm text-gray-700 hover:bg-gray-100 border-t border-gray-100"
                    >
                        <span>{t('nav.userProfileMenu.logout')}</span>
                    </button>
                </div>
            )}
        </div>
    );
};

export default UserProfileMenu;
