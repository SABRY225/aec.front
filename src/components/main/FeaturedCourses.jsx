import React, { useState, useEffect, useRef, useCallback, useMemo } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { useNavigate, Link } from 'react-router-dom';
import { useTranslation } from 'react-i18next';
import {
    Sparkles,
    Flame,
    Star,
    Clock,
    Users,
    Award,
    Tag,
    ShoppingCart,
    Play,
    ChevronLeft,
    ChevronRight,
    ArrowLeft,
    ArrowRight,
    Lock,
    CheckCircle2,
    Video,
    Building,
    BookOpen
} from 'lucide-react';
import { toast } from 'react-toastify';
import { courseService } from '../../services/new-api';
import { useAuth } from '../../context/AuthContext';
import { useCart } from '../../context/CartContext';
import { useCategoryLookup } from '../../context/CategoryLookupContext';
import api from '../../services/new-api';
import CourseTypeFilter from '../common/CourseTypeFilter';

const FeaturedCourses = () => {
    const { t, i18n } = useTranslation();
    const isArabic = i18n.language === 'ar';
    const navigate = useNavigate();

    const [courses, setCourses] = useState([]);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState(null);
    const [currentSlide, setCurrentSlide] = useState(0);
    const [isAutoPlaying, setIsAutoPlaying] = useState(true);
    const [isHovered, setIsHovered] = useState(false);
    const [courseType, setCourseType] = useState('');
    const [enrollmentStatuses, setEnrollmentStatuses] = useState({});

    const { user } = useAuth();
    const { addToCart, isInCart } = useCart();
    const { localizeCategoryPath } = useCategoryLookup();
    const autoPlayRef = useRef(null);

    // Responsive slides per view
    const [slidesPerView, setSlidesPerView] = useState(3);

    useEffect(() => {
        const handleResize = () => {
            if (window.innerWidth < 640) {
                setSlidesPerView(1);
            } else if (window.innerWidth < 1024) {
                setSlidesPerView(2);
            } else {
                setSlidesPerView(3);
            }
        };

        handleResize();
        window.addEventListener('resize', handleResize);
        return () => window.removeEventListener('resize', handleResize);
    }, []);

    useEffect(() => {
        fetchFeaturedCourses();
    }, [courseType]);

    useEffect(() => {
        if (user && courses.length > 0) {
            checkEnrollmentStatuses();
        }
    }, [user, courses]);

    const fetchFeaturedCourses = async () => {
        try {
            setLoading(true);
            setError(null);
            const response = await courseService.getFeaturedCourses(
                courseType ? { courseType } : {}
            );
            setCourses(response?.courses || []);
            setCurrentSlide(0);
        } catch (err) {
            console.error('Error fetching featured courses:', err);
            setError(t('home.featured.failedToLoad', t('autoGenerated.compText1220', 'تعذّر تحميل الدورات المميزة')));
        } finally {
            setLoading(false);
        }
    };

    const checkEnrollmentStatuses = async () => {
        try {
            const statuses = {};
            await Promise.all(
                courses.map(async (course) => {
                    try {
                        const response = await api.get(`/enrollment/status/${course._id}`);
                        statuses[course._id] = response.data;
                    } catch (err) {
                        if (err.response?.status === 404 || err.response?.status === 403) {
                            statuses[course._id] = null;
                        }
                    }
                })
            );
            setEnrollmentStatuses(statuses);
        } catch (err) {
            console.error('Error checking enrollment statuses in featured courses:', err);
        }
    };

    const maxSlide = useMemo(() => {
        return Math.max(0, courses.length - slidesPerView);
    }, [courses.length, slidesPerView]);

    // Auto-play interval
    useEffect(() => {
        if (isAutoPlaying && !isHovered && courses.length > slidesPerView) {
            autoPlayRef.current = setInterval(() => {
                setCurrentSlide((prev) => (prev >= maxSlide ? 0 : prev + 1));
            }, 4500);
        }

        return () => {
            if (autoPlayRef.current) {
                clearInterval(autoPlayRef.current);
            }
        };
    }, [isAutoPlaying, isHovered, courses.length, slidesPerView, maxSlide]);

    const nextSlide = useCallback(() => {
        setCurrentSlide((prev) => (prev >= maxSlide ? 0 : prev + 1));
        setIsAutoPlaying(false);
        setTimeout(() => setIsAutoPlaying(true), 8000);
    }, [maxSlide]);

    const prevSlide = useCallback(() => {
        setCurrentSlide((prev) => (prev <= 0 ? maxSlide : prev - 1));
        setIsAutoPlaying(false);
        setTimeout(() => setIsAutoPlaying(true), 8000);
    }, [maxSlide]);

    const goToSlide = (index) => {
        setCurrentSlide(index);
        setIsAutoPlaying(false);
        setTimeout(() => setIsAutoPlaying(true), 8000);
    };

    const handleCourseClick = (courseId) => {
        navigate(`/course/${courseId}`);
    };

    const handleAddToCart = (e, course) => {
        e.stopPropagation();
        if (isInCart(course._id)) {
            toast.info(t('course.toast.alreadyInCart', t('autoGenerated.compText1221', 'الدورة موجودة بالفعل في السلة')));
        } else {
            addToCart(course);
            toast.success(t('course.toast.addedToCart', t('autoGenerated.compText1222', 'تمت إضافة الدورة إلى السلة')));
        }
    };

    const handleEnrollClick = (e, course) => {
        e.stopPropagation();
        if (!isInCart(course._id)) {
            addToCart(course);
        }
        navigate('/checkout');
    };

    const handleContinueCourse = (e, courseId) => {
        e.stopPropagation();
        navigate(`/course/${courseId}/study`);
    };

    const formatPrice = (price) => {
        if (price === 0) return t('course.card.price.free', t('autoGenerated.compText1223', 'مجاناً'));
        return t('course.card.price.sar', { amount: Number(price).toLocaleString() });
    };

    const formatDuration = (minutes) => {
        if (!minutes || minutes <= 0) return isArabic ? t('autoGenerated.compText1224', 'مرن') : 'Flexible';
        const hours = Math.floor(minutes / 60);
        const mins = minutes % 60;
        if (hours > 0 && mins > 0) {
            return isArabic ? `${hours} س و ${mins} د` : `${hours}h ${mins}m`;
        }
        if (hours > 0) {
            return isArabic ? `${hours} ساعة` : `${hours} hrs`;
        }
        return isArabic ? `${mins} دقيقة` : `${mins} mins`;
    };

    const getCourseLevelLabel = (level) => {
        switch (level) {
            case 'beginner':
                return isArabic ? t('autoGenerated.compText1225', 'مبتدئ') : 'Beginner';
            case 'intermediate':
                return isArabic ? t('autoGenerated.compText1226', 'متوسط') : 'Intermediate';
            case 'advanced':
                return isArabic ? t('autoGenerated.compText1227', 'متقدم') : 'Advanced';
            case 'all-levels':
            default:
                return isArabic ? t('autoGenerated.compText1228', 'جميع المستويات') : 'All Levels';
        }
    };

    const getCourseTypeBadge = (type) => {
        switch (type) {
            case 'online':
                return {
                    label: isArabic ? t('autoGenerated.compText1229', 'أونلاين مباشر') : 'Live Online',
                    icon: Video,
                    color: 'bg-emerald-50 text-emerald-700 border-emerald-200/80',
                    dot: 'bg-emerald-500'
                };
            case 'recorded':
                return {
                    label: isArabic ? t('autoGenerated.compText1230', 'مسجلة') : 'Recorded',
                    icon: Play,
                    color: 'bg-blue-50 text-blue-700 border-blue-200/80',
                    dot: 'bg-blue-500'
                };
            case 'in-person':
            case 'offline':
                return {
                    label: isArabic ? t('autoGenerated.compText1231', 'حضوري') : 'In-Person',
                    icon: Building,
                    color: 'bg-purple-50 text-purple-700 border-purple-200/80',
                    dot: 'bg-purple-500'
                };
            default:
                return null;
        }
    };

    // Direction-aware Icons
    const ForwardChevron = isArabic ? ChevronLeft : ChevronRight;
    const BackwardChevron = isArabic ? ChevronRight : ChevronLeft;
    const DirectionArrow = isArabic ? ArrowLeft : ArrowRight;

    return (
        <section
            className="py-14 sm:py-20 lg:py-24 bg-gradient-to-b from-white via-slate-50/60 to-white relative overflow-hidden font-arabic"
            dir={isArabic ? 'rtl' : 'ltr'}
        >
            {/* Ambient Background Lighting */}
            <div className="absolute top-1/3 start-1/4 -translate-y-1/2 w-96 h-96 bg-primary-500/5 rounded-full blur-3xl pointer-events-none" />
            <div className="absolute bottom-1/3 end-1/4 translate-y-1/2 w-96 h-96 bg-amber-500/5 rounded-full blur-3xl pointer-events-none" />

            <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 relative z-10">

                {/* Section Header */}
                <div className="text-center max-w-3xl mx-auto mb-10 sm:mb-14">
                    <motion.div
                        initial={{ opacity: 0, y: -10 }}
                        whileInView={{ opacity: 1, y: 0 }}
                        viewport={{ once: true }}
                        className="inline-flex items-center gap-2 bg-gradient-to-r from-amber-50 via-orange-50 to-primary-50 border border-amber-200/80 text-amber-900 px-4 py-1.5 rounded-full text-xs sm:text-sm font-extrabold shadow-sm mb-4"
                    >
                        <Flame className="w-4 h-4 text-orange-600 fill-current animate-pulse" />
                        <span>{isArabic ? t('autoGenerated.compText1232', 'برامج تدريبية معتمدة ومميزة') : 'Featured Flagship Programs'}</span>
                    </motion.div>

                    <motion.h2
                        initial={{ opacity: 0, y: 15 }}
                        whileInView={{ opacity: 1, y: 0 }}
                        viewport={{ once: true }}
                        transition={{ delay: 0.1 }}
                        className="text-3xl sm:text-4xl lg:text-5xl font-black text-slate-900 tracking-tight leading-tight mb-4"
                    >
                        {t('home.featured.title', t('autoGenerated.compText1233', 'دورات مميزة'))}
                    </motion.h2>

                    <motion.p
                        initial={{ opacity: 0, y: 15 }}
                        whileInView={{ opacity: 1, y: 0 }}
                        viewport={{ once: true }}
                        transition={{ delay: 0.2 }}
                        className="text-slate-600 text-sm sm:text-base lg:text-lg leading-relaxed max-w-2xl mx-auto"
                    >
                        {t('home.featured.subtitleLong', t('autoGenerated.compText1234', 'دورات متميزة يختارها خبراؤنا لتسريع رحلتك التعليمية واكتساب مهارات احترافية معتمدة'))}
                    </motion.p>

                    {/* Course Type Filter */}
                    <motion.div
                        initial={{ opacity: 0, y: 15 }}
                        whileInView={{ opacity: 1, y: 0 }}
                        viewport={{ once: true }}
                        transition={{ delay: 0.3 }}
                        className="mt-8 flex justify-center"
                    >
                        <CourseTypeFilter
                            value={courseType}
                            onChange={setCourseType}
                            showLabel={false}
                            align="center"
                            className="w-full max-w-xl mx-auto"
                        />
                    </motion.div>
                </div>

                {/* Loading State */}
                {loading && (
                    <div className="max-w-5xl mx-auto py-8">
                        <div className="rounded-3xl bg-white border border-slate-200/80 p-8 shadow-sm animate-pulse grid grid-cols-1 lg:grid-cols-12 gap-8 items-center">
                            <div className="lg:col-span-5 aspect-[16/10] bg-slate-200 rounded-2xl" />
                            <div className="lg:col-span-7 space-y-4">
                                <div className="h-6 w-32 bg-slate-200 rounded-full" />
                                <div className="h-8 w-4/5 bg-slate-200 rounded-xl" />
                                <div className="h-4 w-full bg-slate-200 rounded" />
                                <div className="h-4 w-3/4 bg-slate-200 rounded" />
                                <div className="h-12 bg-slate-100 rounded-xl" />
                                <div className="flex gap-4 pt-4">
                                    <div className="h-11 w-36 bg-slate-200 rounded-xl" />
                                    <div className="h-11 w-28 bg-slate-200 rounded-xl" />
                                </div>
                            </div>
                        </div>
                    </div>
                )}

                {/* Error Banner */}
                {error && !loading && (
                    <div className="max-w-md mx-auto text-center p-6 bg-rose-50 border border-rose-200 rounded-2xl">
                        <p className="text-rose-700 font-bold mb-4">{error}</p>
                        <button
                            onClick={fetchFeaturedCourses}
                            className="px-5 py-2.5 bg-primary-600 hover:bg-primary-700 text-white font-bold text-sm rounded-xl transition-colors shadow-md"
                        >
                            {t('common.tryAgain', t('autoGenerated.compText1235', 'إعادة المحاولة'))}
                        </button>
                    </div>
                )}

                {/* Empty State */}
                {!loading && !error && courses.length === 0 && (
                    <div className="max-w-md mx-auto text-center py-16 px-6 bg-white rounded-3xl border border-slate-200/90 shadow-sm">
                        <div className="w-16 h-16 rounded-2xl bg-amber-50 text-amber-600 flex items-center justify-center mx-auto mb-4">
                            <BookOpen className="w-8 h-8" />
                        </div>
                        <h3 className="text-lg font-bold text-slate-800 mb-2">
                            {isArabic ? t('autoGenerated.compText1236', 'لا توجد دورات مميزة في هذا النمط') : 'No featured courses in this category'}
                        </h3>
                        <p className="text-sm text-slate-500 mb-6">
                            {isArabic ? t('autoGenerated.compText1237', 'جرّب استعراض جميع الدورات أو تصفية تصنيف آخر') : 'Try selecting all courses or other course types'}
                        </p>
                        <button
                            onClick={() => setCourseType('')}
                            className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl font-bold text-sm text-white bg-primary-600 hover:bg-primary-700 shadow-md shadow-primary-500/20 transition-all"
                        >
                            <span>{isArabic ? t('autoGenerated.compText1238', 'عرض جميع الدورات') : 'View All Courses'}</span>
                        </button>
                    </div>
                )}

                {/* Case 1: Single Featured Course -> Spectacular VIP Spotlight Showcase */}
                {!loading && !error && courses.length === 1 && (() => {
                    const course = courses[0];
                    const coursePrice = course.displayPrice || course.price || 0;
                    const originalPrice = course.originalPrice;
                    const hasDiscount = originalPrice && originalPrice > coursePrice;
                    const discountPercent = hasDiscount
                        ? Math.round(((originalPrice - coursePrice) / originalPrice) * 100)
                        : 0;

                    const isUserEnrolled = user && Boolean(enrollmentStatuses[course._id]);
                    const isUserInstructor = user && Boolean(enrollmentStatuses[course._id]?.isInstructor);
                    const courseTypeBadge = getCourseTypeBadge(course.courseType);

                    const instructorName = course.instructor
                        ? `${course.instructor.firstName || ''} ${course.instructor.lastName || ''}`.trim()
                        : (isArabic ? t('autoGenerated.compText1239', 'أكاديمية AEC') : 'AEC Academy');

                    const categoryPath = localizeCategoryPath(course.category, course.subCategory);

                    return (
                        <div className="max-w-5xl mx-auto">
                            <div
                                onClick={() => handleCourseClick(course._id)}
                                className="group relative rounded-3xl bg-white border border-slate-200/90 shadow-xl hover:shadow-2xl hover:border-primary-400 transition-all duration-300 overflow-hidden cursor-pointer"
                            >
                                {/* Top Accent Gradient Line */}
                                <div className="h-1.5 w-full bg-gradient-to-r from-amber-500 via-primary-600 to-amber-500" />

                                <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 p-6 sm:p-8 lg:p-10 items-center">
                                    
                                    {/* Thumbnail / Media Column */}
                                    <div className="lg:col-span-5 relative">
                                        <div className="relative aspect-[16/10] lg:aspect-[4/3] rounded-2xl overflow-hidden bg-slate-100 shadow-md group-hover:shadow-lg transition-shadow">
                                            <img
                                                src={course.thumbnail || '/api/placeholder/400/300'}
                                                alt={course.title}
                                                className="w-full h-full object-cover transition-transform duration-700 ease-out group-hover:scale-105"
                                            />

                                            {/* Subtle Vignette Gradient */}
                                            <div className="absolute inset-0 bg-gradient-to-t from-slate-950/70 via-transparent to-black/25 pointer-events-none" />

                                            {/* Floating VIP Flame Badge */}
                                            <div className="absolute top-3 start-3 z-10 flex items-center gap-2">
                                                <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-lg text-xs font-black text-white bg-gradient-to-r from-orange-500 to-red-600 shadow-lg shadow-orange-500/30">
                                                    <Flame className="w-3.5 h-3.5 fill-current" />
                                                    <span>{isArabic ? t('autoGenerated.compText1240', 'برنامج معتمد وحصري') : 'Exclusive Program'}</span>
                                                </span>
                                            </div>

                                            {/* Floating Level Badge */}
                                            <div className="absolute top-3 end-3 z-10">
                                                <span className="inline-flex items-center px-2.5 py-1 rounded-lg text-xs font-bold bg-white/95 text-slate-800 backdrop-blur-md shadow-md">
                                                    {getCourseLevelLabel(course.courseLevel)}
                                                </span>
                                            </div>

                                            {/* Bottom Discount Tag */}
                                            {hasDiscount && user && (
                                                <div className="absolute bottom-3 start-3 z-10">
                                                    <span className="inline-flex items-center px-2.5 py-1 rounded-md text-xs font-black bg-rose-500 text-white shadow-md">
                                                        {isArabic ? `خصم حصري ${discountPercent}%` : `${discountPercent}% OFF`}
                                                    </span>
                                                </div>
                                            )}
                                        </div>
                                    </div>

                                    {/* Content Column */}
                                    <div className="lg:col-span-7 flex flex-col justify-between space-y-5">
                                        
                                        <div>
                                            {/* Category Tag */}
                                            {categoryPath && (
                                                <div className="mb-2">
                                                    <span className="inline-flex items-center gap-1.5 text-xs font-bold text-primary-700 bg-primary-50 border border-primary-200/80 px-3 py-1 rounded-lg">
                                                        <Tag className="w-3.5 h-3.5 text-primary-600" />
                                                        <span>{categoryPath}</span>
                                                    </span>
                                                </div>
                                            )}

                                            {/* Course Title */}
                                            <h3 className="text-xl sm:text-2xl lg:text-3xl font-black text-slate-900 group-hover:text-primary-600 transition-colors leading-snug mb-3">
                                                {course.title}
                                            </h3>

                                            {/* Instructor */}
                                            <div className="flex items-center gap-2.5 mb-4">
                                                <img
                                                    src={course.instructor?.photo || '/api/placeholder/32/32'}
                                                    alt={instructorName}
                                                    className="w-7 h-7 rounded-full object-cover ring-2 ring-primary-100 shrink-0"
                                                />
                                                <span className="text-sm font-semibold text-slate-700">
                                                    {instructorName}
                                                </span>
                                                <span className="text-slate-300">•</span>
                                                <span className="text-xs text-slate-500 font-medium">
                                                    {isArabic ? t('autoGenerated.compText1241', 'مدرب معتمد بالأكاديمية') : 'Certified Academy Instructor'}
                                                </span>
                                            </div>

                                            {/* 4-Column Key Metrics Strip */}
                                            <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 py-3 px-4 rounded-2xl bg-slate-50 border border-slate-100 text-center">
                                                {/* Rating */}
                                                <div className="flex flex-col items-center justify-center">
                                                    <div className="flex items-center gap-1 text-sm font-black text-slate-900">
                                                        <Star className="w-4 h-4 text-amber-500 fill-amber-500" />
                                                        <span>{course.averageRating ? course.averageRating.toFixed(1) : '5.0'}</span>
                                                    </div>
                                                    <span className="text-[11px] text-slate-400 font-medium">
                                                        ({course.reviewCount || 12} {isArabic ? t('autoGenerated.compText1242', 'تقييم') : 'reviews'})
                                                    </span>
                                                </div>

                                                {/* Duration */}
                                                <div className="flex flex-col items-center justify-center sm:border-x border-slate-200/60">
                                                    <div className="flex items-center gap-1 text-sm font-black text-slate-900">
                                                        <Clock className="w-4 h-4 text-primary-500" />
                                                        <span>{formatDuration(course.duration)}</span>
                                                    </div>
                                                    <span className="text-[11px] text-slate-400 font-medium">
                                                        {isArabic ? t('autoGenerated.compText1243', 'المدة الإجمالية') : 'Duration'}
                                                    </span>
                                                </div>

                                                {/* Students */}
                                                <div className="flex flex-col items-center justify-center">
                                                    <div className="flex items-center gap-1 text-sm font-black text-slate-900">
                                                        <Users className="w-4 h-4 text-emerald-500" />
                                                        <span>{course.enrollmentCount || 48}</span>
                                                    </div>
                                                    <span className="text-[11px] text-slate-400 font-medium">
                                                        {isArabic ? t('autoGenerated.compText1244', 'طالب مسجل') : 'Enrolled'}
                                                    </span>
                                                </div>

                                                {/* Accreditation */}
                                                <div className="flex flex-col items-center justify-center sm:border-s border-slate-200/60">
                                                    <div className="flex items-center gap-1 text-sm font-black text-slate-900">
                                                        <Award className="w-4 h-4 text-amber-600" />
                                                        <span>100%</span>
                                                    </div>
                                                    <span className="text-[11px] text-slate-400 font-medium">
                                                        {isArabic ? t('autoGenerated.compText1245', 'شهادة معتمدة') : 'Accredited'}
                                                    </span>
                                                </div>
                                            </div>
                                        </div>

                                        {/* Pricing & Action Area */}
                                        <div className="border-t border-slate-100 pt-5">
                                            <div className="flex flex-wrap items-center justify-between gap-4">
                                                
                                                {/* Price */}
                                                <div>
                                                    {user ? (
                                                        <div>
                                                            <div className="flex items-baseline gap-2 flex-wrap">
                                                                <span className="text-2xl sm:text-3xl font-black text-slate-900">
                                                                    {formatPrice(coursePrice)}
                                                                </span>
                                                                {hasDiscount && (
                                                                    <span className="text-sm text-slate-400 line-through">
                                                                        {formatPrice(originalPrice)}
                                                                    </span>
                                                                )}
                                                            </div>
                                                            <span className="text-xs text-emerald-600 font-bold block mt-0.5">
                                                                {isArabic ? t('autoGenerated.compText1246', 'شامل الرسوم والشهادة المعتمدة') : 'Includes certification'}
                                                            </span>
                                                        </div>
                                                    ) : (
                                                        <Link
                                                            to="/login"
                                                            onClick={(e) => e.stopPropagation()}
                                                            className="inline-flex items-center gap-2 px-3.5 py-2 rounded-xl text-xs font-bold text-primary-700 bg-primary-50 hover:bg-primary-100 border border-primary-200 transition-colors"
                                                        >
                                                            <Lock className="w-3.5 h-3.5 text-primary-600" />
                                                            <span>{t('course.card.loginToViewPrice', t('autoGenerated.compText1247', 'سجّل لمعرفة السعر'))}</span>
                                                        </Link>
                                                    )}
                                                </div>

                                                {/* CTA Buttons */}
                                                <div className="flex items-center gap-3">
                                                    {isUserInstructor ? (
                                                        <button
                                                            onClick={(e) => {
                                                                e.stopPropagation();
                                                                navigate(`/instructor/courses/${course._id}/edit`);
                                                            }}
                                                            className="px-6 py-3 rounded-xl font-bold text-sm text-white bg-purple-600 hover:bg-purple-700 shadow-md shadow-purple-500/25 transition-all"
                                                        >
                                                            {t('course.card.actions.manageCourse', t('autoGenerated.compText1248', 'إدارة الدورة'))}
                                                        </button>
                                                    ) : isUserEnrolled ? (
                                                        <button
                                                            onClick={(e) => handleContinueCourse(e, course._id)}
                                                            className="inline-flex items-center gap-2 px-6 py-3.5 rounded-xl font-bold text-sm text-white bg-emerald-600 hover:bg-emerald-700 shadow-lg shadow-emerald-500/25 transition-all"
                                                        >
                                                            <Play className="w-4 h-4 fill-current" />
                                                            <span>{t('course.card.actions.continueCourse', t('autoGenerated.compText1249', 'متابعة التعلم'))}</span>
                                                        </button>
                                                    ) : (
                                                        <>
                                                            <button
                                                                onClick={(e) => handleAddToCart(e, course)}
                                                                className={`p-3.5 rounded-xl border transition-all duration-200 flex items-center justify-center ${
                                                                    isInCart(course._id)
                                                                        ? 'bg-primary-50 border-primary-300 text-primary-600'
                                                                        : 'bg-slate-100 hover:bg-primary-50 border-slate-200/80 hover:border-primary-200 text-slate-700 hover:text-primary-600'
                                                                }`}
                                                                title={isInCart(course._id) ? t('course.toast.alreadyInCart', t('autoGenerated.compText1250', 'في السلة')) : t('course.card.actions.addToCart', t('autoGenerated.compText1251', 'إضافة للسلة'))}
                                                                aria-label={t('course.card.actions.addToCart', 'Add to Cart')}
                                                            >
                                                                <ShoppingCart className="w-5 h-5" />
                                                            </button>

                                                            <button
                                                                onClick={(e) => handleEnrollClick(e, course)}
                                                                className="inline-flex items-center gap-2 px-7 py-3.5 rounded-xl font-bold text-sm sm:text-base text-white bg-primary-600 hover:bg-primary-700 shadow-lg shadow-primary-500/25 transition-all transform hover:-translate-y-0.5 active:translate-y-0"
                                                            >
                                                                <span>{t('course.card.actions.enrollNow', t('autoGenerated.compText1252', 'سجّل الآن في البرنامج'))}</span>
                                                                <DirectionArrow className="w-4 h-4" />
                                                            </button>
                                                        </>
                                                    )}
                                                </div>

                                            </div>
                                        </div>

                                    </div>

                                </div>
                            </div>
                        </div>
                    );
                })()}

                {/* Case 2: Multiple Featured Courses -> Executive Carousel */}
                {!loading && !error && courses.length > 1 && (
                    <div
                        className="relative"
                        onMouseEnter={() => setIsHovered(true)}
                        onMouseLeave={() => setIsHovered(false)}
                    >
                        {/* Carousel Navigation Arrows */}
                        {courses.length > slidesPerView && (
                            <>
                                <button
                                    onClick={prevSlide}
                                    className="hidden sm:flex absolute start-0 top-1/2 -translate-y-1/2 z-20 w-11 h-11 rounded-full bg-white/95 border border-slate-200 shadow-xl text-slate-700 hover:bg-primary-600 hover:text-white hover:border-primary-600 transition-all duration-200 items-center justify-center -ms-5 backdrop-blur-sm"
                                    aria-label={t('home.featured.ariaPrevious', t('autoGenerated.compText1253', 'السابق'))}
                                >
                                    <BackwardChevron className="w-5 h-5" />
                                </button>
                                <button
                                    onClick={nextSlide}
                                    className="hidden sm:flex absolute end-0 top-1/2 -translate-y-1/2 z-20 w-11 h-11 rounded-full bg-white/95 border border-slate-200 shadow-xl text-slate-700 hover:bg-primary-600 hover:text-white hover:border-primary-600 transition-all duration-200 items-center justify-center -me-5 backdrop-blur-sm"
                                    aria-label={t('home.featured.ariaNext', t('autoGenerated.compText1254', 'التالي'))}
                                >
                                    <ForwardChevron className="w-5 h-5" />
                                </button>
                            </>
                        )}

                        {/* Carousel Track Container */}
                        <div className="overflow-hidden rounded-2xl py-3">
                            <motion.div
                                className="flex transition-transform duration-500 ease-out will-change-transform"
                                style={{
                                    transform: `translate3d(${isArabic ? '' : '-'}${currentSlide * (100 / slidesPerView)}%, 0, 0)`
                                }}
                            >
                                {courses.map((course, index) => {
                                    const coursePrice = course.displayPrice || course.price || 0;
                                    const originalPrice = course.originalPrice;
                                    const hasDiscount = originalPrice && originalPrice > coursePrice;
                                    const discountPercent = hasDiscount
                                        ? Math.round(((originalPrice - coursePrice) / originalPrice) * 100)
                                        : 0;

                                    const isUserEnrolled = user && Boolean(enrollmentStatuses[course._id]);
                                    const isUserInstructor = user && Boolean(enrollmentStatuses[course._id]?.isInstructor);
                                    const courseTypeBadge = getCourseTypeBadge(course.courseType);

                                    const instructorName = course.instructor
                                        ? `${course.instructor.firstName || ''} ${course.instructor.lastName || ''}`.trim()
                                        : (isArabic ? t('autoGenerated.compText1255', 'أكاديمية AEC') : 'AEC Academy');

                                    const categoryPath = localizeCategoryPath(course.category, course.subCategory);

                                    return (
                                        <div
                                            key={course._id}
                                            className="shrink-0 px-3"
                                            style={{ width: `${100 / slidesPerView}%` }}
                                        >
                                            <div
                                                onClick={() => handleCourseClick(course._id)}
                                                className="group/card bg-white rounded-2xl border border-slate-200/90 shadow-md hover:shadow-2xl hover:border-primary-400 hover:-translate-y-2 transition-all duration-300 flex flex-col h-full overflow-hidden cursor-pointer relative"
                                            >
                                                {/* Top Accent Gradient Border on Hover */}
                                                <div className="h-1 w-full bg-gradient-to-r from-amber-500 via-primary-600 to-amber-500 opacity-0 group-hover/card:opacity-100 transition-opacity duration-300 absolute top-0 inset-x-0 z-20" />

                                                {/* Thumbnail Area */}
                                                <div className="relative w-full aspect-[16/10] overflow-hidden bg-slate-100 shrink-0">
                                                    <img
                                                        src={course.thumbnail || '/api/placeholder/400/250'}
                                                        alt={course.title}
                                                        loading="lazy"
                                                        className="w-full h-full object-cover transition-transform duration-700 ease-out group-hover/card:scale-108"
                                                    />

                                                    {/* Subtle Vignette Gradient */}
                                                    <div className="absolute inset-0 bg-gradient-to-t from-slate-950/70 via-transparent to-black/25 pointer-events-none" />

                                                    {/* Top Start: Level Badge & Course Type */}
                                                    <div className="absolute top-3 start-3 z-10 flex flex-wrap items-center gap-1.5">
                                                        <span className="inline-flex items-center px-2.5 py-1 rounded-lg text-xs font-bold bg-white/95 text-slate-800 backdrop-blur-md shadow-md">
                                                            {getCourseLevelLabel(course.courseLevel)}
                                                        </span>

                                                        {courseTypeBadge && (
                                                            <span className={`inline-flex items-center gap-1 px-2.5 py-1 rounded-lg text-xs font-bold backdrop-blur-md border shadow-md ${courseTypeBadge.color}`}>
                                                                <span className={`w-1.5 h-1.5 rounded-full ${courseTypeBadge.dot} ${course.courseType === 'online' ? 'animate-ping' : ''}`} />
                                                                <span>{courseTypeBadge.label}</span>
                                                            </span>
                                                        )}
                                                    </div>

                                                    {/* Top End: Featured Flame Badge */}
                                                    <div className="absolute top-3 end-3 z-10">
                                                        <span className="inline-flex items-center gap-1 px-3 py-1 rounded-lg text-xs font-black text-white bg-gradient-to-r from-orange-500 to-red-600 shadow-md">
                                                            <Flame className="w-3.5 h-3.5 fill-current" />
                                                            <span>{t('home.featured.featuredBadge', t('autoGenerated.compText1256', 'مميز'))}</span>
                                                        </span>
                                                    </div>

                                                    {/* Bottom Overlay: Discount Tag or Lock */}
                                                    <div className="absolute bottom-3 start-3 end-3 z-10 flex items-center justify-between">
                                                        {hasDiscount && user ? (
                                                            <span className="inline-flex items-center px-2.5 py-0.5 rounded-md text-xs font-black bg-rose-500 text-white shadow-md">
                                                                {isArabic ? `خصم ${discountPercent}%` : `${discountPercent}% OFF`}
                                                            </span>
                                                        ) : <div />}

                                                        {!user && (
                                                            <Link
                                                                to="/login"
                                                                onClick={(e) => e.stopPropagation()}
                                                                className="inline-flex items-center gap-1.5 px-3 py-1 rounded-lg text-xs font-bold text-white bg-slate-900/85 backdrop-blur-md hover:bg-primary-600 transition-colors shadow-sm ms-auto"
                                                            >
                                                                <Lock className="w-3 h-3 text-amber-300" />
                                                                <span>{t('course.card.loginToViewPrice', t('autoGenerated.compText1257', 'سجّل لمعرفة السعر'))}</span>
                                                            </Link>
                                                        )}
                                                    </div>
                                                </div>

                                                {/* Card Body */}
                                                <div className="p-5 sm:p-6 flex flex-col flex-1 justify-between">
                                                    <div>
                                                        {/* Category Tag */}
                                                        {categoryPath && (
                                                            <div className="mb-2">
                                                                <span className="inline-flex items-center gap-1 text-[11px] font-bold text-primary-700 bg-primary-50 border border-primary-100/80 px-2.5 py-0.5 rounded-md line-clamp-1 max-w-full">
                                                                    <Tag className="w-3 h-3 text-primary-500 shrink-0" />
                                                                    <span className="truncate">{categoryPath}</span>
                                                                </span>
                                                            </div>
                                                        )}

                                                        {/* Course Title */}
                                                        <h3 className="text-base sm:text-lg font-black text-slate-900 group-hover/card:text-primary-600 transition-colors line-clamp-2 leading-snug mb-3 min-h-[2.85rem]">
                                                            {course.title}
                                                        </h3>

                                                        {/* Instructor Row */}
                                                        <div className="flex items-center gap-2 mb-4">
                                                            <img
                                                                src={course.instructor?.photo || '/api/placeholder/32/32'}
                                                                alt={instructorName}
                                                                className="w-6 h-6 rounded-full object-cover ring-1 ring-slate-200 shrink-0"
                                                            />
                                                            <span className="text-xs font-semibold text-slate-600 truncate">
                                                                {instructorName}
                                                            </span>
                                                        </div>

                                                        {/* Key Metrics Strip */}
                                                        <div className="grid grid-cols-3 gap-2 py-2.5 px-3 rounded-xl bg-slate-50 border border-slate-100 mb-4 text-center">
                                                            <div className="flex flex-col items-center justify-center">
                                                                <div className="flex items-center gap-1 text-xs font-black text-slate-800">
                                                                    <Star className="w-3.5 h-3.5 text-amber-500 fill-amber-500" />
                                                                    <span>{course.averageRating ? course.averageRating.toFixed(1) : '5.0'}</span>
                                                                </div>
                                                                <span className="text-[10px] text-slate-400 font-medium mt-0.5">
                                                                    ({course.reviewCount || 0} {isArabic ? t('autoGenerated.compText1258', 'تقييم') : 'reviews'})
                                                                </span>
                                                            </div>

                                                            <div className="flex flex-col items-center justify-center border-x border-slate-200/60">
                                                                <div className="flex items-center gap-1 text-xs font-black text-slate-800">
                                                                    <Clock className="w-3.5 h-3.5 text-primary-500" />
                                                                    <span>{formatDuration(course.duration)}</span>
                                                                </div>
                                                                <span className="text-[10px] text-slate-400 font-medium mt-0.5">
                                                                    {isArabic ? t('autoGenerated.compText1259', 'المدة الإجمالية') : 'Duration'}
                                                                </span>
                                                            </div>

                                                            <div className="flex flex-col items-center justify-center">
                                                                <div className="flex items-center gap-1 text-xs font-black text-slate-800">
                                                                    <Users className="w-3.5 h-3.5 text-emerald-500" />
                                                                    <span>{course.enrollmentCount || 0}</span>
                                                                </div>
                                                                <span className="text-[10px] text-slate-400 font-medium mt-0.5">
                                                                    {isArabic ? t('autoGenerated.compText1260', 'طالب مسجل') : 'Students'}
                                                                </span>
                                                            </div>
                                                        </div>
                                                    </div>

                                                    {/* Card Footer: Pricing & Action Buttons */}
                                                    <div className="border-t border-slate-100 pt-4 mt-auto">
                                                        <div className="flex items-center justify-between gap-3">
                                                            {/* Price */}
                                                            <div>
                                                                {user ? (
                                                                    <div>
                                                                        <div className="flex items-baseline gap-1.5 flex-wrap">
                                                                            <span className="text-lg sm:text-xl font-black text-slate-900">
                                                                                {formatPrice(coursePrice)}
                                                                            </span>
                                                                            {hasDiscount && (
                                                                                <span className="text-xs text-slate-400 line-through">
                                                                                    {formatPrice(originalPrice)}
                                                                                </span>
                                                                            )}
                                                                        </div>
                                                                        <span className="text-[10px] text-emerald-600 font-bold block">
                                                                            {isArabic ? t('autoGenerated.compText1261', 'شامل الشهادة') : 'Certified'}
                                                                        </span>
                                                                    </div>
                                                                ) : (
                                                                    <div className="text-xs font-bold text-primary-600">
                                                                        {isArabic ? t('autoGenerated.compText1262', 'خصومات خاصة') : 'Special rates'}
                                                                    </div>
                                                                )}
                                                            </div>

                                                            {/* Buttons */}
                                                            <div className="flex items-center gap-2">
                                                                {isUserInstructor ? (
                                                                    <button
                                                                        onClick={(e) => {
                                                                            e.stopPropagation();
                                                                            navigate(`/instructor/courses/${course._id}/edit`);
                                                                        }}
                                                                        className="px-4 py-2.5 rounded-xl font-bold text-xs text-white bg-purple-600 hover:bg-purple-700 shadow-md transition-all"
                                                                    >
                                                                        {t('course.card.actions.manageCourse', t('autoGenerated.compText1263', 'إدارة'))}
                                                                    </button>
                                                                ) : isUserEnrolled ? (
                                                                    <button
                                                                        onClick={(e) => handleContinueCourse(e, course._id)}
                                                                        className="inline-flex items-center gap-1.5 px-4 py-2.5 rounded-xl font-bold text-xs text-white bg-emerald-600 hover:bg-emerald-700 shadow-md transition-all"
                                                                    >
                                                                        <Play className="w-3 h-3 fill-current" />
                                                                        <span>{t('course.card.actions.continueCourse', t('autoGenerated.compText1264', 'متابعة'))}</span>
                                                                    </button>
                                                                ) : (
                                                                    <>
                                                                        <button
                                                                            onClick={(e) => handleAddToCart(e, course)}
                                                                            className={`p-2.5 rounded-xl border transition-all duration-200 flex items-center justify-center ${
                                                                                isInCart(course._id)
                                                                                    ? 'bg-primary-50 border-primary-300 text-primary-600'
                                                                                    : 'bg-slate-100 hover:bg-primary-50 border-slate-200/80 hover:border-primary-200 text-slate-700 hover:text-primary-600'
                                                                            }`}
                                                                            title={isInCart(course._id) ? t('course.toast.alreadyInCart', t('autoGenerated.compText1265', 'في السلة')) : t('course.card.actions.addToCart', t('autoGenerated.compText1266', 'إضافة للسلة'))}
                                                                            aria-label={t('course.card.actions.addToCart', 'Add to Cart')}
                                                                        >
                                                                            <ShoppingCart className="w-4 h-4" />
                                                                        </button>

                                                                        <button
                                                                            onClick={(e) => handleEnrollClick(e, course)}
                                                                            className="inline-flex items-center gap-1 px-3.5 py-2.5 rounded-xl font-bold text-xs text-white bg-primary-600 hover:bg-primary-700 shadow-md shadow-primary-500/25 transition-all transform hover:-translate-y-0.5 active:translate-y-0"
                                                                        >
                                                                            <span>{t('course.card.actions.enrollNow', t('autoGenerated.compText1267', 'سجّل'))}</span>
                                                                            <DirectionArrow className="w-3.5 h-3.5" />
                                                                        </button>
                                                                    </>
                                                                )}
                                                            </div>
                                                        </div>
                                                    </div>

                                                </div>
                                            </div>
                                        </div>
                                    );
                                })}
                            </motion.div>
                        </div>

                        {/* Dots Indicators */}
                        {courses.length > slidesPerView && (
                            <div className="flex justify-center items-center gap-1.5 mt-8">
                                {Array.from({ length: maxSlide + 1 }).map((_, index) => (
                                    <button
                                        key={index}
                                        onClick={() => goToSlide(index)}
                                        className={`h-2 rounded-full transition-all duration-300 ${
                                            currentSlide === index
                                                ? 'w-7 bg-primary-600 shadow-sm'
                                                : 'w-2 bg-slate-200 hover:bg-slate-300'
                                        }`}
                                        aria-label={t('home.featured.ariaGoToSlide', { index: index + 1 })}
                                    />
                                ))}
                            </div>
                        )}
                    </div>
                )}

                {/* Bottom Browse All Courses CTA Button */}
                <div className="text-center mt-12 sm:mt-16">
                    <button
                        onClick={() => navigate('/explore')}
                        className="inline-flex items-center gap-3 bg-gradient-to-r from-primary-600 via-primary-700 to-primary-600 hover:to-primary-700 text-white px-8 sm:px-10 py-3.5 sm:py-4 rounded-2xl font-bold text-base shadow-xl shadow-primary-500/25 hover:shadow-2xl hover:shadow-primary-500/35 transition-all duration-300 transform hover:-translate-y-0.5 active:translate-y-0 group"
                    >
                        <span>{t('common.browseAllCourses', t('autoGenerated.compText1268', 'تصفح جميع الدورات المتاحة'))}</span>
                        <DirectionArrow className="w-5 h-5 transform group-hover:translate-x-1 rtl:group-hover:-translate-x-1 transition-transform" />
                    </button>
                    <p className="text-slate-500 mt-3 text-xs sm:text-sm">
                        {isArabic
                            ? t('autoGenerated.compText1269', 'انضم إلى نخبة المتدربين واحصل على شهادات معتمدة تساند مسيرتك المهنية')
                            : 'Join elite learners and obtain accredited certifications to support your career'}
                    </p>
                </div>

            </div>
        </section>
    );
};

export default FeaturedCourses;