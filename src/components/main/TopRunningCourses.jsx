import React, { useState, useEffect, useMemo, useCallback } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { useTranslation } from 'react-i18next';
import { useNavigate, Link } from 'react-router-dom';
import {
    Star,
    Users,
    Clock,
    Tag,
    ShoppingCart,
    Eye,
    Play,
    Trophy,
    Sparkles,
    ArrowLeft,
    ArrowRight,
    Video,
    BookOpen,
    Lock,
    CheckCircle,
    Building,
    Calendar,
    Flame
} from 'lucide-react';
import { toast } from 'react-toastify';
import { courseService } from '../../services/new-api';
import { useCart } from '../../context/CartContext';
import { useAuth } from '../../context/AuthContext';
import { useCategoryLookup } from '../../context/CategoryLookupContext';
import api from '../../services/new-api';
import CourseTypeFilter from '../common/CourseTypeFilter';

const TopRunningCourses = () => {
    const { t, i18n } = useTranslation();
    const isArabic = i18n.language === 'ar';
    const navigate = useNavigate();

    const [courses, setCourses] = useState([]);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState(null);
    const [enrollmentStatuses, setEnrollmentStatuses] = useState({});
    const [courseType, setCourseType] = useState('');

    const { addToCart, isInCart } = useCart();
    const { user } = useAuth();
    const { localizeCategoryPath } = useCategoryLookup();

    useEffect(() => {
        fetchTopCourses();
    }, [courseType]);

    useEffect(() => {
        if (user && courses.length > 0) {
            checkEnrollmentStatuses();
        }
    }, [user, courses]);

    const fetchTopCourses = async () => {
        try {
            setLoading(true);
            setError(null);
            const response = await courseService.getTopRunningCourses(
                courseType ? { courseType } : {}
            );
            setCourses(response?.courses || []);
        } catch (err) {
            console.error('Error fetching top courses:', err);
            setError(t('home.topRunning.failedToLoad', t('autoGenerated.compText1337', 'تعذّر تحميل الدورات النشطة')));
        } finally {
            setLoading(false);
        }
    };

    const checkEnrollmentStatuses = async () => {
        try {
            const statuses = {};
            await Promise.all(
                courses.map(async (course) => {
                    try {
                        const response = await api.get(`/enrollment/status/${course._id}`);
                        statuses[course._id] = response.data;
                    } catch (err) {
                        if (err.response?.status === 404 || err.response?.status === 403) {
                            statuses[course._id] = null;
                        }
                    }
                })
            );
            setEnrollmentStatuses(statuses);
        } catch (err) {
            console.error('Error checking enrollment statuses:', err);
        }
    };

    const handleCourseClick = (courseId) => {
        navigate(`/course/${courseId}`);
    };

    const handleAddToCart = (e, course) => {
        e.stopPropagation();
        if (isInCart(course._id)) {
            toast.info(t('course.toast.alreadyInCart', t('autoGenerated.compText1338', 'الدورة موجودة بالفعل في السلة')));
        } else {
            addToCart(course);
            toast.success(t('course.toast.addedToCart', t('autoGenerated.compText1339', 'تمت إضافة الدورة إلى السلة')));
        }
    };

    const handleEnrollClick = (e, course) => {
        e.stopPropagation();
        if (!isInCart(course._id)) {
            addToCart(course);
        }
        navigate('/checkout');
    };

    const handleContinueCourse = (e, courseId) => {
        e.stopPropagation();
        navigate(`/course/${courseId}/study`);
    };

    const formatPrice = (price) => {
        if (price === 0) return t('course.card.price.free', t('autoGenerated.compText1340', 'مجاناً'));
        return t('course.card.price.sar', { amount: Number(price).toLocaleString() });
    };

    const formatDuration = (minutes) => {
        if (!minutes || minutes <= 0) return isArabic ? t('autoGenerated.compText1341', 'مرن') : 'Flexible';
        const hours = Math.floor(minutes / 60);
        const mins = minutes % 60;
        if (hours > 0 && mins > 0) {
            return isArabic ? `${hours} س و ${mins} د` : `${hours}h ${mins}m`;
        }
        if (hours > 0) {
            return isArabic ? `${hours} ساعة` : `${hours} hrs`;
        }
        return isArabic ? `${mins} دقيقة` : `${mins} mins`;
    };

    const getCourseLevelLabel = (level) => {
        switch (level) {
            case 'beginner':
                return isArabic ? t('autoGenerated.compText1342', 'مبتدئ') : 'Beginner';
            case 'intermediate':
                return isArabic ? t('autoGenerated.compText1343', 'متوسط') : 'Intermediate';
            case 'advanced':
                return isArabic ? t('autoGenerated.compText1344', 'متقدم') : 'Advanced';
            case 'all-levels':
            default:
                return isArabic ? t('autoGenerated.compText1345', 'جميع المستويات') : 'All Levels';
        }
    };

    const getCourseTypeBadge = (type) => {
        switch (type) {
            case 'online':
                return {
                    label: isArabic ? t('autoGenerated.compText1346', 'أونلاين مباشر') : 'Live Online',
                    icon: Video,
                    color: 'bg-emerald-50 text-emerald-700 border-emerald-200/80',
                    dot: 'bg-emerald-500'
                };
            case 'recorded':
                return {
                    label: isArabic ? t('autoGenerated.compText1347', 'مسجلة') : 'Recorded',
                    icon: Play,
                    color: 'bg-blue-50 text-blue-700 border-blue-200/80',
                    dot: 'bg-blue-500'
                };
            case 'in-person':
            case 'offline':
                return {
                    label: isArabic ? t('autoGenerated.compText1348', 'حضوري') : 'In-Person',
                    icon: Building,
                    color: 'bg-purple-50 text-purple-700 border-purple-200/80',
                    dot: 'bg-purple-500'
                };
            default:
                return null;
        }
    };

    // Direction-aware Icons
    const DirectionArrow = isArabic ? ArrowLeft : ArrowRight;

    return (
        <section
            className="py-14 sm:py-20 lg:py-24 bg-gradient-to-b from-slate-50/50 via-white to-slate-50/70 relative overflow-hidden font-arabic"
            dir={isArabic ? 'rtl' : 'ltr'}
        >
            {/* Background Ambient Lighting */}
            <div className="absolute top-1/4 start-1/10 w-[500px] h-[500px] bg-primary-500/5 rounded-full blur-[140px] pointer-events-none" />
            <div className="absolute bottom-1/4 end-1/10 w-[500px] h-[500px] bg-amber-500/5 rounded-full blur-[140px] pointer-events-none" />

            <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 relative z-10">

                {/* Section Header */}
                <div className="text-center max-w-3xl mx-auto mb-10 sm:mb-14">
                    <motion.div
                        initial={{ opacity: 0, y: -10 }}
                        whileInView={{ opacity: 1, y: 0 }}
                        viewport={{ once: true }}
                        className="inline-flex items-center gap-2 bg-gradient-to-r from-amber-50 via-amber-100/60 to-primary-50 border border-amber-200/70 text-amber-900 px-4 py-1.5 rounded-full text-xs sm:text-sm font-extrabold shadow-sm mb-4"
                    >
                        <Trophy className="w-4 h-4 text-amber-600" />
                        <span>{isArabic ? t('autoGenerated.compText1349', 'الدورات الأكثر طلباً وإقبالاً') : 'Most Popular & In-Demand Courses'}</span>
                    </motion.div>

                    <motion.h2
                        initial={{ opacity: 0, y: 15 }}
                        whileInView={{ opacity: 1, y: 0 }}
                        viewport={{ once: true }}
                        transition={{ delay: 0.1 }}
                        className="text-3xl sm:text-4xl lg:text-5xl font-black text-slate-900 tracking-tight leading-tight mb-4"
                    >
                        {t('home.topRunning.title', t('autoGenerated.compText1350', 'أفضل 10 دورات نشطة'))}
                    </motion.h2>

                    <motion.p
                        initial={{ opacity: 0, y: 15 }}
                        whileInView={{ opacity: 1, y: 0 }}
                        viewport={{ once: true }}
                        transition={{ delay: 0.2 }}
                        className="text-slate-600 text-sm sm:text-base lg:text-lg leading-relaxed max-w-2xl mx-auto"
                    >
                        {t('home.topRunning.subtitle', t('autoGenerated.compText1351', 'اكتشف الدورات التدريبية المعتمدة الأكثر إقبالاً من الطلاب والمهنيين لتطوير مسارهم الوظيفي'))}
                    </motion.p>

                    {/* Course Type Filter Bar */}
                    <motion.div
                        initial={{ opacity: 0, y: 15 }}
                        whileInView={{ opacity: 1, y: 0 }}
                        viewport={{ once: true }}
                        transition={{ delay: 0.3 }}
                        className="mt-8 flex justify-center"
                    >
                        <CourseTypeFilter
                            value={courseType}
                            onChange={setCourseType}
                            showLabel={false}
                            align="center"
                            className="w-full max-w-xl mx-auto"
                        />
                    </motion.div>
                </div>

                {/* Loading Skeleton */}
                {loading && (
                    <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6 sm:gap-8">
                        {[1, 2, 3, 4, 5, 6].map((n) => (
                            <div
                                key={n}
                                className="bg-white rounded-2xl border border-slate-200/80 p-4 shadow-sm space-y-4 animate-pulse"
                            >
                                <div className="aspect-[16/10] bg-slate-200 rounded-xl" />
                                <div className="h-4 w-28 bg-slate-200 rounded" />
                                <div className="h-6 w-5/6 bg-slate-200 rounded" />
                                <div className="h-12 bg-slate-100 rounded-xl" />
                                <div className="flex justify-between items-center pt-2">
                                    <div className="h-6 w-24 bg-slate-200 rounded" />
                                    <div className="h-9 w-24 bg-slate-200 rounded-lg" />
                                </div>
                            </div>
                        ))}
                    </div>
                )}

                {/* Error Banner */}
                {error && !loading && (
                    <div className="max-w-md mx-auto text-center p-6 bg-rose-50 border border-rose-200 rounded-2xl">
                        <p className="text-rose-700 font-bold mb-4">{error}</p>
                        <button
                            onClick={fetchTopCourses}
                            className="px-5 py-2.5 bg-primary-600 hover:bg-primary-700 text-white font-bold text-sm rounded-xl transition-colors shadow-md"
                        >
                            {t('common.tryAgain', t('autoGenerated.compText1352', 'إعادة المحاولة'))}
                        </button>
                    </div>
                )}

                {/* Empty State */}
                {!loading && !error && courses.length === 0 && (
                    <div className="max-w-md mx-auto text-center py-16 px-6 bg-white rounded-3xl border border-slate-200/90 shadow-sm">
                        <div className="w-16 h-16 rounded-2xl bg-primary-50 text-primary-600 flex items-center justify-center mx-auto mb-4">
                            <BookOpen className="w-8 h-8" />
                        </div>
                        <h3 className="text-lg font-bold text-slate-800 mb-2">
                            {isArabic ? t('autoGenerated.compText1353', 'لا توجد دورات حالياً في هذا النمط') : 'No courses found in this category'}
                        </h3>
                        <p className="text-sm text-slate-500 mb-6">
                            {isArabic ? t('autoGenerated.compText1354', 'جرّب تصفية جميع الدورات أو تصفح بقية الأنماط المتاحة') : 'Try selecting all courses or other course types'}
                        </p>
                        <button
                            onClick={() => setCourseType('')}
                            className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl font-bold text-sm text-white bg-primary-600 hover:bg-primary-700 shadow-md shadow-primary-500/20 transition-all"
                        >
                            <span>{isArabic ? t('autoGenerated.compText1355', 'عرض جميع الدورات') : 'View All Courses'}</span>
                        </button>
                    </div>
                )}

                {/* Courses Grid */}
                {!loading && !error && courses.length > 0 && (
                    <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6 sm:gap-8">
                        {courses.map((course, index) => {
                            const coursePrice = course.displayPrice || course.price || 0;
                            const originalPrice = course.originalPrice;
                            const hasDiscount = originalPrice && originalPrice > coursePrice;
                            const discountPercent = hasDiscount
                                ? Math.round(((originalPrice - coursePrice) / originalPrice) * 100)
                                : 0;

                            const isUserEnrolled = user && Boolean(enrollmentStatuses[course._id]);
                            const isUserInstructor = user && Boolean(enrollmentStatuses[course._id]?.isInstructor);
                            const courseTypeBadge = getCourseTypeBadge(course.courseType);

                            // Ranking badge metadata
                            const rank = index + 1;
                            const isTop1 = rank === 1;
                            const isTop3 = rank <= 3;

                            const instructorName = course.instructor
                                ? `${course.instructor.firstName || ''} ${course.instructor.lastName || ''}`.trim()
                                : (isArabic ? t('autoGenerated.compText1356', 'أكاديمية AEC') : 'AEC Academy');

                            const categoryPath = localizeCategoryPath(course.category, course.subCategory);

                            return (
                                <motion.div
                                    key={course._id}
                                    initial={{ opacity: 0, y: 20 }}
                                    whileInView={{ opacity: 1, y: 0 }}
                                    viewport={{ once: true }}
                                    transition={{ duration: 0.4, delay: (index % 3) * 0.1 }}
                                    onClick={() => handleCourseClick(course._id)}
                                    className="group/card bg-white rounded-2xl border border-slate-200/90 shadow-md hover:shadow-2xl hover:border-primary-400 hover:-translate-y-2 transition-all duration-300 flex flex-col h-full overflow-hidden cursor-pointer relative"
                                >
                                    {/* Top Accent Gradient Line on Hover */}
                                    <div className="h-1 w-full bg-gradient-to-r from-primary-600 via-secondary-500 to-primary-600 opacity-0 group-hover/card:opacity-100 transition-opacity duration-300 absolute top-0 inset-x-0 z-20" />

                                    {/* Thumbnail Area */}
                                    <div className="relative w-full aspect-[16/10] overflow-hidden bg-slate-100 shrink-0">
                                        <img
                                            src={course.thumbnail || '/api/placeholder/400/250'}
                                            alt={course.title}
                                            loading="lazy"
                                            className="w-full h-full object-cover transition-transform duration-700 ease-out group-hover/card:scale-108"
                                        />

                                        {/* Subtle Vignette Gradient for Readability */}
                                        <div className="absolute inset-0 bg-gradient-to-t from-slate-950/70 via-transparent to-black/25 pointer-events-none" />

                                        {/* Top Start: Level Badge & Course Type */}
                                        <div className="absolute top-3 start-3 z-10 flex flex-wrap items-center gap-1.5">
                                            <span className="inline-flex items-center px-2.5 py-1 rounded-lg text-xs font-bold bg-white/95 text-slate-800 backdrop-blur-md shadow-md">
                                                {getCourseLevelLabel(course.courseLevel)}
                                            </span>

                                            {courseTypeBadge && (
                                                <span className={`inline-flex items-center gap-1 px-2.5 py-1 rounded-lg text-xs font-bold backdrop-blur-md border shadow-md ${courseTypeBadge.color}`}>
                                                    <span className={`w-1.5 h-1.5 rounded-full ${courseTypeBadge.dot} ${course.courseType === 'online' ? 'animate-ping' : ''}`} />
                                                    <span>{courseTypeBadge.label}</span>
                                                </span>
                                            )}
                                        </div>

                                        {/* Top End: Ranking Badge */}
                                        <div className="absolute top-3 end-3 z-10">
                                            {isTop1 ? (
                                                <span className="inline-flex items-center gap-1 px-3 py-1 rounded-lg text-xs font-black text-white bg-gradient-to-r from-amber-500 to-amber-600 shadow-lg shadow-amber-500/30">
                                                    <Flame className="w-3.5 h-3.5 fill-current" />
                                                    <span>{t('autoGenerated.compText1357', '#1 الأكثر طلباً')}</span>
                                                </span>
                                            ) : isTop3 ? (
                                                <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg text-xs font-extrabold text-white bg-slate-900/85 backdrop-blur-md shadow-md">
                                                    <Trophy className="w-3 h-3 text-amber-400" />
                                                    <span>#{rank}</span>
                                                </span>
                                            ) : (
                                                <span className="inline-flex items-center px-2 py-0.5 rounded-md text-[11px] font-bold text-white/90 bg-slate-900/70 backdrop-blur-md">
                                                    #{rank}
                                                </span>
                                            )}
                                        </div>

                                        {/* Bottom Overlay: Discount Tag or Lock Hint */}
                                        <div className="absolute bottom-3 start-3 end-3 z-10 flex items-center justify-between">
                                            {hasDiscount && user ? (
                                                <span className="inline-flex items-center px-2.5 py-0.5 rounded-md text-xs font-black bg-rose-500 text-white shadow-md">
                                                    {isArabic ? `خصم ${discountPercent}%` : `${discountPercent}% OFF`}
                                                </span>
                                            ) : <div />}

                                            {!user && (
                                                <Link
                                                    to="/login"
                                                    onClick={(e) => e.stopPropagation()}
                                                    className="inline-flex items-center gap-1.5 px-3 py-1 rounded-lg text-xs font-bold text-white bg-slate-900/85 backdrop-blur-md hover:bg-primary-600 transition-colors shadow-sm ms-auto"
                                                >
                                                    <Lock className="w-3 h-3 text-amber-300" />
                                                    <span>{t('course.card.loginToViewPrice', t('autoGenerated.compText1358', 'سجّل لمعرفة السعر'))}</span>
                                                </Link>
                                            )}
                                        </div>
                                    </div>

                                    {/* Card Body */}
                                    <div className="p-5 sm:p-6 flex flex-col flex-1 justify-between">
                                        <div>
                                            {/* Category Tag */}
                                            {categoryPath && (
                                                <div className="mb-2">
                                                    <span className="inline-flex items-center gap-1 text-[11px] font-bold text-primary-700 bg-primary-50 border border-primary-100/80 px-2.5 py-0.5 rounded-md line-clamp-1 max-w-full">
                                                        <Tag className="w-3 h-3 text-primary-500 shrink-0" />
                                                        <span className="truncate">{categoryPath}</span>
                                                    </span>
                                                </div>
                                            )}

                                            {/* Course Title */}
                                            <h3 className="text-base sm:text-lg font-black text-slate-900 group-hover/card:text-primary-600 transition-colors line-clamp-2 leading-snug mb-3 min-h-[2.85rem]">
                                                {course.title}
                                            </h3>

                                            {/* Instructor Row */}
                                            <div className="flex items-center gap-2 mb-4">
                                                <img
                                                    src={course.instructor?.photo || '/api/placeholder/32/32'}
                                                    alt={instructorName}
                                                    className="w-6 h-6 rounded-full object-cover ring-1 ring-slate-200 shrink-0"
                                                />
                                                <span className="text-xs font-semibold text-slate-600 truncate">
                                                    {instructorName}
                                                </span>
                                            </div>

                                            {/* Key Metrics Strip (Rating, Duration, Students) */}
                                            <div className="grid grid-cols-3 gap-2 py-2.5 px-3 rounded-xl bg-slate-50 border border-slate-100 mb-4 text-center">
                                                {/* Rating */}
                                                <div className="flex flex-col items-center justify-center">
                                                    <div className="flex items-center gap-1 text-xs font-black text-slate-800">
                                                        <Star className="w-3.5 h-3.5 text-amber-500 fill-amber-500" />
                                                        <span>{course.averageRating ? course.averageRating.toFixed(1) : '5.0'}</span>
                                                    </div>
                                                    <span className="text-[10px] text-slate-400 font-medium mt-0.5">
                                                        ({course.reviewCount || 0} {isArabic ? t('autoGenerated.compText1359', 'تقييم') : 'reviews'})
                                                    </span>
                                                </div>

                                                {/* Duration */}
                                                <div className="flex flex-col items-center justify-center border-x border-slate-200/60">
                                                    <div className="flex items-center gap-1 text-xs font-black text-slate-800">
                                                        <Clock className="w-3.5 h-3.5 text-primary-500" />
                                                        <span>{formatDuration(course.duration)}</span>
                                                    </div>
                                                    <span className="text-[10px] text-slate-400 font-medium mt-0.5">
                                                        {isArabic ? t('autoGenerated.compText1360', 'المدة الإجمالية') : 'Duration'}
                                                    </span>
                                                </div>

                                                {/* Enrolled Students */}
                                                <div className="flex flex-col items-center justify-center">
                                                    <div className="flex items-center gap-1 text-xs font-black text-slate-800">
                                                        <Users className="w-3.5 h-3.5 text-emerald-500" />
                                                        <span>{course.enrollmentCount || 0}</span>
                                                    </div>
                                                    <span className="text-[10px] text-slate-400 font-medium mt-0.5">
                                                        {isArabic ? t('autoGenerated.compText1361', 'طالب مسجل') : 'Students'}
                                                    </span>
                                                </div>
                                            </div>
                                        </div>

                                        {/* Card Footer: Pricing & Action Buttons */}
                                        <div className="border-t border-slate-100 pt-4 mt-auto">
                                            <div className="flex items-center justify-between gap-3">
                                                
                                                {/* Price Container */}
                                                <div>
                                                    {user ? (
                                                        <div>
                                                            <div className="flex items-baseline gap-1.5 flex-wrap">
                                                                <span className="text-lg sm:text-xl font-black text-slate-900">
                                                                    {formatPrice(coursePrice)}
                                                                </span>
                                                                {hasDiscount && (
                                                                    <span className="text-xs text-slate-400 line-through">
                                                                        {formatPrice(originalPrice)}
                                                                    </span>
                                                                )}
                                                            </div>
                                                            <span className="text-[10px] text-emerald-600 font-bold block">
                                                                {isArabic ? t('autoGenerated.compText1362', 'شامل الشهادة والضريبة') : 'Includes Certificate'}
                                                            </span>
                                                        </div>
                                                    ) : (
                                                        <div className="text-xs font-bold text-primary-600">
                                                            {isArabic ? t('autoGenerated.compText1363', 'خصومات خاصة للأعضاء') : 'Member discounts'}
                                                        </div>
                                                    )}
                                                </div>

                                                {/* Action Buttons */}
                                                <div className="flex items-center gap-2">
                                                    {isUserInstructor ? (
                                                        <button
                                                            onClick={(e) => {
                                                                e.stopPropagation();
                                                                navigate(`/instructor/courses/${course._id}/edit`);
                                                            }}
                                                            className="px-4 py-2.5 rounded-xl font-bold text-xs sm:text-sm text-white bg-purple-600 hover:bg-purple-700 shadow-md shadow-purple-500/20 transition-all"
                                                        >
                                                            {t('course.card.actions.manageCourse', t('autoGenerated.compText1364', 'إدارة الدورة'))}
                                                        </button>
                                                    ) : isUserEnrolled ? (
                                                        <button
                                                            onClick={(e) => handleContinueCourse(e, course._id)}
                                                            className="inline-flex items-center gap-1.5 px-4 py-2.5 rounded-xl font-bold text-xs sm:text-sm text-white bg-emerald-600 hover:bg-emerald-700 shadow-md shadow-emerald-500/20 transition-all"
                                                        >
                                                            <Play className="w-3.5 h-3.5 fill-current" />
                                                            <span>{t('course.card.actions.continueCourse', t('autoGenerated.compText1365', 'متابعة التعلم'))}</span>
                                                        </button>
                                                    ) : (
                                                        <>
                                                            {/* Add To Cart Icon Button */}
                                                            <button
                                                                onClick={(e) => handleAddToCart(e, course)}
                                                                className={`p-2.5 rounded-xl border transition-all duration-200 flex items-center justify-center ${
                                                                    isInCart(course._id)
                                                                        ? 'bg-primary-50 border-primary-300 text-primary-600'
                                                                        : 'bg-slate-100 hover:bg-primary-50 border-slate-200/80 hover:border-primary-200 text-slate-700 hover:text-primary-600'
                                                                }`}
                                                                title={isInCart(course._id) ? t('course.toast.alreadyInCart', t('autoGenerated.compText1366', 'في السلة')) : t('course.card.actions.addToCart', t('autoGenerated.compText1367', 'إضافة للسلة'))}
                                                                aria-label={t('course.card.actions.addToCart', 'Add to Cart')}
                                                            >
                                                                <ShoppingCart className="w-4 h-4" />
                                                            </button>

                                                            {/* Direct Enroll / Explore Button */}
                                                            <button
                                                                onClick={(e) => handleEnrollClick(e, course)}
                                                                className="inline-flex items-center gap-1.5 px-3.5 sm:px-4 py-2.5 rounded-xl font-bold text-xs sm:text-sm text-white bg-primary-600 hover:bg-primary-700 shadow-md shadow-primary-500/25 transition-all transform hover:-translate-y-0.5 active:translate-y-0"
                                                            >
                                                                <span>{t('course.card.actions.enrollNow', t('autoGenerated.compText1368', 'سجّل الآن'))}</span>
                                                                <DirectionArrow className="w-3.5 h-3.5" />
                                                            </button>
                                                        </>
                                                    )}
                                                </div>

                                            </div>
                                        </div>

                                    </div>
                                </motion.div>
                            );
                        })}
                    </div>
                )}

                {/* Bottom Browse All CTA Button */}
                <div className="text-center mt-12 sm:mt-16">
                    <button
                        onClick={() => navigate('/explore')}
                        className="inline-flex items-center gap-3 bg-gradient-to-r from-primary-600 via-primary-700 to-primary-600 hover:to-primary-700 text-white px-8 sm:px-10 py-3.5 sm:py-4 rounded-2xl font-bold text-base shadow-xl shadow-primary-500/25 hover:shadow-2xl hover:shadow-primary-500/35 transition-all duration-300 transform hover:-translate-y-0.5 active:translate-y-0 group"
                    >
                        <span>{t('common.browseAllCourses', t('autoGenerated.compText1369', 'تصفح جميع الدورات المتاحة'))}</span>
                        <DirectionArrow className="w-5 h-5 transform group-hover:translate-x-1 rtl:group-hover:-translate-x-1 transition-transform" />
                    </button>
                    <p className="text-slate-500 mt-3 text-xs sm:text-sm">
                        {isArabic
                            ? t('autoGenerated.compText1370', 'انضم لأكثر من 10,000+ متدرب ناجح وانطلق نحو مستقبلك المهني بثقة')
                            : 'Join over 10,000+ successful learners and advance your career with confidence'}
                    </p>
                </div>

            </div>
        </section>
    );
};

