import React, { useState, useEffect, useMemo } from 'react';
import { useParams, Link } from 'react-router-dom';
import { motion, AnimatePresence } from 'framer-motion';
import { useTranslation } from 'react-i18next';
import { useLanguage } from '../hooks/useLanguage';
import api from '../services/new-api';
import CourseCard from '../components/CourseCard';
import {
    Search,
    X,
    BookOpen,
    Layers,
    Award,
    GraduationCap,
    ArrowRight,
    ArrowLeft,
    ChevronRight,
    ChevronLeft,
    ChevronDown,
    ChevronUp,
    Home,
    Sparkles,
    CheckCircle2,
    Compass,
    SlidersHorizontal
} from 'lucide-react';

const Subcategory = () => {
    const { slug } = useParams();
    const { t } = useTranslation();
    const { language, isRTL } = useLanguage();

    const [subcategory, setSubcategory] = useState(null);
    const [courses, setCourses] = useState([]);
    const [searchTerm, setSearchTerm] = useState('');
    const [sortBy, setSortBy] = useState('default'); // 'default' | 'rating' | 'newest'
    const [isDescriptionExpanded, setIsDescriptionExpanded] = useState(false);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState(null);

    const getLocalizedName = (item) => {
        if (!item) return '';
        return language === 'ar' ? (item.nameAr || item.nameEn) : (item.nameEn || item.nameAr);
    };

    const getLocalizedDescription = (item) => {
        if (!item) return '';
        return language === 'ar'
            ? (item.descriptionAr || item.description || item.descriptionEn || '')
            : (item.descriptionEn || item.description || item.descriptionAr || '');
    };

    useEffect(() => {
        if (slug) {
            fetchSubcategoryData();
            setSearchTerm('');
            setIsDescriptionExpanded(false);
        }
    }, [slug]);

    const fetchSubcategoryData = async () => {
        try {
            setLoading(true);
            setError(null);
            const response = await api.get(`/subcategories/slug/${slug}`);
            const subcategoryData = response.data?.data;

            if (!subcategoryData) {
                setError(t('subcategoryPage.notFound', 'التصنيف الفرعي غير موجود'));
                return;
            }

            setSubcategory(subcategoryData);
            setCourses(subcategoryData.courses || []);
            setLoading(false); // Display initial data immediately

            // Background fetch to ensure all courses are loaded without blocking UI
            // const subCategoryQuery = subcategoryData.nameEn || subcategoryData.slug || subcategoryData._id;
            // api.get('/courses', {
            //     params: {
            //         subCategory: subCategoryQuery,
            //         limit: 500
            //     }
            // }).then(coursesRes => {
            //     if (coursesRes.data?.courses?.length > 0) {
            //         setCourses(coursesRes.data.courses);
            //     }
            // }).catch(err => {
            //     console.error('Error fetching all courses for subcategory:', err);
            // });
        } catch (err) {
            console.error('Error fetching subcategory data:', err);
            setError(t('subcategoryPage.loadFailed', 'تعذّر تحميل بيانات التصنيف الفرعي'));
            setLoading(false);
        }
    };

    // Update document title for SEO
    useEffect(() => {
        if (subcategory) {
            const subName = getLocalizedName(subcategory);
            const catName = getLocalizedName(subcategory.category);
            document.title = `${subName} | ${catName ? `${catName} - ` : ''}${t('common.meta.siteTitle', 'أكاديمية AEC')}`;
        }
    }, [subcategory, language, t]);

    // Filter and sort courses
    const filteredCourses = useMemo(() => {
        let list = [...courses];

        if (searchTerm.trim() !== '') {
            const term = searchTerm.toLowerCase().trim();
            list = list.filter((course) => {
                const title = (course.title || '').toLowerCase();
                const desc = (course.description || '').toLowerCase();
                const instructorName = (course.instructor?.name || '').toLowerCase();
                return title.includes(term) || desc.includes(term) || instructorName.includes(term);
            });
        }

        if (sortBy === 'rating') {
            list.sort((a, b) => (Number(b.rating) || 0) - (Number(a.rating) || 0));
        } else if (sortBy === 'newest') {
            list.sort((a, b) => new Date(b.createdAt || 0) - new Date(a.createdAt || 0));
        }

        return list;
    }, [courses, searchTerm, sortBy]);

    const ArrowIcon = isRTL ? ArrowLeft : ArrowRight;
    const BreadcrumbSeparator = isRTL ? ChevronLeft : ChevronRight;

    // Loading Skeleton State
    if (loading) {
        return (
            <div className="min-h-screen bg-slate-50/70" dir={t('autoGenerated.ltr', `ltr`)}>
                {/* Hero Skeleton */}
                <div className="relative bg-[#071942] py-14 sm:py-20 px-4 sm:px-6 lg:px-8 overflow-hidden">
                    <div className="max-w-7xl mx-auto space-y-6 animate-pulse">
                        <div className="h-7 w-64 bg-white/10 rounded-full" />
                        <div className="h-6 w-36 bg-white/10 rounded-full" />
                        <div className="h-12 w-3/4 max-w-lg bg-white/15 rounded-2xl" />
                        <div className="h-5 w-full max-w-2xl bg-white/10 rounded-lg" />
                        <div className="h-5 w-2/3 max-w-xl bg-white/10 rounded-lg" />

                        {/* Stats Skeleton */}
                        <div className="grid grid-cols-2 md:grid-cols-4 gap-4 pt-10">
                            {[1, 2, 3, 4].map((i) => (
                                <div key={i} className="h-20 bg-white/5 border border-white/10 rounded-2xl p-4" />
                            ))}
                        </div>
                    </div>
                </div>

                {/* Grid Skeleton */}
                <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
                    <div className="h-14 bg-white rounded-2xl border border-slate-200/80 mb-8 animate-pulse" />
                    <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6 sm:gap-7">
                        {[1, 2, 3, 4, 5, 6].map((i) => (
                            <div key={i} className="bg-white rounded-3xl border border-slate-200/80 overflow-hidden shadow-sm animate-pulse">
                                <div className="h-48 bg-slate-200" />
                                <div className="p-6 space-y-3">
                                    <div className="h-5 bg-slate-200 rounded w-3/4" />
                                    <div className="h-4 bg-slate-100 rounded w-full" />
                                    <div className="h-4 bg-slate-100 rounded w-2/3" />
                                    <div className="pt-4 border-t border-slate-100 flex justify-between items-center">
                                        <div className="h-5 bg-slate-200 rounded w-20" />
                                        <div className="h-5 bg-slate-200 rounded w-24" />
                                    </div>
                                </div>
                            </div>
                        ))}
                    </div>
                </div>
            </div>
        );
    }

    // Error State
    if (error || !subcategory) {
        return (
            <motion.div
                initial={{ opacity: 0, y: 20 }}
                animate={{ opacity: 1, y: 0 }}
                className="min-h-screen bg-slate-50 flex items-center justify-center px-4"
                dir={t('autoGenerated.ltr', `ltr`)}
            >
                <div className="max-w-md w-full bg-white rounded-3xl p-8 sm:p-10 border border-slate-100 shadow-xl text-center">
                    <div className="w-16 h-16 bg-rose-50 text-rose-500 rounded-2xl flex items-center justify-center mx-auto mb-5 shadow-sm">
                        <Compass className="w-8 h-8" />
                    </div>
                    <h2 className="text-2xl font-extrabold text-slate-900 mb-2">
                        {t('subcategoryPage.notFound', 'التصنيف الفرعي غير موجود')}
                    </h2>
                    <p className="text-slate-600 text-sm mb-6 leading-relaxed">
                        {error || t('subcategoryPage.notFoundDesc', 'تعذّر العثور على التصنيف الفرعي المطلوب.')}
                    </p>
                    <Link
                        to="/categories"
                        className="inline-flex items-center justify-center gap-2 w-full bg-[#004C97] hover:bg-[#071942] text-white font-bold py-3 px-6 rounded-xl transition-all shadow-md shadow-blue-900/20"
                    >
                        <span>{t('subcategoryPage.backToCategories', 'العودة إلى التصنيفات')}</span>
                        <ArrowIcon className="w-4 h-4" />
                    </Link>
                </div>
            </motion.div>
        );
    }

    const subcategoryName = getLocalizedName(subcategory);
    const categoryName = getLocalizedName(subcategory.category);
    const subcategoryDescription = getLocalizedDescription(subcategory) || t('subcategoryPage.exploreIn', { name: subcategoryName, defaultValue: `استكشف أفضل الدورات المتخصصة والمعتمدة في مجال ${subcategoryName}` });
    const isLongDesc = subcategoryDescription.length > 220;

    return (
        <div className="min-h-screen bg-slate-50/70" dir={t('autoGenerated.ltr', `ltr`)}>
            
            {/* ========================================================================= */}
            {/* HERO SECTION: Subcategory Image as Section Background with Cinematic Gradient */}
            {/* ========================================================================= */}
            <section className="relative bg-[#071942] text-white overflow-hidden py-14 sm:py-20 lg:py-24">
                
                {/* Subcategory Image as Full Section Background */}
                {subcategory.image ? (
                    <div className="absolute inset-0 z-0 overflow-hidden">
                        <img
                            src={subcategory.image}
                            alt={subcategoryName}
                            className="w-full h-full object-cover object-center"
                        />
                        {/* Directional Cinematic Gradient */}
                        <div className="absolute inset-0 bg-[#06102b]/65" />
                        <div className={`absolute inset-0 ${
                            t('autoGenerated.bg_gradient_to_r_from_06102b_9', `bg-gradient-to-r from-[#06102b]/95 via-[#071942]/80 to-[#071942]/45`)
                        }`} />
                        <div className="absolute inset-0 bg-gradient-to-t from-[#06102b] via-transparent to-black/30" />
                    </div>
                ) : (
                    <div className="absolute inset-0 z-0 bg-gradient-to-br from-[#071942] to-[#004C97]" />
                )}

                {/* Ambient Radial Lights */}
                <div className="absolute top-0 right-1/4 w-96 h-96 bg-blue-600/15 rounded-full blur-3xl pointer-events-none z-10" />
                <div className="absolute bottom-0 left-1/4 w-[450px] h-[450px] bg-amber-500/10 rounded-full blur-3xl pointer-events-none z-10" />

                <div className="relative z-20 max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
                    
                    {/* Integrated Glassmorphic Breadcrumbs */}
                    <motion.div
                        initial={{ opacity: 0, y: -10 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ duration: 0.3 }}
                        className="mb-6 inline-flex"
                    >
                        <nav
                            aria-label="Breadcrumb"
                            className="flex items-center flex-wrap gap-2 text-xs sm:text-sm bg-slate-900/60 backdrop-blur-md border border-white/20 px-4 py-2 rounded-full text-blue-100 shadow-md"
                        >
                            <Link
                                to="/"
                                className="flex items-center gap-1.5 text-blue-200 hover:text-white transition-colors"
                            >
                                <Home className="w-3.5 h-3.5" />
                                <span>{t('subcategoryPage.home', 'الرئيسية')}</span>
                            </Link>

                            <BreadcrumbSeparator className="w-3.5 h-3.5 text-blue-300/60" />

                            <Link
                                to="/categories"
                                className="text-blue-200 hover:text-white transition-colors"
                            >
                                {t('subcategoryPage.categories', 'التصنيفات')}
                            </Link>

                            {subcategory.category && (
                                <>
                                    <BreadcrumbSeparator className="w-3.5 h-3.5 text-blue-300/60" />
                                    <Link
                                        to={`/category/${subcategory.category?.slug}`}
                                        className="text-blue-200 hover:text-white transition-colors truncate max-w-[150px] sm:max-w-none"
                                    >
                                        {categoryName}
                                    </Link>
                                </>
                            )}

                            <BreadcrumbSeparator className="w-3.5 h-3.5 text-blue-300/60" />

                            <span className="font-semibold text-white truncate max-w-[200px] sm:max-w-none">
                                {subcategoryName}
                            </span>
                        </nav>
                    </motion.div>

                    {/* Hero Title & Description Area */}
                    <div className="max-w-4xl space-y-4">
                        <motion.div
                            initial={{ opacity: 0, x: isRTL ? 20 : -20 }}
                            animate={{ opacity: 1, x: 0 }}
                            transition={{ duration: 0.4 }}
                            className="inline-flex items-center gap-2 bg-gradient-to-r from-amber-500/25 to-amber-500/10 border border-amber-400/40 text-amber-300 px-4 py-1.5 rounded-full text-xs font-bold tracking-wide backdrop-blur-md shadow-md"
                        >
                            <Sparkles className="w-3.5 h-3.5 text-amber-400" />
                            <span>{t('subcategoryPage.trackBadge', 'مسار تدريبي تخصصي معتمد')}</span>
                        </motion.div>

                        <motion.h1
                            initial={{ opacity: 0, y: 15 }}
                            animate={{ opacity: 1, y: 0 }}
                            transition={{ duration: 0.5, delay: 0.1 }}
                            className="text-3xl sm:text-5xl lg:text-6xl font-black text-white tracking-tight leading-tight drop-shadow-lg"
                        >
                            {subcategoryName}
                        </motion.h1>

                        {/* Description with Expand/Collapse */}
                        <motion.div
                            initial={{ opacity: 0, y: 15 }}
                            animate={{ opacity: 1, y: 0 }}
                            transition={{ duration: 0.5, delay: 0.2 }}
                            className="text-slate-100 text-sm sm:text-base md:text-lg leading-relaxed max-w-3xl drop-shadow"
                        >
                            <p className={!isDescriptionExpanded && isLongDesc ? 'line-clamp-3' : 'whitespace-pre-line'}>
                                {subcategoryDescription}
                            </p>
                            {isLongDesc && (
                                <button
                                    onClick={() => setIsDescriptionExpanded(!isDescriptionExpanded)}
                                    className="mt-2 inline-flex items-center gap-1.5 text-amber-400 hover:text-amber-300 font-semibold text-sm transition-colors focus:outline-none"
                                >
                                    <span>
                                        {isDescriptionExpanded
                                            ? t('subcategoryPage.readLess', 'عرض أقل')
                                            : t('subcategoryPage.readMore', 'قراءة المزيد')}
                                    </span>
                                    {isDescriptionExpanded ? (
                                        <ChevronUp className="w-4 h-4" />
                                    ) : (
                                        <ChevronDown className="w-4 h-4" />
                                    )}
                                </button>
                            )}
                        </motion.div>
                    </div>

                    {/* Stats Highlights Strip */}
                    <motion.div
                        initial={{ opacity: 0, y: 20 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ duration: 0.5, delay: 0.3 }}
                        className="mt-10 grid grid-cols-2 sm:grid-cols-4 gap-3 sm:gap-4 max-w-5xl"
                    >
                        {/* Metric 1: Courses Count */}
                        <div className="bg-slate-900/65 backdrop-blur-md border border-white/20 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-slate-900/80 transition-all shadow-lg">
                            <div className="w-11 h-11 rounded-xl bg-amber-500/25 border border-amber-400/40 flex items-center justify-center text-amber-400 shrink-0">
                                <BookOpen className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-xl sm:text-2xl font-black text-white">
                                    {courses.length}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    {courses.length === 1 ? t('subcategoryPage.course', 'دورة معتمدة') : t('subcategoryPage.courses', 'دورات معتمدة')}
                                </span>
                            </div>
                        </div>

                        {/* Metric 2: Parent Category */}
                        {categoryName ? (
                            <Link
                                to={`/category/${subcategory.category?.slug}`}
                                className="bg-slate-900/65 backdrop-blur-md border border-white/20 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-slate-900/80 transition-all shadow-lg group"
                            >
                                <div className="w-11 h-11 rounded-xl bg-blue-500/25 border border-blue-400/40 flex items-center justify-center text-blue-300 shrink-0 group-hover:scale-105 transition-transform">
                                    <Layers className="w-5 h-5" />
                                </div>
                                <div className="min-w-0">
                                    <span className="block text-sm sm:text-base font-bold text-white truncate group-hover:text-amber-300 transition-colors">
                                        {categoryName}
                                    </span>
                                    <span className="block text-xs text-blue-200 font-medium">
                                        {t('subcategoryPage.parentCategory', 'المجال الرئيسي')}
                                    </span>
                                </div>
                            </Link>
                        ) : (
                            <div className="bg-slate-900/65 backdrop-blur-md border border-white/20 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-slate-900/80 transition-all shadow-lg">
                                <div className="w-11 h-11 rounded-xl bg-blue-500/25 border border-blue-400/40 flex items-center justify-center text-blue-300 shrink-0">
                                    <Layers className="w-5 h-5" />
                                </div>
                                <div>
                                    <span className="block text-sm sm:text-base font-bold text-white">
                                        AEC Certified
                                    </span>
                                    <span className="block text-xs text-blue-200 font-medium">
                                        مسار تدريبي معتمد
                                    </span>
                                </div>
                            </div>
                        )}

                        {/* Metric 3: Accredited Certificates */}
                        <div className="bg-slate-900/65 backdrop-blur-md border border-white/20 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-slate-900/80 transition-all shadow-lg">
                            <div className="w-11 h-11 rounded-xl bg-emerald-500/25 border border-emerald-400/40 flex items-center justify-center text-emerald-400 shrink-0">
                                <Award className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-sm sm:text-base font-bold text-white">
                                    {t('subcategoryPage.certifiedPrograms', 'شهادات معتمدة')}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    محلياً ودولياً
                                </span>
                            </div>
                        </div>

                        {/* Metric 4: Career Ready */}
                        <div className="bg-slate-900/65 backdrop-blur-md border border-white/20 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-slate-900/80 transition-all shadow-lg">
                            <div className="w-11 h-11 rounded-xl bg-indigo-500/25 border border-indigo-400/40 flex items-center justify-center text-indigo-300 shrink-0">
                                <GraduationCap className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-sm sm:text-base font-bold text-white">
                                    {t('subcategoryPage.practicalTraining', 'تطبيق عملي')}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    مشاريع وتأهيل مباشر
                                </span>
                            </div>
                        </div>
                    </motion.div>

                </div>
            </section>

            {/* ========================================================================= */}
            {/* MAIN CONTENT: Interactive Search, Filters & Courses Grid                  */}
            {/* ========================================================================= */}
            <main className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10 sm:py-14">
                
                {/* Header Strip & Search Bar */}
                <div className="bg-white rounded-3xl border border-slate-200/80 p-5 sm:p-7 shadow-sm mb-10 space-y-6">
                    <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
                        <div>
                            <h2 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight">
                                {t('subcategoryPage.exploreIn', { name: subcategoryName, defaultValue: `دورات وبرامج ${subcategoryName}` })}
                            </h2>
                            <p className="text-slate-500 text-sm mt-1">
                                استكشف قائمة الدورات التدريبية المعتمدة والمتاحة للتسجيل الفوري.
                            </p>
                        </div>

                        {/* Showing count indicator */}
                        <div className="inline-flex items-center gap-2 bg-blue-50 text-blue-700 px-4 py-2 rounded-xl text-xs sm:text-sm font-bold border border-blue-100 self-start md:self-auto">
                            <span>
                                {t('subcategoryPage.showingResults', {
                                    count: filteredCourses.length,
                                    total: courses.length,
                                    defaultValue: `عرض ${filteredCourses.length} من أصل ${courses.length} دورة تدريبية`
                                })}
                            </span>
                        </div>
                    </div>

                    {/* Search and Sort Toolbar */}
                    <div className="grid grid-cols-1 sm:grid-cols-12 gap-3 pt-2">
                        {/* Search Input */}
                        <div className="sm:col-span-8 lg:col-span-8 relative">
                            <div className={`absolute inset-y-0 ${t('autoGenerated.left_0_pl_4', `left-0 pl-4`)} flex items-center pointer-events-none text-slate-400`}>
                                <Search className="w-5 h-5" />
                            </div>
                            <input
                                type="text"
                                value={searchTerm}
                                onChange={(e) => setSearchTerm(e.target.value)}
                                placeholder={t('subcategoryPage.searchPlaceholder', 'ابحث في دورات هذا التخصص...')}
                                className={`w-full bg-slate-50/80 border border-slate-200 rounded-2xl ${
                                    t('autoGenerated.pl_11_pr_10', `pl-11 pr-10`)
                                } py-3 text-sm text-slate-800 placeholder-slate-400 focus:outline-none focus:ring-2 focus:ring-blue-600/30 focus:border-blue-600 focus:bg-white transition-all`}
                            />
                            {searchTerm && (
                                <button
                                    onClick={() => setSearchTerm('')}
                                    className={`absolute inset-y-0 ${t('autoGenerated.right_0_pr_3_5', `right-0 pr-3.5`)} flex items-center text-slate-400 hover:text-slate-600 transition-colors`}
                                    aria-label="Clear search"
                                >
                                    <X className="w-4 h-4" />
                                </button>
                            )}
                        </div>

                        {/* Sort Tabs */}
                        <div className="sm:col-span-4 lg:col-span-4 flex items-center gap-1.5 bg-slate-50/80 p-1 border border-slate-200 rounded-2xl">
                            <button
                                onClick={() => setSortBy('default')}
                                className={`flex-1 py-2 px-3 rounded-xl text-xs font-bold transition-all text-center ${
                                    sortBy === 'default'
                                        ? 'bg-white text-blue-700 shadow-sm border border-slate-100'
                                        : 'text-slate-600 hover:text-slate-900'
                                }`}
                            >
                                {t('subcategoryPage.allCourses', 'جميع الدورات')}
                            </button>
                            <button
                                onClick={() => setSortBy('rating')}
                                className={`flex-1 py-2 px-3 rounded-xl text-xs font-bold transition-all text-center ${
                                    sortBy === 'rating'
                                        ? 'bg-white text-blue-700 shadow-sm border border-slate-100'
                                        : 'text-slate-600 hover:text-slate-900'
                                }`}
                            >
                                {t('subcategoryPage.highestRated', 'الأعلى تقييماً')}
                            </button>
                            <button
                                onClick={() => setSortBy('newest')}
                                className={`flex-1 py-2 px-3 rounded-xl text-xs font-bold transition-all text-center ${
                                    sortBy === 'newest'
                                        ? 'bg-white text-blue-700 shadow-sm border border-slate-100'
                                        : 'text-slate-600 hover:text-slate-900'
                                }`}
                            >
                                {t('subcategoryPage.newest', 'الأحدث')}
                            </button>
                        </div>
                    </div>
                </div>

                {/* Courses Grid */}
                {filteredCourses.length > 0 ? (
                    <motion.div
                        layout
                        className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6 sm:gap-7"
                    >
                        <AnimatePresence>
                            {filteredCourses.map((course, index) => (
                                <motion.div
                                    key={course._id || index}
                                    layout
                                    initial={{ opacity: 0, y: 20 }}
                                    animate={{ opacity: 1, y: 0 }}
                                    exit={{ opacity: 0, scale: 0.95 }}
                                    transition={{ duration: 0.35, delay: Math.min(index * 0.05, 0.4) }}
                                >
                                    <CourseCard course={course} />
                                </motion.div>
                            ))}
                        </AnimatePresence>
                    </motion.div>
                ) : searchTerm ? (
                    /* Search Term Empty State */
                    <motion.div
                        initial={{ opacity: 0, scale: 0.95 }}
                        animate={{ opacity: 1, scale: 1 }}
                        className="bg-white rounded-3xl border border-slate-200/80 p-10 sm:p-14 text-center max-w-xl mx-auto shadow-sm"
                    >
                        <div className="w-16 h-16 bg-blue-50 text-blue-600 rounded-2xl flex items-center justify-center mx-auto mb-4">
                            <Search className="w-8 h-8 text-blue-500" />
                        </div>
                        <h3 className="text-xl font-bold text-slate-900 mb-2">
                            {t('subcategoryPage.noCoursesFound', 'لم يتم العثور على دورات تطابق بحثك')}
                        </h3>
                        <p className="text-slate-500 text-sm mb-6 leading-relaxed">
                            {t('subcategoryPage.noMatchSearch', { term: searchTerm, defaultValue: `لا توجد نتائج تطابق "${searchTerm}".` })}
                        </p>
                        <button
                            onClick={() => setSearchTerm('')}
                            className="inline-flex items-center gap-2 bg-[#004C97] hover:bg-[#071942] text-white font-bold py-2.5 px-6 rounded-xl text-sm transition-all"
                        >
                            <span>{t('subcategoryPage.clearSearch', 'إعادة ضبط البحث')}</span>
                            <X className="w-4 h-4" />
                        </button>
                    </motion.div>
                ) : (
                    /* Total Empty Subcategory State */
                    <motion.div
                        initial={{ opacity: 0, scale: 0.95 }}
                        animate={{ opacity: 1, scale: 1 }}
                        className="bg-white rounded-3xl border border-slate-200/80 p-12 text-center max-w-lg mx-auto shadow-sm"
                    >
                        <div className="w-16 h-16 bg-amber-50 text-amber-600 rounded-2xl flex items-center justify-center mx-auto mb-4">
                            <BookOpen className="w-8 h-8 text-amber-500" />
                        </div>
                        <h3 className="text-2xl font-bold text-slate-900 mb-2">
                            {t('subcategoryPage.noCoursesAvailable', 'لا توجد دورات متاحة حالياً')}
                        </h3>
                        <p className="text-slate-500 text-sm mb-6 leading-relaxed">
                            {t('subcategoryPage.noCoursesYet', {
                                name: subcategoryName,
                                defaultValue: `لا توجد دورات مدرجة في مسار ${subcategoryName} حالياً، جاري إضافة برامج جديدة قريباً.`
                            })}
                        </p>
                        <div className="flex flex-wrap items-center justify-center gap-3">
                            {subcategory.category && (
                                <Link
                                    to={`/category/${subcategory.category?.slug}`}
                                    className="inline-flex items-center gap-2 bg-[#004C97] hover:bg-[#071942] text-white font-bold py-3 px-6 rounded-xl text-sm transition-all"
                                >
                                    <span>العودة إلى {categoryName}</span>
                                    <ArrowIcon className="w-4 h-4" />
                                </Link>
                            )}
                            <Link
                                to="/categories"
                                className="inline-flex items-center gap-2 bg-slate-100 hover:bg-slate-200 text-slate-700 font-bold py-3 px-6 rounded-xl text-sm transition-all"
                            >
                                <span>{t('subcategoryPage.exploreOther', 'استكشف تصنيفات أخرى')}</span>
                            </Link>
                        </div>
                    </motion.div>
                )}

            </main>
        </div>
    );
};

export default Subcategory;
