import React, { useState, useEffect, useMemo } from 'react';
import { Link } from 'react-router-dom';
import { motion, AnimatePresence } from 'framer-motion';
import { useTranslation } from 'react-i18next';
import { useLanguage } from '../hooks/useLanguage';
import api from '../services/new-api';
import {
    Search,
    X,
    Layers,
    Award,
    GraduationCap,
    ArrowRight,
    ArrowLeft,
    ChevronRight,
    ChevronLeft,
    Home,
    Sparkles,
    CheckCircle2,
    Compass,
    RotateCcw
} from 'lucide-react';

const Categories = () => {
    const { t } = useTranslation();
    const { language, isRTL } = useLanguage();

    const [categories, setCategories] = useState([]);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState(null);

    // Search and filter states
    const [searchTerm, setSearchTerm] = useState('');
    const [sortBy, setSortBy] = useState('default'); // 'default' | 'tracks' | 'alpha'

    const getLocalizedName = (item) => {
        if (!item) return '';
        return language === 'ar' ? (item.nameAr || item.nameEn) : (item.nameEn || item.nameAr);
    };

    const getLocalizedDescription = (item) => {
        if (!item) return '';
        return language === 'ar'
            ? (item.descriptionAr || item.description || item.descriptionEn || '')
            : (item.descriptionEn || item.description || item.descriptionAr || '');
    };

    useEffect(() => {
        fetchCategories();
    }, []);

    const fetchCategories = async () => {
        try {
            setLoading(true);
            setError(null);
            const response = await api.get('/categories');
            const data = response.data?.data || [];
            setCategories(data);
        } catch (err) {
            console.error('Error fetching categories:', err);
            setError(t('categories.loadFailed', 'حدث خطأ أثناء تحميل بيانات التصنيفات، يرجى المحاولة مرة أخرى.'));
        } finally {
            setLoading(false);
        }
    };

    // Update document title for SEO
    useEffect(() => {
        document.title = `${t('categories.title', 'جميع التصنيفات والمجالات')} | ${t('common.meta.siteTitle', 'أكاديمية AEC')}`;
    }, [language, t]);

    // Calculate total subcategories across all categories
    const totalSubcategories = useMemo(() => {
        return categories.reduce((acc, cat) => {
            return acc + (Number(cat.subcategoryCount) || cat.subcategories?.length || 0);
        }, 0);
    }, [categories]);

    // Filter and sort categories
    const filteredCategories = useMemo(() => {
        let list = [...categories];

        if (searchTerm.trim() !== '') {
            const term = searchTerm.toLowerCase().trim();
            list = list.filter((cat) => {
                const nameAr = (cat.nameAr || '').toLowerCase();
                const nameEn = (cat.nameEn || '').toLowerCase();
                const desc = (cat.description || '').toLowerCase();
                return nameAr.includes(term) || nameEn.includes(term) || desc.includes(term);
            });
        }

        if (sortBy === 'tracks') {
            list.sort((a, b) => {
                const countA = Number(a.subcategoryCount) || a.subcategories?.length || 0;
                const countB = Number(b.subcategoryCount) || b.subcategories?.length || 0;
                return countB - countA;
            });
        } else if (sortBy === 'alpha') {
            list.sort((a, b) => {
                const nameA = getLocalizedName(a);
                const nameB = getLocalizedName(b);
                return nameA.localeCompare(nameB, language === 'ar' ? 'ar' : 'en');
            });
        }

        return list;
    }, [categories, searchTerm, sortBy, language]);

    const ArrowIcon = isRTL ? ArrowLeft : ArrowRight;
    const BreadcrumbSeparator = isRTL ? ChevronLeft : ChevronRight;

    // Loading Skeleton State
    if (loading) {
        return (
            <div className="min-h-screen bg-slate-50/70" dir={t('autoGenerated.ltr', `ltr`)}>
                {/* Hero Skeleton */}
                <div className="relative bg-[#071942] py-14 sm:py-20 px-4 sm:px-6 lg:px-8 overflow-hidden">
                    <div className="max-w-7xl mx-auto space-y-6 animate-pulse">
                        <div className="h-7 w-48 bg-white/10 rounded-full" />
                        <div className="h-6 w-36 bg-white/10 rounded-full" />
                        <div className="h-12 w-3/4 max-w-lg bg-white/15 rounded-2xl" />
                        <div className="h-5 w-full max-w-2xl bg-white/10 rounded-lg" />
                        <div className="h-5 w-2/3 max-w-xl bg-white/10 rounded-lg" />

                        {/* Stats Skeleton */}
                        <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 pt-8">
                            {[1, 2, 3, 4].map((i) => (
                                <div key={i} className="h-20 bg-white/5 border border-white/10 rounded-2xl p-4" />
                            ))}
                        </div>
                    </div>
                </div>

                {/* Grid Skeleton */}
                <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
                    <div className="h-14 bg-white rounded-2xl border border-slate-200/80 mb-8 animate-pulse" />
                    <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-7">
                        {[1, 2, 3, 4, 5, 6, 7, 8].map((i) => (
                            <div key={i} className="bg-white rounded-3xl border border-slate-200/80 overflow-hidden shadow-sm animate-pulse">
                                <div className="h-52 bg-slate-200" />
                                <div className="p-6 space-y-3">
                                    <div className="h-5 bg-slate-200 rounded w-3/4" />
                                    <div className="h-4 bg-slate-100 rounded w-full" />
                                    <div className="h-4 bg-slate-100 rounded w-2/3" />
                                    <div className="pt-4 border-t border-slate-100 flex justify-between items-center">
                                        <div className="h-4 bg-slate-200 rounded w-24" />
                                        <div className="h-4 bg-slate-200 rounded w-16" />
                                    </div>
                                </div>
                            </div>
                        ))}
                    </div>
                </div>
            </div>
        );
    }

    // Error State
    if (error) {
        return (
            <motion.div
                initial={{ opacity: 0, y: 20 }}
                animate={{ opacity: 1, y: 0 }}
                className="min-h-screen bg-slate-50 flex items-center justify-center px-4"
                dir={t('autoGenerated.ltr', `ltr`)}
            >
                <div className="max-w-md w-full bg-white rounded-3xl p-8 sm:p-10 border border-slate-100 shadow-xl text-center">
                    <div className="w-16 h-16 bg-rose-50 text-rose-500 rounded-2xl flex items-center justify-center mx-auto mb-5 shadow-sm">
                        <Compass className="w-8 h-8" />
                    </div>
                    <h2 className="text-2xl font-extrabold text-slate-900 mb-2">
                        {t('categories.errorTitle', 'تعذّر تحميل التصنيفات')}
                    </h2>
                    <p className="text-slate-600 text-sm mb-6 leading-relaxed">
                        {error}
                    </p>
                    <button
                        onClick={fetchCategories}
                        className="inline-flex items-center justify-center gap-2 w-full bg-[#004C97] hover:bg-[#071942] text-white font-bold py-3 px-6 rounded-xl transition-all shadow-md shadow-blue-900/20"
                    >
                        <RotateCcw className="w-4 h-4" />
                        <span>{t('common.tryAgain', 'إعادة المحاولة')}</span>
                    </button>
                </div>
            </motion.div>
        );
    }

    return (
        <div className="min-h-screen bg-slate-50/70" dir={t('autoGenerated.ltr', `ltr`)}>
            
            {/* ========================================================================= */}
            {/* HERO SECTION: Cinematic, Rich, Brand-Aligned                             */}
            {/* ========================================================================= */}
            <section className="relative bg-[#071942] text-white overflow-hidden py-14 sm:py-20">
                {/* Background Ambient Glows */}
                <div className="absolute top-0 right-1/4 w-96 h-96 bg-blue-600/20 rounded-full blur-3xl pointer-events-none" />
                <div className="absolute bottom-0 left-1/4 w-[450px] h-[450px] bg-amber-500/10 rounded-full blur-3xl pointer-events-none" />

                <div className="relative z-10 max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
                    
                    {/* Integrated Glassmorphic Breadcrumbs */}
                    <motion.div
                        initial={{ opacity: 0, y: -10 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ duration: 0.3 }}
                        className="mb-6 inline-flex"
                    >
                        <nav
                            aria-label="Breadcrumb"
                            className="flex items-center flex-wrap gap-2 text-xs sm:text-sm bg-white/10 backdrop-blur-md border border-white/15 px-4 py-2 rounded-full text-blue-100 shadow-sm"
                        >
                            <Link
                                to="/"
                                className="flex items-center gap-1.5 text-blue-200 hover:text-white transition-colors"
                            >
                                <Home className="w-3.5 h-3.5" />
                                <span>{t('categories.home', 'الرئيسية')}</span>
                            </Link>

                            <BreadcrumbSeparator className="w-3.5 h-3.5 text-blue-300/60" />

                            <span className="font-semibold text-white">
                                {t('categories.title', 'جميع التصنيفات')}
                            </span>
                        </nav>
                    </motion.div>

                    {/* Hero Title & Subtitle */}
                    <div className="max-w-4xl space-y-4">
                        <motion.div
                            initial={{ opacity: 0, x: isRTL ? 20 : -20 }}
                            animate={{ opacity: 1, x: 0 }}
                            transition={{ duration: 0.4 }}
                            className="inline-flex items-center gap-2 bg-gradient-to-r from-amber-500/20 to-amber-500/10 border border-amber-400/30 text-amber-300 px-3.5 py-1.5 rounded-full text-xs font-bold tracking-wide"
                        >
                            <Sparkles className="w-3.5 h-3.5 text-amber-400" />
                            <span>{t('categories.badge', 'دليلك الشامل للمسارات المهنية المعتمدة')}</span>
                        </motion.div>

                        <motion.h1
                            initial={{ opacity: 0, y: 15 }}
                            animate={{ opacity: 1, y: 0 }}
                            transition={{ duration: 0.5, delay: 0.1 }}
                            className="text-3xl sm:text-4xl md:text-5xl lg:text-6xl font-black text-white tracking-tight leading-tight"
                        >
                            {t('categories.exploreTitle', 'استكشف كافة المجالات والتخصصات التدريبية')}
                        </motion.h1>

                        <motion.p
                            initial={{ opacity: 0, y: 15 }}
                            animate={{ opacity: 1, y: 0 }}
                            transition={{ duration: 0.5, delay: 0.2 }}
                            className="text-slate-200 text-sm sm:text-base md:text-lg leading-relaxed max-w-3xl"
                        >
                            {t('categories.exploreSubtitle', 'اختر مجالك المفضل وابدأ رحلتك الأكاديمية مع نخبة من الخبراء والشهادات المعتمدة محلياً ودولياً.')}
                        </motion.p>
                    </div>

                    {/* Stats Highlights Strip */}
                    <motion.div
                        initial={{ opacity: 0, y: 20 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ duration: 0.5, delay: 0.3 }}
                        className="mt-10 grid grid-cols-2 sm:grid-cols-4 gap-3 sm:gap-4 max-w-5xl"
                    >
                        {/* Metric 1: Total Categories */}
                        <div className="bg-white/10 backdrop-blur-md border border-white/15 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-white/15 transition-all">
                            <div className="w-11 h-11 rounded-xl bg-blue-500/20 border border-blue-400/30 flex items-center justify-center text-blue-300 shrink-0">
                                <Layers className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-xl sm:text-2xl font-black text-white">
                                    {categories.length}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    {t('categories.majorFields', 'مجال تدريبي معتمد')}
                                </span>
                            </div>
                        </div>

                        {/* Metric 2: Total Tracks */}
                        <div className="bg-white/10 backdrop-blur-md border border-white/15 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-white/15 transition-all">
                            <div className="w-11 h-11 rounded-xl bg-amber-500/20 border border-amber-400/30 flex items-center justify-center text-amber-400 shrink-0">
                                <Compass className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-xl sm:text-2xl font-black text-white">
                                    {totalSubcategories > 0 ? `+${totalSubcategories}` : '+250'}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    مسار وتخصص مهني
                                </span>
                            </div>
                        </div>

                        {/* Metric 3: Certificates */}
                        <div className="bg-white/10 backdrop-blur-md border border-white/15 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-white/15 transition-all">
                            <div className="w-11 h-11 rounded-xl bg-emerald-500/20 border border-emerald-400/30 flex items-center justify-center text-emerald-400 shrink-0">
                                <Award className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-sm sm:text-base font-bold text-white">
                                    {t('categories.certifiedTracks', 'شهادات معتمدة')}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    محلياً ودولياً
                                </span>
                            </div>
                        </div>

                        {/* Metric 4: Career Training */}
                        <div className="bg-white/10 backdrop-blur-md border border-white/15 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-white/15 transition-all">
                            <div className="w-11 h-11 rounded-xl bg-indigo-500/20 border border-indigo-400/30 flex items-center justify-center text-indigo-300 shrink-0">
                                <GraduationCap className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-sm sm:text-base font-bold text-white">
                                    {t('categories.handsOnTraining', 'تأهيل وظيفي')}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    مشاريع وتطبيق عملي
                                </span>
                            </div>
                        </div>
                    </motion.div>

                </div>
            </section>

            {/* ========================================================================= */}
            {/* MAIN CONTENT: Search, Filters & Category Cards Grid                       */}
            {/* ========================================================================= */}
            <main className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10 sm:py-14">
                
                {/* Header Strip & Search Bar */}
                <div className="bg-white rounded-3xl border border-slate-200/80 p-5 sm:p-7 shadow-sm mb-10 space-y-6">
                    <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
                        <div>
                            <h2 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight">
                                {t('categories.browse', 'تصفح حسب المجال والتخصص')}
                            </h2>
                            <p className="text-slate-500 text-sm mt-1">
                                {t('categories.exploreSubtitle', 'اكتشف البرامج التدريبية المعتمدة في مختلف المجالات العلمية والمهنية.')}
                            </p>
                        </div>

                        {/* Showing count indicator */}
                        <div className="inline-flex items-center gap-2 bg-blue-50 text-blue-700 px-4 py-2 rounded-xl text-xs sm:text-sm font-bold border border-blue-100 self-start md:self-auto">
                            <span>
                                {t('categories.showingResults', {
                                    count: filteredCategories.length,
                                    total: categories.length,
                                    defaultValue: `عرض ${filteredCategories.length} من أصل ${categories.length} مجال تدريبي`
                                })}
                            </span>
                        </div>
                    </div>

                    {/* Search and Sort Toolbar */}
                    <div className="grid grid-cols-1 sm:grid-cols-12 gap-3 pt-2">
                        {/* Search Input */}
                        <div className="sm:col-span-8 lg:col-span-8 relative">
                            <div className={`absolute inset-y-0 ${t('autoGenerated.left_0_pl_4', `left-0 pl-4`)} flex items-center pointer-events-none text-slate-400`}>
                                <Search className="w-5 h-5" />
                            </div>
                            <input
                                type="text"
                                value={searchTerm}
                                onChange={(e) => setSearchTerm(e.target.value)}
                                placeholder={t('categories.searchPlaceholder', 'ابحث في التصنيفات والمجالات التدريبية...')}
                                className={`w-full bg-slate-50/80 border border-slate-200 rounded-2xl ${
                                    t('autoGenerated.pl_11_pr_10', `pl-11 pr-10`)
                                } py-3 text-sm text-slate-800 placeholder-slate-400 focus:outline-none focus:ring-2 focus:ring-blue-600/30 focus:border-blue-600 focus:bg-white transition-all`}
                            />
                            {searchTerm && (
                                <button
                                    onClick={() => setSearchTerm('')}
                                    className={`absolute inset-y-0 ${t('autoGenerated.right_0_pr_3_5', `right-0 pr-3.5`)} flex items-center text-slate-400 hover:text-slate-600 transition-colors`}
                                    aria-label="Clear search"
                                >
                                    <X className="w-4 h-4" />
                                </button>
                            )}
                        </div>

                        {/* Sort Tabs */}
                        <div className="sm:col-span-4 lg:col-span-4 flex items-center gap-1.5 bg-slate-50/80 p-1 border border-slate-200 rounded-2xl">
                            <button
                                onClick={() => setSortBy('default')}
                                className={`flex-1 py-2 px-3 rounded-xl text-xs font-bold transition-all text-center ${
                                    sortBy === 'default'
                                        ? 'bg-white text-blue-700 shadow-sm border border-slate-100'
                                        : 'text-slate-600 hover:text-slate-900'
                                }`}
                            >
                                {t('categories.allFields', 'الكل')}
                            </button>
                            <button
                                onClick={() => setSortBy('tracks')}
                                className={`flex-1 py-2 px-3 rounded-xl text-xs font-bold transition-all text-center ${
                                    sortBy === 'tracks'
                                        ? 'bg-white text-blue-700 shadow-sm border border-slate-100'
                                        : 'text-slate-600 hover:text-slate-900'
                                }`}
                            >
                                {t('categories.mostTracks', 'الأكثر مسارات')}
                            </button>
                            <button
                                onClick={() => setSortBy('alpha')}
                                className={`flex-1 py-2 px-3 rounded-xl text-xs font-bold transition-all text-center ${
                                    sortBy === 'alpha'
                                        ? 'bg-white text-blue-700 shadow-sm border border-slate-100'
                                        : 'text-slate-600 hover:text-slate-900'
                                }`}
                            >
                                {t('categories.alphabetical', 'أبجدياً')}
                            </button>
                        </div>
                    </div>
                </div>

                {/* Categories Grid */}
                {filteredCategories.length > 0 ? (
                    <motion.div
                        layout
                        className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-6 sm:gap-8"
                    >
                        <AnimatePresence>
                            {filteredCategories.map((category, index) => {
                                const catName = getLocalizedName(category);
                                const catDesc = getLocalizedDescription(category);
                                const subCount = Number(category.subcategoryCount) || category.subcategories?.length || 0;

                                return (
                                    <motion.div
                                        key={category._id || index}
                                        layout
                                        initial={{ opacity: 0, y: 20 }}
                                        animate={{ opacity: 1, y: 0 }}
                                        exit={{ opacity: 0, scale: 0.95 }}
                                        transition={{ duration: 0.35, delay: Math.min(index * 0.05, 0.4) }}
                                    >
                                        <Link
                                            to={`/category/${category.slug}`}
                                            className="group relative bg-white rounded-3xl border border-slate-200/80 hover:border-blue-500/50 shadow-sm hover:shadow-2xl hover:shadow-blue-900/10 hover:-translate-y-2 transition-all duration-300 flex flex-col h-full overflow-hidden"
                                        >
                                            {/* Top Image Banner */}
                                            <div className="relative h-52 w-full bg-slate-900 overflow-hidden">
                                                {category.image ? (
                                                    <img
                                                        src={category.image}
                                                        alt={catName}
                                                        loading="lazy"
                                                        className="w-full h-full object-cover transition-transform duration-700 ease-out group-hover:scale-108"
                                                    />
                                                ) : (
                                                    <div className="w-full h-full flex flex-col items-center justify-center bg-gradient-to-br from-[#071942] to-[#004C97] text-white p-4 text-center">
                                                        <span className="text-5xl mb-2">{category.icon || '📚'}</span>
                                                        <span className="text-xs font-semibold text-blue-200">AEC Academy</span>
                                                    </div>
                                                )}

                                                {/* Image Gradient Scrim */}
                                                <div className="absolute inset-0 bg-gradient-to-t from-slate-950/75 via-slate-950/20 to-transparent pointer-events-none" />

                                                {/* Subcategories Count Floating Pill */}
                                                <div className={`absolute top-3 ${t('autoGenerated.left_3', `left-3`)} z-10`}>
                                                    <span className="inline-flex items-center gap-1.5 bg-slate-900/85 backdrop-blur-md text-amber-300 border border-white/20 text-xs font-bold px-3 py-1.5 rounded-full shadow-md">
                                                        <Layers className="w-3.5 h-3.5 text-amber-400" />
                                                        <span>
                                                            {subCount > 0
                                                                ? t('categories.subcategoriesCount', { count: subCount, defaultValue: `${subCount} مسار فرعي` })
                                                                : t('categories.certifiedTracks', 'مسارات معتمدة')}
                                                        </span>
                                                    </span>
                                                </div>

                                                {/* Bottom Tag Overlay on Image */}
                                                <div className={`absolute bottom-3 ${t('autoGenerated.left_3', `left-3`)} z-10`}>
                                                    <span className="inline-flex items-center gap-1 text-[11px] font-semibold text-white/95 drop-shadow">
                                                        <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
                                                        <span>تأهيل مهني معتمد</span>
                                                    </span>
                                                </div>
                                            </div>

                                            {/* Card Body */}
                                            <div className="p-6 flex flex-col flex-1">
                                                <h3 className="text-xl font-bold text-slate-900 group-hover:text-blue-600 transition-colors line-clamp-1 leading-snug">
                                                    {catName}
                                                </h3>

                                                <p className="text-slate-500 text-xs sm:text-sm mt-2 line-clamp-2 leading-relaxed min-h-[40px]">
                                                    {catDesc || t('categories.exploreDefaultDesc', 'استكشف أفضل الدورات والمسارات التدريبية المعتمدة في هذا المجال.')}
                                                </p>

                                                {/* Card Footer / Action Link */}
                                                <div className="pt-4 mt-auto border-t border-slate-100 flex items-center justify-between">
                                                    <span className="text-xs font-medium text-slate-400">
                                                        AEC Certified
                                                    </span>

                                                    <div className="inline-flex items-center gap-1.5 text-xs sm:text-sm font-bold text-[#004C97] group-hover:text-blue-600 transition-all">
                                                        <span>{t('categories.explore', 'استكشف التخصصات')}</span>
                                                        <ArrowIcon
                                                            className={`w-4 h-4 transition-transform duration-300 ${
                                                                t('autoGenerated.group_hover_translate_x_1_5', `group-hover:translate-x-1.5`)
                                                            }`}
                                                        />
                                                    </div>
                                                </div>
                                            </div>
                                        </Link>
                                    </motion.div>
                                );
                            })}
                        </AnimatePresence>
                    </motion.div>
                ) : searchTerm ? (
                    /* Search Term Empty State */
                    <motion.div
                        initial={{ opacity: 0, scale: 0.95 }}
                        animate={{ opacity: 1, scale: 1 }}
                        className="bg-white rounded-3xl border border-slate-200/80 p-10 sm:p-14 text-center max-w-xl mx-auto shadow-sm"
                    >
                        <div className="w-16 h-16 bg-blue-50 text-blue-600 rounded-2xl flex items-center justify-center mx-auto mb-4">
                            <Search className="w-8 h-8 text-blue-500" />
                        </div>
                        <h3 className="text-xl font-bold text-slate-900 mb-2">
                            {t('categories.noSearchResults', 'لم يتم العثور على نتائج تطابق بحثك')}
                        </h3>
                        <p className="text-slate-500 text-sm mb-6 leading-relaxed">
                            {t('categories.noSearchDesc', 'جرّب كتابة كلمة بحث أخرى أو قم بإعادة ضبط البحث لرؤية كافة المجالات.')}
                        </p>
                        <button
                            onClick={() => setSearchTerm('')}
                            className="inline-flex items-center gap-2 bg-[#004C97] hover:bg-[#071942] text-white font-bold py-2.5 px-6 rounded-xl text-sm transition-all"
                        >
                            <span>{t('categories.clearSearch', 'إعادة ضبط البحث')}</span>
                            <X className="w-4 h-4" />
                        </button>
                    </motion.div>
                ) : (
                    /* Total Empty Categories State */
                    <motion.div
                        initial={{ opacity: 0, scale: 0.95 }}
                        animate={{ opacity: 1, scale: 1 }}
                        className="bg-white rounded-3xl border border-slate-200/80 p-12 text-center max-w-lg mx-auto shadow-sm"
                    >
                        <div className="w-16 h-16 bg-amber-50 text-amber-600 rounded-2xl flex items-center justify-center mx-auto mb-4">
                            <Layers className="w-8 h-8 text-amber-500" />
                        </div>
                        <h3 className="text-2xl font-bold text-slate-900 mb-2">
                            {t('categories.noCategories', 'لا توجد تصنيفات متاحة حالياً')}
                        </h3>
                        <p className="text-slate-500 text-sm mb-6 leading-relaxed">
                            جاري إضافة وتحديث التصنيفات والمجالات التدريبية قريباً.
                        </p>
                        <button
                            onClick={fetchCategories}
                            className="inline-flex items-center gap-2 bg-[#004C97] hover:bg-[#071942] text-white font-bold py-3 px-6 rounded-xl text-sm transition-all"
                        >
                            <RotateCcw className="w-4 h-4" />
                            <span>{t('common.tryAgain', 'تحديث الصفحة')}</span>
                        </button>
                    </motion.div>
                )}

            </main>
        </div>
    );
};

