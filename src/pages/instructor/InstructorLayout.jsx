import { useState, useMemo, useEffect, useRef } from 'react';
import { useTranslation } from 'react-i18next';
import { Link, Outlet, useLocation, useNavigate } from 'react-router-dom';
import { useAuth } from '../../context/AuthContext';
import ProtectedRoute from '../../components/layouts/ProtectedRoute';
import NotificationBell from '../../components/shared/NotificationBell';
import {
    LayoutDashboard,
    BookOpen,
    PlusCircle,
    GraduationCap,
    User,
    Settings,
    LogOut,
    Menu,
    X,
    Moon,
    Sun,
    Languages,
    Sparkles,
    CheckCircle2,
    Layers,
    Plus,
    Compass,
    Bell
} from 'lucide-react';

const InstructorLayout = () => {
    const { t, i18n } = useTranslation();
    const { user, logout } = useAuth();
    const location = useLocation();
    const navigate = useNavigate();
    const [isSidebarOpen, setIsSidebarOpen] = useState(false);
    const mainContentRef = useRef(null);

    // Keep window scroll locked at 0 so inner layout is never displaced
    useEffect(() => {
        const handleWindowScroll = () => {
            if (window.scrollY !== 0 || window.scrollX !== 0) {
                window.scrollTo(0, 0);
            }
        };
        window.addEventListener('scroll', handleWindowScroll, { passive: true });
        window.scrollTo(0, 0);
        return () => window.removeEventListener('scroll', handleWindowScroll);
    }, []);

    // Dark mode state synchronized with localStorage
    const [isDark, setIsDark] = useState(() => {
        return localStorage.getItem('theme') === 'dark' ||
            (!('theme' in localStorage) && window.matchMedia('(prefers-color-scheme: dark)').matches);
    });

    useEffect(() => {
        if (isDark) {
            document.documentElement.classList.add('dark');
            localStorage.setItem('theme', 'dark');
        } else {
            document.documentElement.classList.remove('dark');
            localStorage.setItem('theme', 'light');
        }
    }, [isDark]);

    const toggleDarkMode = () => setIsDark(!isDark);

    const toggleLanguage = () => {
        const newLang = i18n.language === 'ar' ? 'en' : 'ar';
        i18n.changeLanguage(newLang);
        document.documentElement.dir = newLang === 'ar' ? 'rtl' : 'ltr';
        document.documentElement.lang = newLang;
    };

    // Close mobile drawer and reset container scroll on route transition
    useEffect(() => {
        setIsSidebarOpen(false);
        if (mainContentRef.current) {
            mainContentRef.current.scrollTo({ top: 0, behavior: 'instant' });
        }
        window.scrollTo({ top: 0, left: 0, behavior: 'instant' });
    }, [location.pathname]);

    const handleLogout = async () => {
        const result = await logout();
        if (result?.redirectPath) {
            navigate(result.redirectPath);
        } else {
            navigate('/login');
        }
    };

    const isRtl = i18n.language === 'ar';

    // Navigation items grouped by category
    const navigationGroups = useMemo(() => [
        {
            title: t('autoGenerated.teaching_courses', `Teaching & Courses`),
            items: [
                {
                    path: '/instructor/dashboard',
                    label: t('nav.instructorNav.dashboard', 'لوحة التحكم'),
                    icon: <LayoutDashboard className="h-4.5 w-4.5" />
                },
                {
                    path: '/instructor/courses',
                    label: t('nav.instructorNav.courses', 'دوراتي التدريبية'),
                    icon: <BookOpen className="h-4.5 w-4.5" />
                },
                {
                    path: '/instructor/courses-create',
                    label: t('nav.instructorNav.createCourse', 'إنشاء دورة جديدة'),
                    icon: <PlusCircle className="h-4.5 w-4.5" />
                },
                {
                    path: '/instructor/my-courses',
                    label: t('nav.instructorNav.enrolledCourses', 'الدورات المسجل بها'),
                    icon: <GraduationCap className="h-4.5 w-4.5" />
                }
            ]
        },
        {
            title: t('autoGenerated.account_settings', `Account & Settings`),
            items: [
                {
                    path: '/instructor/profile-settings',
                    label: t('nav.instructorNav.profileSettings', 'الملف الشخصي'),
                    icon: <User className="h-4.5 w-4.5" />
                },
                {
                    path: '/instructor/notifications',
                    label: t('nav.instructorNav.notifications', 'التنبيهات والإشعارات'),
                    icon: <Bell className="h-4.5 w-4.5" />
                },
                {
                    path: '/instructor/account-settings',
                    label: t('nav.instructorNav.accountSettings', 'إعدادات الحساب والأمان'),
                    icon: <Settings className="h-4.5 w-4.5" />
                }
            ]
        }
    ], [t, isRtl]);

    // Current page title for topbar breadcrumb
    const currentItem = useMemo(() => {
        return navigationGroups.flatMap(g => g.items).find(item =>
            location.pathname === item.path ||
            (item.path !== '/instructor/dashboard' && location.pathname.startsWith(item.path + '/'))
        );
    }, [navigationGroups, location.pathname]);

    return (
        <ProtectedRoute allowedRoles={['instructor', 'admin']} requireVerified={true}>
            <div className={`h-screen flex overflow-hidden font-sans transition-colors duration-300 ${
                isDark ? 'dark bg-slate-950 text-slate-100' : 'bg-slate-50/80 text-slate-900'
            }`}>

                {/* Mobile Drawer Overlay */}
                {isSidebarOpen && (
                    <div
                        className="fixed inset-0 bg-slate-950/60 backdrop-blur-xs z-40 lg:hidden transition-opacity duration-300"
                        onClick={() => setIsSidebarOpen(false)}
                    />
                )}

                {/* SIDEBAR */}
                <aside
                    className={`
                        fixed lg:static inset-y-0 start-0 z-50 
                        w-72 lg:w-68 h-full 
                        bg-white dark:bg-slate-900 
                        border-e border-slate-200/80 dark:border-slate-800 
                        shadow-2xl lg:shadow-none 
                        flex flex-col shrink-0
                        transform transition-transform duration-300 ease-in-out
                        ${isSidebarOpen
                            ? 'translate-x-0'
                            : (t('autoGenerated.translate_x_full_lg_translate_', `-translate-x-full lg:translate-x-0`))
                        }
                    `}
                >
                    {/* Sidebar Brand Header */}
                    <div className="h-16 px-5 flex items-center justify-between border-b border-slate-100 dark:border-slate-800 shrink-0">
                        <Link to="/instructor/dashboard" className="flex items-center gap-3 group">
                            <div className="w-10 h-10 rounded-xl bg-gradient-to-tr from-blue-600 via-indigo-600 to-purple-600 flex items-center justify-center text-white font-black text-base shadow-md shadow-blue-600/30 group-hover:scale-105 transition-transform">
                                AEC
                            </div>
                            <div>
                                <span className="font-extrabold text-base text-slate-900 dark:text-white tracking-tight block leading-tight">
                                    {t('autoGenerated.aec_academy', 'أكاديمية AEC')}
                                </span>
                                <span className="text-[11px] font-bold text-indigo-600 dark:text-indigo-400 block mt-0.5">
                                    {t('autoGenerated.instructor_portal', `Instructor Portal`)}
                                </span>
                            </div>
                        </Link>

                        <button
                            onClick={() => setIsSidebarOpen(false)}
                            className="lg:hidden p-1.5 rounded-lg text-slate-500 hover:text-slate-800 dark:hover:text-white hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors"
                            aria-label="Close Sidebar"
                        >
                            <X className="w-5 h-5" />
                        </button>
                    </div>

                    {/* Scrollable Navigation Groups */}
                    <div className="flex-1 overflow-y-auto custom-scrollbar px-3 py-3 space-y-6">
                        {navigationGroups.map((group, gIdx) => (
                            <div key={gIdx}>
                                <h3 className="px-3 mb-2 text-[11px] font-bold text-slate-400 dark:text-slate-500 uppercase tracking-wider">
                                    {group.title}
                                </h3>
                                <nav className="space-y-1">
                                    {group.items.map((item) => {
                                        const isActive = location.pathname === item.path ||
                                            (item.path !== '/instructor/dashboard' && location.pathname.startsWith(item.path + '/'));

                                        return (
                                            <Link
                                                key={item.path}
                                                to={item.path}
                                                onClick={() => setIsSidebarOpen(false)}
                                                className={`group flex items-center gap-3 px-3.5 py-2.5 rounded-xl transition-all duration-200 text-sm font-semibold ${
                                                    isActive
                                                        ? 'bg-gradient-to-r from-blue-600 to-indigo-600 text-white shadow-md shadow-blue-500/25'
                                                        : 'text-slate-600 dark:text-slate-400 hover:bg-slate-100/80 dark:hover:bg-slate-800/80 hover:text-slate-900 dark:hover:text-white'
                                                }`}
                                            >
                                                <span className={`shrink-0 transition-transform duration-200 group-hover:scale-110 ${
                                                    isActive
                                                        ? 'text-white'
                                                        : 'text-slate-400 dark:text-slate-500 group-hover:text-blue-600 dark:group-hover:text-blue-400'
                                                }`}>
                                                    {item.icon}
                                                </span>
                                                <span className="truncate">{item.label}</span>
                                            </Link>
                                        );
                                    })}
                                </nav>
                            </div>
                        ))}
                    </div>

                    {/* Sidebar Footer Controls & Logout */}
                    <div className="p-3 border-t border-slate-100 dark:border-slate-800 shrink-0 space-y-2">
                        {/* Instructor Verified Badge */}
                        <div className="px-3 py-2 rounded-xl bg-slate-50 dark:bg-slate-800/50 border border-slate-100 dark:border-slate-800/80 flex items-center gap-2 text-xs">
                            <CheckCircle2 className="w-4 h-4 text-emerald-500 shrink-0" />
                            <div className="min-w-0">
                                <span className="font-bold text-slate-800 dark:text-slate-200 block truncate">
                                    {t('autoGenerated.verified_instructor', `Verified Instructor`)}
                                </span>
                                <span className="text-[10px] text-slate-400 block truncate">
                                    {user?.email}
                                </span>
                            </div>
                        </div>

                        {/* Logout Button */}
                        <button
                            onClick={handleLogout}
                            className="w-full flex items-center justify-center gap-2.5 px-3 py-2.5 rounded-xl text-rose-600 dark:text-rose-400 hover:bg-rose-50 dark:hover:bg-rose-950/40 font-semibold text-sm transition-colors cursor-pointer"
                        >
                            <LogOut className="w-4 h-4" />
                            <span>{t('common.logout', 'تسجيل الخروج')}</span>
                        </button>
                    </div>
                </aside>

                {/* MAIN CONTENT AREA */}
                <div className="flex-1 flex flex-col min-w-0 h-full overflow-hidden bg-slate-50/60 dark:bg-slate-950">

                    {/* TOPBAR */}
                    <header className="h-16 bg-white dark:bg-slate-900 border-b border-slate-200/80 dark:border-slate-800 px-4 sm:px-6 flex items-center justify-between shrink-0 z-20 shadow-xs">
                        
                        {/* Start side: Mobile Menu Toggle + Breadcrumb Title */}
                        <div className="flex items-center gap-3">
                            <button
                                onClick={() => setIsSidebarOpen(true)}
                                className="lg:hidden p-2 rounded-xl text-slate-600 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors"
                                aria-label="Open Sidebar"
                            >
                                <Menu className="w-5 h-5" />
                            </button>

                            <div className="flex items-center gap-2 font-bold text-sm sm:text-base">
                                <span className="text-slate-400 dark:text-slate-500 hidden sm:inline">
                                    {t('autoGenerated.instructor_portal', `Instructor Portal`)}
                                </span>
                                <span className="text-slate-300 dark:text-slate-600 hidden sm:inline">/</span>
                                <span className="text-slate-900 dark:text-white">
                                    {currentItem?.label || t('nav.instructorNav.dashboard', 'لوحة التحكم')}
                                </span>
                            </div>
                        </div>

                        {/* End side: Quick Action Buttons & Profile */}
                        <div className="flex items-center gap-2 sm:gap-3">
                            
                            {/* Explore Courses Link */}
                            <Link
                                to="/explore"
                                title={t('autoGenerated.explore_platform', 'تصفح المنصة')}
                                className="inline-flex items-center gap-1.5 px-2.5 sm:px-3 py-1.5 rounded-xl bg-blue-50 dark:bg-blue-950/50 text-blue-600 dark:text-blue-400 hover:bg-blue-100 dark:hover:bg-blue-900/50 font-semibold text-xs transition-colors"
                            >
                                <Compass className="w-4 h-4 sm:w-3.5 sm:h-3.5 shrink-0" />
                                <span className="hidden sm:inline">{t('autoGenerated.explore_platform', 'تصفح المنصة')}</span>
                            </Link>

                            {/* Create Course Topbar Button */}
                            <Link
                                to="/instructor/courses-create"
                                className="hidden md:inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-indigo-50 dark:bg-indigo-950/50 text-indigo-600 dark:text-indigo-400 hover:bg-indigo-100 dark:hover:bg-indigo-900/50 font-semibold text-xs transition-colors"
                            >
                                <Plus className="w-3.5 h-3.5" />
                                <span>{t('autoGenerated.new_course', `New Course`)}</span>
                            </Link>

                            {/* In-app Notification Bell */}
                            <NotificationBell />

                            {/* Language Switch */}
                            <button
                                onClick={toggleLanguage}
                                className="p-2 rounded-xl text-slate-500 hover:text-slate-800 dark:hover:text-white hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors flex items-center gap-1 text-xs font-bold cursor-pointer"
                                title={t('autoGenerated.change_language', 'تغيير اللغة')}
                            >
                                <Languages className="w-4.5 h-4.5" />
                                <span className="hidden sm:inline">{i18n.language === 'ar' ? 'EN' : t('autoGenerated.arabic', 'عربي')}</span>
                            </button>

                            {/* Dark Mode Switch */}
                            <button
                                onClick={toggleDarkMode}
                                className="p-2 rounded-xl text-slate-500 hover:text-slate-800 dark:hover:text-white hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors cursor-pointer"
                                title={t('autoGenerated.change_theme', 'تغيير المظهر')}
                            >
                                {isDark ? <Sun className="w-4.5 h-4.5 text-amber-400" /> : <Moon className="w-4.5 h-4.5" />}
                            </button>

                            <div className="w-px h-6 bg-slate-200 dark:bg-slate-800 mx-1 hidden sm:block" />

                            {/* Instructor Avatar & Profile Link */}
                            <Link to="/instructor/profile-settings" className="flex items-center gap-2.5 group">
                                <div className="w-8 h-8 rounded-xl ring-2 ring-indigo-500/20 overflow-hidden bg-gradient-to-tr from-blue-600 to-indigo-600 flex items-center justify-center text-white font-bold text-xs shrink-0">
                                    {user?.photo ? (
                                        <img src={user.photo} alt={user.firstName} className="w-full h-full object-cover" />
                                    ) : (
                                        <span>{(user?.firstName?.[0] || 'I').toUpperCase()}</span>
                                    )}
                                </div>
                                <div className="hidden md:block text-start">
                                    <span className="text-xs font-bold text-slate-700 dark:text-slate-300 group-hover:text-blue-600 dark:group-hover:text-blue-400 transition-colors block max-w-[110px] truncate leading-tight">
                                        {user?.firstName ? `${user.firstName} ${user.lastName || ''}`.trim() : (user?.name || t('autoGenerated.instructor', 'المحاضر'))}
                                    </span>
                                    <span className="text-[10px] text-slate-400 block leading-tight">
                                        {t('autoGenerated.instructor', `Instructor`)}
                                    </span>
                                </div>
                            </Link>
                        </div>
                    </header>

                    {/* SCROLLABLE OUTLET CONTAINER */}
                    <main ref={mainContentRef} className="flex-1 overflow-y-auto custom-scrollbar">
                        <Outlet />
                    </main>

                </div>

            </div>
        </ProtectedRoute>
    );
};

export default InstructorLayout;
