import { useState, useEffect, useCallback, useMemo, useRef } from 'react';
import { useTranslation } from 'react-i18next';
import { useLanguage } from '../../hooks/useLanguage';
import { toast } from 'react-toastify';
import { Link, useNavigate } from 'react-router-dom';
import { instructorService } from '../../services/new-api';
import {
    BookOpen,
    Plus,
    Search,
    Users,
    DollarSign,
    Star,
    Edit3,
    Eye,
    CheckCircle2,
    Clock,
    AlertCircle,
    Layers,
    Sparkles,
    ChevronLeft,
    ChevronRight,
    RefreshCw,
    Filter,
    ArrowUpRight,
    Loader2
} from 'lucide-react';

const PAGE_SIZE = 12;

const InstructorCourses = () => {
    const { t } = useTranslation();
    const { isRTL } = useLanguage();
    const navigate = useNavigate();

    const [courses, setCourses] = useState([]);
    const [loading, setLoading] = useState(true);
    const [activeFilter, setActiveFilter] = useState('all');
    const [searchQuery, setSearchQuery] = useState('');
    const [page, setPage] = useState(1);
    const [pagination, setPagination] = useState({ total: 0, pages: 1, page: 1, limit: PAGE_SIZE });
    const [stats, setStats] = useState({ total: 0, approved: 0, pending: 0 });
    const cacheRef = useRef({});

    const fetchInstructorCourses = useCallback(async (force = false) => {
        const cacheKey = `${page}_${activeFilter}`;
        const cached = cacheRef.current[cacheKey];
        const isFresh = cached && (Date.now() - cached.timestamp < 30000); // 30s cache TTL

        // Instant render from cache if available
        if (cached && !force) {
            setCourses(cached.courses);
            if (cached.pagination) setPagination(cached.pagination);
            if (cached.stats) setStats(cached.stats);
            setLoading(false);
            if (isFresh) return; // Data is fresh, no background fetch needed
        } else {
            setLoading(true);
        }

        try {
            const response = await instructorService.getInstructorCourses({
                page,
                limit: PAGE_SIZE,
                status: activeFilter
            });

            const list = response?.courses || (Array.isArray(response) ? response : []);
            setCourses(list);
            if (response?.pagination) {
                setPagination(response.pagination);
            }
            if (response?.stats) {
                setStats(response.stats);
            }

            // Save to SWR cache
            cacheRef.current[cacheKey] = {
                courses: list,
                pagination: response?.pagination,
                stats: response?.stats,
                timestamp: Date.now()
            };
        } catch (error) {
            if (!cached) {
                toast.error(t('instructor.courses.fetchFailed', 'تعذّر تحميل الدورات التدريبية'));
                setCourses([]);
            }
            console.error(error);
        } finally {
            setLoading(false);
        }
    }, [page, activeFilter, t]);

    useEffect(() => {
        fetchInstructorCourses();
    }, [fetchInstructorCourses]);

    const filterCourses = (filter) => {
        setActiveFilter(filter);
        setPage(1);
    };

    // Client-side search filtering
    const filteredCourses = useMemo(() => {
        if (!searchQuery.trim()) return courses;
        return courses.filter(course =>
            course.title?.toLowerCase().includes(searchQuery.toLowerCase()) ||
            course.category?.toLowerCase().includes(searchQuery.toLowerCase())
        );
    }, [courses, searchQuery]);

    // Status Badge Helpers
    const getStatusBadge = (status) => {
        switch (status) {
            case 'published':
            case 'approved':
                return {
                    label: t('autoGenerated.approved', `Approved`),
                    className: 'bg-emerald-50 dark:bg-emerald-950/50 text-emerald-600 dark:text-emerald-400 border border-emerald-200 dark:border-emerald-800/60',
                    icon: <CheckCircle2 className="w-3 h-3" />
                };
            case 'pending':
                return {
                    label: t('autoGenerated.pending_review', `Pending Review`),
                    className: 'bg-amber-50 dark:bg-amber-950/50 text-amber-600 dark:text-amber-400 border border-amber-200 dark:border-amber-800/60',
                    icon: <Clock className="w-3 h-3" />
                };
            case 'rejected':
                return {
                    label: t('autoGenerated.rejected', `Rejected`),
                    className: 'bg-rose-50 dark:bg-rose-950/50 text-rose-600 dark:text-rose-400 border border-rose-200 dark:border-rose-800/60',
                    icon: <AlertCircle className="w-3 h-3" />
                };
            default:
                return {
                    label: t('autoGenerated.draft', `Draft`),
                    className: 'bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-300 border border-slate-200 dark:border-slate-700',
                    icon: <Layers className="w-3 h-3" />
                };
        }
    };

    return (
        <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-6 sm:py-8 space-y-8" dir={t('autoGenerated.ltr', `ltr`)}>

            {/* HEADER BAR */}
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
                <div className="space-y-1">
                    <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-bold bg-blue-50 dark:bg-blue-950/50 text-blue-600 dark:text-blue-400 border border-blue-200/50 dark:border-blue-900/40">
                        <BookOpen className="w-3.5 h-3.5" />
                        <span>{t('autoGenerated.course_management_studio', `Course Management Studio`)}</span>
                    </div>
                    <h1 className="text-2xl sm:text-3xl font-extrabold text-slate-900 dark:text-white tracking-tight">
                        {t('instructor.courses.title', 'دوراتي التدريبية')}
                    </h1>
                    <p className="text-sm text-slate-500 dark:text-slate-400">
                        {t('autoGenerated.manage_your_courses_edit_lectu', `Manage your courses, edit lectures, and monitor student enrollments`)}
                    </p>
                </div>

                <div className="flex items-center gap-3">
                    <button
                        onClick={() => fetchInstructorCourses(true)}
                        disabled={loading}
                        className="p-2.5 rounded-xl border border-slate-200 dark:border-slate-800 text-slate-600 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors cursor-pointer"
                        title={t('autoGenerated.refresh', `Refresh`)}
                    >
                        <RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin text-blue-600' : ''}`} />
                    </button>

                    <Link
                        to="/instructor/courses-create"
                        className="inline-flex items-center gap-2 px-5 py-2.5 rounded-2xl bg-gradient-to-r from-blue-600 to-indigo-600 hover:from-blue-700 hover:to-indigo-700 text-white font-bold text-sm shadow-md shadow-blue-500/20 transition-all hover:scale-105 active:scale-98"
                    >
                        <Plus className="w-4 h-4" />
                        <span>{t('instructor.courses.createNew', 'إنشاء دورة جديدة')}</span>
                    </Link>
                </div>
            </div>

            {/* STATS OVERVIEW CARDS */}
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
                
                {/* Total Courses */}
                <button
                    onClick={() => filterCourses('all')}
                    className={`p-5 rounded-3xl border text-start transition-all cursor-pointer ${
                        activeFilter === 'all'
                            ? 'bg-blue-50/60 dark:bg-blue-950/30 border-blue-600 ring-2 ring-blue-500/20'
                            : 'bg-white dark:bg-slate-900 border-slate-200/80 dark:border-slate-800 hover:border-slate-300 dark:hover:border-slate-700'
                    }`}
                >
                    <div className="flex items-center justify-between mb-2">
                        <span className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                            {t('autoGenerated.total_courses', `Total Courses`)}
                        </span>
                        <div className="w-8 h-8 rounded-xl bg-blue-100 dark:bg-blue-900/50 text-blue-600 dark:text-blue-400 flex items-center justify-center">
                            <BookOpen className="w-4 h-4" />
                        </div>
                    </div>
                    <div className="text-2xl font-black text-slate-900 dark:text-white">
                        {stats.total || courses.length}
                    </div>
                </button>

                {/* Approved Courses */}
                <button
                    onClick={() => filterCourses('approved')}
                    className={`p-5 rounded-3xl border text-start transition-all cursor-pointer ${
                        activeFilter === 'approved'
                            ? 'bg-emerald-50/60 dark:bg-emerald-950/30 border-emerald-600 ring-2 ring-emerald-500/20'
                            : 'bg-white dark:bg-slate-900 border-slate-200/80 dark:border-slate-800 hover:border-slate-300 dark:hover:border-slate-700'
                    }`}
                >
                    <div className="flex items-center justify-between mb-2">
                        <span className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                            {t('autoGenerated.approved_live', `Approved / Live`)}
                        </span>
                        <div className="w-8 h-8 rounded-xl bg-emerald-100 dark:bg-emerald-900/50 text-emerald-600 dark:text-emerald-400 flex items-center justify-center">
                            <CheckCircle2 className="w-4 h-4" />
                        </div>
                    </div>
                    <div className="text-2xl font-black text-emerald-600 dark:text-emerald-400">
                        {stats.approved || 0}
                    </div>
                </button>

                {/* Pending Review Courses */}
                <button
                    onClick={() => filterCourses('pending')}
                    className={`p-5 rounded-3xl border text-start transition-all cursor-pointer ${
                        activeFilter === 'pending'
                            ? 'bg-amber-50/60 dark:bg-amber-950/30 border-amber-600 ring-2 ring-amber-500/20'
                            : 'bg-white dark:bg-slate-900 border-slate-200/80 dark:border-slate-800 hover:border-slate-300 dark:hover:border-slate-700'
                    }`}
                >
                    <div className="flex items-center justify-between mb-2">
                        <span className="text-xs font-bold text-slate-400 uppercase tracking-wider">
                            {t('autoGenerated.under_review', `Under Review`)}
                        </span>
                        <div className="w-8 h-8 rounded-xl bg-amber-100 dark:bg-amber-900/50 text-amber-600 dark:text-amber-400 flex items-center justify-center">
                            <Clock className="w-4 h-4" />
                        </div>
                    </div>
                    <div className="text-2xl font-black text-amber-600 dark:text-amber-400">
                        {stats.pending || 0}
                    </div>
                </button>

            </div>

            {/* SEARCH AND FILTER BAR */}
            <div className="flex flex-col sm:flex-row items-center justify-between gap-3">
                <div className="relative w-full sm:w-80">
                    <Search className="w-4 h-4 absolute start-3.5 top-1/2 -translate-y-1/2 text-slate-400" />
                    <input
                        type="text"
                        value={searchQuery}
                        onChange={(e) => setSearchQuery(e.target.value)}
                        placeholder={t('autoGenerated.search_by_course_title', `Search by course title...`)}
                        className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl ps-10 pe-4 py-2.5 text-sm text-slate-900 dark:text-white placeholder:text-slate-400 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-600 transition-all shadow-xs"
                    />
                </div>

                <div className="text-xs font-semibold text-slate-400">
                    {filteredCourses.length} {t('autoGenerated.courses_found', `courses found`)}
                </div>
            </div>

            {/* COURSES GRID */}
            {loading ? (
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-16 text-center space-y-3">
                    <Loader2 className="w-8 h-8 animate-spin text-blue-600 mx-auto" />
                    <p className="text-sm font-semibold text-slate-500">{t('autoGenerated.loading_courses', `Loading courses...`)}</p>
                </div>
            ) : filteredCourses.length === 0 ? (
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-12 sm:p-16 text-center space-y-4 shadow-xs">
                    <div className="w-16 h-16 rounded-2xl bg-blue-50 dark:bg-blue-950/50 text-blue-600 dark:text-blue-400 flex items-center justify-center mx-auto">
                        <BookOpen className="w-8 h-8" />
                    </div>
                    <div className="space-y-1">
                        <h3 className="text-lg font-bold text-slate-900 dark:text-white">
                            {t('instructor.courses.noCoursesTitle', 'لا توجد دورات مسجلة بهذا الفلتر')}
                        </h3>
                        <p className="text-xs text-slate-500 dark:text-slate-400 max-w-sm mx-auto">
                            {t('instructor.courses.noCoursesDesc', 'يمكنك البدء الآن بإنشاء دورتك التدريبية الأولى وإضافة محتواها الأكاديمي.')}
                        </p>
                    </div>
                    <Link
                        to="/instructor/courses/create"
                        className="inline-flex items-center gap-2 px-6 py-2.5 rounded-2xl bg-blue-600 hover:bg-blue-700 text-white font-bold text-xs shadow-md shadow-blue-500/20 transition-all cursor-pointer"
                    >
                        <Plus className="w-4 h-4" />
                        <span>{t('instructor.courses.createFirst', 'إنشاء دورة جديدة')}</span>
                    </Link>
                </div>
            ) : (
                <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-6">
                    {filteredCourses.map((course) => {
                        const statusBadge = getStatusBadge(course.status);
                        return (
                            <div
                                key={course._id || course.id}
                                className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 overflow-hidden shadow-xs hover:shadow-lg transition-all duration-300 flex flex-col group"
                            >
                                {/* Thumbnail */}
                                <div className="relative aspect-video w-full overflow-hidden bg-slate-100 dark:bg-slate-800">
                                    {course.thumbnail ? (
                                        <img
                                            src={course.thumbnail}
                                            alt={course.title}
                                            className="w-full h-full object-cover transition-transform duration-500 group-hover:scale-105"
                                        />
                                    ) : (
                                        <div className="w-full h-full flex items-center justify-center text-slate-400">
                                            <BookOpen className="w-10 h-10 stroke-[1.5]" />
                                        </div>
                                    )}

                                    {/* Status Badge */}
                                    <div className="absolute top-3 end-3">
                                        <span className={`inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-[11px] font-bold shadow-xs backdrop-blur-md ${statusBadge.className}`}>
                                            {statusBadge.icon}
                                            <span>{statusBadge.label}</span>
                                        </span>
                                    </div>

                                    {/* Course Type Badge */}
                                    {course.courseType && (
                                        <div className="absolute bottom-3 start-3">
                                            <span className="px-2.5 py-0.5 rounded-lg text-[10px] font-bold bg-black/60 text-white backdrop-blur-md uppercase">
                                                {course.courseType}
                                            </span>
                                        </div>
                                    )}
                                </div>

                                {/* Body */}
                                <div className="p-5 flex-1 flex flex-col justify-between space-y-4">
                                    <div className="space-y-2">
                                        <h3 className="font-extrabold text-sm sm:text-base text-slate-900 dark:text-white line-clamp-2 leading-snug group-hover:text-blue-600 dark:group-hover:text-blue-400 transition-colors">
                                            {course.title}
                                        </h3>

                                        {course.category && (
                                            <span className="inline-block text-xs font-semibold text-blue-600 dark:text-blue-400">
                                                {course.category}
                                            </span>
                                        )}
                                    </div>

                                    {/* Metrics (Students & Revenue) */}
                                    <div className="pt-3 border-t border-slate-100 dark:border-slate-800 grid grid-cols-2 gap-2 text-xs">
                                        <div className="space-y-0.5">
                                            <span className="text-[11px] text-slate-400 block font-medium">{t('autoGenerated.enrolled_students', 'الطلاب المسجلون')}</span>
                                            <span className="font-bold text-slate-800 dark:text-slate-200 flex items-center gap-1">
                                                <Users className="w-3.5 h-3.5 text-blue-500" />
                                                <span>{course.students || 0}</span>
                                            </span>
                                        </div>
                                        <div className="space-y-0.5 text-end">
                                            <span className="text-[11px] text-slate-400 block font-medium">{t('autoGenerated.total_sales', 'إجمالي المبيعات')}</span>
                                            <span className="font-extrabold text-emerald-600 dark:text-emerald-400">
                                                {(course.revenue || 0).toLocaleString()} ر.س
                                            </span>
                                        </div>
                                    </div>

                                    {/* Action Buttons */}
                                    <div className="pt-2 flex items-center gap-2">
                                        <Link
                                            to={`/instructor/courses/${course._id || course.id}/edit`}
                                            className="flex-1 flex items-center justify-center gap-1.5 px-3 py-2 rounded-xl bg-blue-50 dark:bg-blue-950/50 hover:bg-blue-100 dark:hover:bg-blue-900/50 text-blue-600 dark:text-blue-400 text-xs font-bold transition-colors"
                                        >
                                            <Edit3 className="w-3.5 h-3.5" />
                                            <span>{t('instructor.courses.edit', 'تعديل الدورة')}</span>
                                        </Link>

                                        <Link
                                            to={`/course/${course._id || course.id}`}
                                            target="_blank"
                                            className="p-2 rounded-xl border border-slate-200 dark:border-slate-800 text-slate-500 hover:text-slate-900 dark:hover:text-white hover:bg-slate-50 dark:hover:bg-slate-800 transition-colors"
                                            title={t('autoGenerated.preview_course_students', 'معاينة الدورة كما تظهر للطلاب')}
                                        >
                                            <Eye className="w-4 h-4" />
                                        </Link>
                                    </div>
                                </div>
                            </div>
                        );
                    })}
                </div>
            )}

            {/* PAGINATION */}
            {pagination.pages > 1 && (
                <div className="flex items-center justify-center gap-3 pt-6 border-t border-slate-200 dark:border-slate-800">
                    <button
                        type="button"
                        disabled={page <= 1}
                        onClick={() => setPage(p => Math.max(1, p - 1))}
                        className="inline-flex items-center gap-1 px-4 py-2 rounded-xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 text-xs font-bold disabled:opacity-40 hover:bg-slate-50 dark:hover:bg-slate-800 text-slate-700 dark:text-slate-300 transition-colors cursor-pointer"
                    >
                        {isRTL ? <ChevronRight className="w-4 h-4" /> : <ChevronLeft className="w-4 h-4" />}
                        <span>{t('common.previous', 'السابق')}</span>
                    </button>

                    <span className="text-xs font-bold text-slate-500 dark:text-slate-400">
                        {page} / {pagination.pages}
                    </span>

                    <button
                        type="button"
                        disabled={page >= pagination.pages}
                        onClick={() => setPage(p => Math.min(pagination.pages, p + 1))}
                        className="inline-flex items-center gap-1 px-4 py-2 rounded-xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 text-xs font-bold disabled:opacity-40 hover:bg-slate-50 dark:hover:bg-slate-800 text-slate-700 dark:text-slate-300 transition-colors cursor-pointer"
                    >
                        <span>{t('common.next', 'التالي')}</span>
                        {isRTL ? <ChevronLeft className="w-4 h-4" /> : <ChevronRight className="w-4 h-4" />}
                    </button>
                </div>
            )}

        </div>
    );
};

export default InstructorCourses;
