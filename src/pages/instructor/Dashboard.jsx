import { useState, useEffect, useMemo } from 'react';
import { useTranslation } from 'react-i18next';
import { Link } from 'react-router-dom';
import { useAuth } from '../../context/AuthContext';
import { useLanguage } from '../../hooks/useLanguage';
import { dashboardService } from '../../services/new-api';
import { toast } from 'react-toastify';
import {
    Users,
    BookOpen,
    DollarSign,
    Star,
    TrendingUp,
    CheckCircle2,
    Clock,
    PlusCircle,
    ArrowUpRight,
    BarChart3,
    Award,
    Calendar,
    Layers,
    ShieldCheck,
    RefreshCw,
    Sparkles,
    AlertCircle,
    GraduationCap,
    Plus,
    ChevronLeft,
    ChevronRight,
    Activity
} from 'lucide-react';

const Dashboard = () => {
    const { t } = useTranslation();
    const { user } = useAuth();
    const { isRTL } = useLanguage();
    const [stats, setStats] = useState(null);
    const [loading, setLoading] = useState(true);
    const [timeRange, setTimeRange] = useState('thisWeek');

    useEffect(() => {
        fetchDashboardData();
    }, []);

    const fetchDashboardData = async () => {
        try {
            setLoading(true);
            const dashboardData = await dashboardService.getInstructorDashboard();
            setStats(dashboardData);
        } catch (err) {
            console.error('Error fetching dashboard data:', err);
            toast.error(t('instructor.dashboard.toast.loadFailed', 'تعذّر تحميل بيانات لوحة التحكم'));
        } finally {
            setLoading(false);
        }
    };

    // Calculate metrics
    const metrics = useMemo(() => {
        if (!stats) return {
            totalStudents: 0,
            totalCourses: 0,
            totalRevenue: 0,
            averageRating: 0,
            activeStudents: 0,
            completionRate: '0%',
            weekStats: { newEnrollments: 0, revenue: 0, completions: 0 },
            courses: []
        };

        const overview = stats.overview || {};
        const totalEnrollments = (overview.processing || 0) + (overview.completed || 0) + (overview.canceled || 0);
        const completionRate = totalEnrollments > 0 ? Math.round(((overview.completed || 0) / totalEnrollments) * 100) : 0;

        return {
            totalStudents: overview.totalStudents || 0,
            totalCourses: overview.totalCourses || 0,
            totalRevenue: overview.totalSales || 0,
            averageRating: overview.averageRating || 0,
            activeStudents: overview.processing || 0,
            completedStudents: overview.completed || 0,
            completionRate: `${completionRate}%`,
            weekStats: stats.weekStats || { newEnrollments: 0, revenue: 0, completions: 0 },
            courses: stats.courses || []
        };
    }, [stats]);

    return (
        <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-6 sm:py-8 space-y-8" dir={t('autoGenerated.ltr', `ltr`)}>

            {/* HERO BANNER */}
            <div className="relative overflow-hidden rounded-3xl bg-gradient-to-br from-blue-700 via-indigo-800 to-slate-900 text-white shadow-xl shadow-blue-950/20 p-6 sm:p-10">
                {/* Decorative background glows */}
                <div className="absolute top-0 end-0 -mt-10 -me-10 w-80 h-80 rounded-full bg-blue-500/20 blur-3xl pointer-events-none" />
                <div className="absolute bottom-0 start-1/4 -mb-10 w-72 h-72 rounded-full bg-indigo-500/20 blur-2xl pointer-events-none" />

                <div className="relative z-10 flex flex-col lg:flex-row lg:items-center justify-between gap-6">
                    <div className="space-y-3 max-w-2xl">
                        <div className="flex flex-wrap items-center gap-2">
                            <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-bold bg-white/15 backdrop-blur-md text-blue-100 border border-white/10">
                                <Sparkles className="w-3.5 h-3.5 text-amber-300" />
                                <span>{t('autoGenerated.welcome_to_instructor_studio', `Welcome to Instructor Studio`)}</span>
                            </span>
                            <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-full text-xs font-semibold bg-emerald-500/20 text-emerald-200 border border-emerald-400/20">
                                <CheckCircle2 className="w-3 h-3 text-emerald-400" />
                                <span>{t('autoGenerated.verified_instructor', `Verified Instructor`)}</span>
                            </span>
                        </div>

                        <h1 className="text-2xl sm:text-4xl font-extrabold tracking-tight">
                            {t('instructor.dashboard.welcomeBack', {
                                name: user?.firstName ? `${user.firstName} ${user.lastName || ''}`.trim() : (user?.name || (t('autoGenerated.instructor', `Instructor`)))
                            })} 👋
                        </h1>

                        <p className="text-blue-100/90 text-sm sm:text-base leading-relaxed">
                            {t('autoGenerated.track_course_performance_monit', `Track course performance, monitor student enrollments, and manage your teaching revenue in real time.`)}
                        </p>
                    </div>

                    {/* Quick Action CTAs */}
                    <div className="flex flex-wrap sm:flex-nowrap items-center gap-3 shrink-0">
                        <Link
                            to="/instructor/courses-create"
                            className="w-full sm:w-auto inline-flex items-center justify-center gap-2 px-5 py-3 rounded-2xl bg-white text-indigo-900 hover:bg-blue-50 font-bold text-sm shadow-lg shadow-black/10 transition-all hover:scale-105 active:scale-98"
                        >
                            <Plus className="w-4 h-4 text-indigo-700" />
                            <span>{t('autoGenerated.create_course', `Create Course`)}</span>
                        </Link>

                        <Link
                            to="/instructor/courses"
                            className="w-full sm:w-auto inline-flex items-center justify-center gap-2 px-5 py-3 rounded-2xl bg-white/10 hover:bg-white/20 backdrop-blur-md text-white font-semibold text-sm border border-white/15 transition-all"
                        >
                            <BookOpen className="w-4 h-4" />
                            <span>{t('autoGenerated.my_courses', `My Courses`)}</span>
                        </Link>
                    </div>
                </div>
            </div>

            {/* PERFORMANCE METRICS GRID */}
            <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-6 gap-4 sm:gap-6">
                
                {/* Total Students */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs hover:shadow-md transition-shadow">
                    <div className="flex items-center justify-between mb-3">
                        <span className="text-xs font-bold text-slate-400 dark:text-slate-500 uppercase tracking-wider">
                            {t('instructor.dashboard.stats.totalStudents', 'إجمالي الطلاب')}
                        </span>
                        <div className="w-10 h-10 rounded-2xl bg-blue-50 dark:bg-blue-950/50 text-blue-600 dark:text-blue-400 flex items-center justify-center">
                            <Users className="w-5 h-5" />
                        </div>
                    </div>
                    <div className="text-2xl font-black text-slate-900 dark:text-white">
                        {loading ? '—' : metrics.totalStudents.toLocaleString()}
                    </div>
                    <span className="text-[11px] font-semibold text-emerald-600 dark:text-emerald-400 flex items-center gap-1 mt-1">
                        <TrendingUp className="w-3 h-3" />
                        <span>{t('autoGenerated.enrolled_learners', `enrolled learners`)}</span>
                    </span>
                </div>

                {/* Total Courses */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs hover:shadow-md transition-shadow">
                    <div className="flex items-center justify-between mb-3">
                        <span className="text-xs font-bold text-slate-400 dark:text-slate-500 uppercase tracking-wider">
                            {t('instructor.dashboard.stats.totalCourses', 'الدورات المنشورة')}
                        </span>
                        <div className="w-10 h-10 rounded-2xl bg-indigo-50 dark:bg-indigo-950/50 text-indigo-600 dark:text-indigo-400 flex items-center justify-center">
                            <BookOpen className="w-5 h-5" />
                        </div>
                    </div>
                    <div className="text-2xl font-black text-slate-900 dark:text-white">
                        {loading ? '—' : metrics.totalCourses}
                    </div>
                    <span className="text-[11px] font-semibold text-indigo-600 dark:text-indigo-400 flex items-center gap-1 mt-1">
                        <Layers className="w-3 h-3" />
                        <span>{t('autoGenerated.courses', `courses`)}</span>
                    </span>
                </div>

                {/* Total Revenue */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs hover:shadow-md transition-shadow">
                    <div className="flex items-center justify-between mb-3">
                        <span className="text-xs font-bold text-slate-400 dark:text-slate-500 uppercase tracking-wider">
                            {t('instructor.dashboard.stats.totalRevenue', 'إجمالي العوائد')}
                        </span>
                        <div className="w-10 h-10 rounded-2xl bg-emerald-50 dark:bg-emerald-950/50 text-emerald-600 dark:text-emerald-400 flex items-center justify-center">
                            <DollarSign className="w-5 h-5" />
                        </div>
                    </div>
                    <div className="text-2xl font-black text-slate-900 dark:text-white">
                        {loading ? '—' : metrics.totalRevenue.toLocaleString()}
                        <span className="text-xs font-bold text-slate-500 ms-1">{t('autoGenerated.currency_sar', 'ر.س')}</span>
                    </div>
                    <span className="text-[11px] font-semibold text-emerald-600 dark:text-emerald-400 flex items-center gap-1 mt-1">
                        <CheckCircle2 className="w-3 h-3" />
                        <span>{t('autoGenerated.verified_sales', `verified sales`)}</span>
                    </span>
                </div>

                {/* Average Rating */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs hover:shadow-md transition-shadow">
                    <div className="flex items-center justify-between mb-3">
                        <span className="text-xs font-bold text-slate-400 dark:text-slate-500 uppercase tracking-wider">
                            {t('instructor.dashboard.stats.averageRating', 'متوسط التقييم')}
                        </span>
                        <div className="w-10 h-10 rounded-2xl bg-amber-50 dark:bg-amber-950/50 text-amber-500 flex items-center justify-center">
                            <Star className="w-5 h-5 fill-amber-400" />
                        </div>
                    </div>
                    <div className="text-2xl font-black text-slate-900 dark:text-white flex items-center gap-1.5">
                        <span>{loading ? '—' : (metrics.averageRating || '5.0')}</span>
                        <span className="text-xs font-semibold text-amber-500">/ 5.0</span>
                    </div>
                    <span className="text-[11px] font-semibold text-amber-600 dark:text-amber-400 flex items-center gap-1 mt-1">
                        <Award className="w-3 h-3" />
                        <span>{t('autoGenerated.student_rating', `student rating`)}</span>
                    </span>
                </div>

                {/* Active Learning Students */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs hover:shadow-md transition-shadow">
                    <div className="flex items-center justify-between mb-3">
                        <span className="text-xs font-bold text-slate-400 dark:text-slate-500 uppercase tracking-wider">
                            {t('instructor.dashboard.stats.activeStudents', 'قيد التعلم')}
                        </span>
                        <div className="w-10 h-10 rounded-2xl bg-purple-50 dark:bg-purple-950/50 text-purple-600 dark:text-purple-400 flex items-center justify-center">
                            <Clock className="w-5 h-5" />
                        </div>
                    </div>
                    <div className="text-2xl font-black text-slate-900 dark:text-white">
                        {loading ? '—' : metrics.activeStudents}
                    </div>
                    <span className="text-[11px] font-semibold text-purple-600 dark:text-purple-400 flex items-center gap-1 mt-1">
                        <Activity className="w-3 h-3" />
                        <span>{t('autoGenerated.in_progress', `in progress`)}</span>
                    </span>
                </div>

                {/* Completion Rate */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs hover:shadow-md transition-shadow">
                    <div className="flex items-center justify-between mb-3">
                        <span className="text-xs font-bold text-slate-400 dark:text-slate-500 uppercase tracking-wider">
                            {t('instructor.dashboard.stats.completionRate', 'نسبة الإكمال')}
                        </span>
                        <div className="w-10 h-10 rounded-2xl bg-teal-50 dark:bg-teal-950/50 text-teal-600 dark:text-teal-400 flex items-center justify-center">
                            <GraduationCap className="w-5 h-5" />
                        </div>
                    </div>
                    <div className="text-2xl font-black text-slate-900 dark:text-white">
                        {loading ? '—' : metrics.completionRate}
                    </div>
                    <span className="text-[11px] font-semibold text-teal-600 dark:text-teal-400 flex items-center gap-1 mt-1">
                        <CheckCircle2 className="w-3 h-3" />
                        <span>{metrics.completedStudents} {t('autoGenerated.graduates', `graduates`)}</span>
                    </span>
                </div>

            </div>

            {/* TWO-COLUMN SECTION: WEEKLY HIGHLIGHTS & COURSES SNAPSHOT */}
            <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">

                {/* Left/Start: Weekly Pulse & Quick Insights (1 col) */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-6 sm:p-7 shadow-xs space-y-6">
                    <div className="flex items-center justify-between border-b border-slate-100 dark:border-slate-800/80 pb-4">
                        <div className="flex items-center gap-2.5">
                            <div className="p-2 rounded-xl bg-blue-50 dark:bg-blue-950/50 text-blue-600 dark:text-blue-400">
                                <Calendar className="w-5 h-5" />
                            </div>
                            <h2 className="text-base font-bold text-slate-900 dark:text-white">
                                {t('autoGenerated.this_week_s_activity', `This Week\'s Activity`)}
                            </h2>
                        </div>
                        <span className="text-xs font-bold text-slate-400">
                            {t('autoGenerated.past_7_days', `Past 7 days`)}
                        </span>
                    </div>

                    <div className="space-y-4">
                        <div className="p-4 rounded-2xl bg-slate-50 dark:bg-slate-800/40 border border-slate-100 dark:border-slate-800/80 flex items-center justify-between">
                            <div className="space-y-0.5">
                                <span className="text-xs text-slate-500 dark:text-slate-400 font-semibold block">
                                    {t('autoGenerated.new_enrollments', `New Enrollments`)}
                                </span>
                                <span className="text-xl font-black text-slate-900 dark:text-white">
                                    {metrics.weekStats.newEnrollments}
                                </span>
                            </div>
                            <div className="w-9 h-9 rounded-xl bg-blue-100 dark:bg-blue-900/50 text-blue-600 dark:text-blue-400 flex items-center justify-center">
                                <Users className="w-4 h-4" />
                            </div>
                        </div>

                        <div className="p-4 rounded-2xl bg-slate-50 dark:bg-slate-800/40 border border-slate-100 dark:border-slate-800/80 flex items-center justify-between">
                            <div className="space-y-0.5">
                                <span className="text-xs text-slate-500 dark:text-slate-400 font-semibold block">
                                    {t('autoGenerated.weekly_earnings', `Weekly Earnings`)}
                                </span>
                                <span className="text-xl font-black text-emerald-600 dark:text-emerald-400">
                                    {metrics.weekStats.revenue.toLocaleString()} <span className="text-xs">{t('autoGenerated.currency_sar', 'ر.س')}</span>
                                </span>
                            </div>
                            <div className="w-9 h-9 rounded-xl bg-emerald-100 dark:bg-emerald-900/50 text-emerald-600 dark:text-emerald-400 flex items-center justify-center">
                                <DollarSign className="w-4 h-4" />
                            </div>
                        </div>

                        <div className="p-4 rounded-2xl bg-slate-50 dark:bg-slate-800/40 border border-slate-100 dark:border-slate-800/80 flex items-center justify-between">
                            <div className="space-y-0.5">
                                <span className="text-xs text-slate-500 dark:text-slate-400 font-semibold block">
                                    {t('autoGenerated.completed_certifications', `Completed Certifications`)}
                                </span>
                                <span className="text-xl font-black text-purple-600 dark:text-purple-400">
                                    {metrics.weekStats.completions}
                                </span>
                            </div>
                            <div className="w-9 h-9 rounded-xl bg-purple-100 dark:bg-purple-900/50 text-purple-600 dark:text-purple-400 flex items-center justify-center">
                                <Award className="w-4 h-4" />
                            </div>
                        </div>
                    </div>

                    <div className="pt-2">
                        <Link
                            to="/instructor/courses/create"
                            className="w-full flex items-center justify-center gap-2 p-3 rounded-2xl border-2 border-dashed border-slate-300 dark:border-slate-700 hover:border-blue-500 dark:hover:border-blue-400 text-slate-600 dark:text-slate-300 hover:text-blue-600 dark:hover:text-blue-400 text-xs font-bold transition-colors"
                        >
                            <Plus className="w-4 h-4" />
                            <span>{t('autoGenerated.launch_new_course_workshop', `Launch New Course / Workshop`)}</span>
                        </Link>
                    </div>
                </div>

                {/* Right/End: Top Courses Performance (2 cols) */}
                <div className="lg:col-span-2 bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-6 sm:p-7 shadow-xs space-y-6">
                    <div className="flex items-center justify-between border-b border-slate-100 dark:border-slate-800/80 pb-4">
                        <div className="flex items-center gap-2.5">
                            <div className="p-2 rounded-xl bg-indigo-50 dark:bg-indigo-950/50 text-indigo-600 dark:text-indigo-400">
                                <BarChart3 className="w-5 h-5" />
                            </div>
                            <div>
                                <h2 className="text-base font-bold text-slate-900 dark:text-white">
                                    {t('autoGenerated.course_performance_overview', `Course Performance Overview`)}
                                </h2>
                                <p className="text-xs text-slate-500 dark:text-slate-400">
                                    {t('autoGenerated.students_and_revenue_breakdown', `Students and revenue breakdown by course`)}
                                </p>
                            </div>
                        </div>

                        <Link
                            to="/instructor/courses"
                            className="inline-flex items-center gap-1 text-xs font-bold text-blue-600 dark:text-blue-400 hover:underline"
                        >
                            <span>{t('autoGenerated.view_all', `View All`)}</span>
                            {isRTL ? <ChevronLeft className="w-4 h-4" /> : <ChevronRight className="w-4 h-4" />}
                        </Link>
                    </div>

                    {/* Courses List */}
                    {metrics.courses.length === 0 ? (
                        <div className="py-12 text-center space-y-3">
                            <div className="w-14 h-14 rounded-2xl bg-slate-100 dark:bg-slate-800 text-slate-400 flex items-center justify-center mx-auto">
                                <BookOpen className="w-7 h-7" />
                            </div>
                            <div className="space-y-1">
                                <h3 className="text-sm font-bold text-slate-900 dark:text-white">
                                    {t('autoGenerated.no_courses_created_yet', `No courses created yet`)}
                                </h3>
                                <p className="text-xs text-slate-400 max-w-sm mx-auto">
                                    {t('autoGenerated.start_by_creating_your_first_c', `Start by creating your first course and reach thousands of learners.`)}
                                </p>
                            </div>
                            <Link
                                to="/instructor/courses/create"
                                className="inline-flex items-center gap-2 px-4 py-2 rounded-xl bg-blue-600 hover:bg-blue-700 text-white text-xs font-bold transition-colors"
                            >
                                <Plus className="w-4 h-4" />
                                <span>{t('autoGenerated.create_first_course', `Create First Course`)}</span>
                            </Link>
                        </div>
                    ) : (
                        <div className="space-y-3">
                            {metrics.courses.slice(0, 5).map((course, idx) => (
                                <div
                                    key={course.id || idx}
                                    className="p-4 rounded-2xl bg-slate-50/70 dark:bg-slate-800/40 hover:bg-slate-100/70 dark:hover:bg-slate-800/80 border border-slate-100 dark:border-slate-800/80 flex flex-col sm:flex-row sm:items-center justify-between gap-3 transition-colors"
                                >
                                    <div className="flex items-center gap-3 min-w-0">
                                        <div className="w-10 h-10 rounded-xl bg-blue-100 dark:bg-blue-900/40 text-blue-600 dark:text-blue-400 font-black text-sm flex items-center justify-center shrink-0">
                                            #{idx + 1}
                                        </div>
                                        <div className="min-w-0">
                                            <h4 className="font-bold text-sm text-slate-900 dark:text-white truncate">
                                                {course.title || t('autoGenerated.untitled_course', 'دورة بدون عنوان')}
                                            </h4>
                                            <div className="flex items-center gap-3 text-xs text-slate-400 mt-0.5">
                                                <span className="flex items-center gap-1">
                                                    <Users className="w-3.5 h-3.5 text-blue-500" />
                                                    <span>{course.students || 0} {t('autoGenerated.student', 'طالب')}</span>
                                                </span>
                                            </div>
                                        </div>
                                    </div>

                                    <div className="flex items-center justify-between sm:justify-end gap-4 shrink-0 pt-2 sm:pt-0 border-t sm:border-0 border-slate-200/50 dark:border-slate-700/50">
                                        <div className="text-end">
                                            <span className="text-xs text-slate-400 block font-medium">{t('autoGenerated.revenue', 'العوائد')}</span>
                                            <span className="text-sm font-extrabold text-emerald-600 dark:text-emerald-400">
                                                {(course.revenue || 0).toLocaleString()} {t('autoGenerated.currency_sar', 'ر.س')}
                                            </span>
                                        </div>

                                        <Link
                                            to={`/instructor/courses/${course.id}/edit`}
                                            className="p-2 rounded-xl bg-white dark:bg-slate-700 border border-slate-200 dark:border-slate-600 hover:bg-blue-50 hover:border-blue-300 dark:hover:bg-slate-600 text-slate-600 dark:text-slate-200 transition-colors"
                                            title={t('autoGenerated.edit_course', 'تعديل الدورة')}
                                        >
                                            <ArrowUpRight className="w-4 h-4" />
                                        </Link>
                                    </div>
                                </div>
                            ))}
                        </div>
                    )}
                </div>

            </div>

        </div>
    );
};

export default Dashboard;
