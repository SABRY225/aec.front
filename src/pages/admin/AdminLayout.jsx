import { useState, useMemo, useEffect } from 'react';
import { useTranslation } from 'react-i18next';
import { Link, Outlet, useLocation, useNavigate } from 'react-router-dom';
import { useAuth } from '../../context/AuthContext';
import ProtectedRoute from '../../components/layouts/ProtectedRoute';
import NotificationBell from '../../components/shared/NotificationBell';
import {
    LayoutDashboard,
    Users,
    BookOpen,
    Tags,
    Layers,
    UserCheck,
    Settings,
    MessageSquare,
    Ticket,
    Megaphone,
    LogOut,
    Globe,
    Moon,
    Sun,
    Menu,
    X,
    UserPlus,
    FileText,
    Wifi, ShoppingCart,
    WifiOff,
    Languages,
    Activity,
    Radio,
    Bell,
    Star,
    CreditCard,
    Database,
    Shield
} from 'lucide-react';

const AdminLayout = () => {
    const { t, i18n } = useTranslation();
    const { user, logout } = useAuth();
    const location = useLocation();
    const navigate = useNavigate();
    const [isSidebarOpen, setIsSidebarOpen] = useState(false);
    
    // Dark mode state
    const [isDark, setIsDark] = useState(() => {
        return localStorage.getItem('theme') === 'dark' || 
               (!('theme' in localStorage) && window.matchMedia('(prefers-color-scheme: dark)').matches);
    });

    useEffect(() => {
        if (isDark) {
            document.documentElement.classList.add('dark');
            localStorage.setItem('theme', 'dark');
        } else {
            document.documentElement.classList.remove('dark');
            localStorage.setItem('theme', 'light');
        }
    }, [isDark]);

    const toggleDarkMode = () => setIsDark(!isDark);

    const toggleLanguage = () => {
        const newLang = i18n.language === 'ar' ? 'en' : 'ar';
        i18n.changeLanguage(newLang);
        document.documentElement.dir = newLang === 'ar' ? 'rtl' : 'ltr';
        document.documentElement.lang = newLang;
    };

    const handleLogout = async () => {
        const result = await logout();
        if (result?.redirectPath) {
            navigate(result.redirectPath);
        } else {
            navigate('/login');
        }
    };

    const navigationGroups = useMemo(() => [
        {
            title: t('autoGenerated.compText1000', 'الرئيسية والتحليلات'),
            items: [
                { path: '/admin/dashboard', label: t('nav.adminNav.dashboard', t('autoGenerated.compText1001', 'لوحة القيادة')), icon: <LayoutDashboard size={20} /> },
                { path: '/admin/analytics', label: t('autoGenerated.compText1002', 'تتبع الزيارات'), icon: <Activity size={20} /> },
                { path: '/admin/active-sessions', label: t('autoGenerated.compText1003', 'الجلسات النشطة'), icon: <Radio size={20} /> },
                { path: '/admin/notifications', label: t('autoGenerated.compText1004', 'الاشعارات'), icon: <Bell size={20} /> },
            ]
        },
        {
            title: t('autoGenerated.compText1005', 'إدارة المحتوى'),
            items: [
                { path: '/admin/courses', label: t('nav.adminNav.courses', t('autoGenerated.compText1006', 'الدورات')), icon: <BookOpen size={20} /> },
                { path: '/admin/categories', label: t('nav.adminNav.categories', t('autoGenerated.compText1007', 'الأقسام الرئيسية')), icon: <Layers size={20} /> },
                { path: '/admin/subcategories', label: t('nav.adminNav.subcategories', t('autoGenerated.compText1008', 'الأقسام الفرعية')), icon: <Tags size={20} /> },
                { path: '/admin/reviews', label: t('autoGenerated.compText1009', 'التقييمات'), icon: <Star size={20} /> },
            ]
        },
        {
            title: t('autoGenerated.compText1010', 'إدارة المستخدمين'),
            items: [
                { path: '/admin/staff', label: t('autoGenerated.compText1011', 'الموظفين والصلاحيات'), icon: <Shield size={20} /> },
                { path: '/admin/instructors', label: t('nav.adminNav.instructors', t('autoGenerated.compText1012', 'المحاضرين')), icon: <UserCheck size={20} /> },
                { path: '/admin/students', label: t('admin.students.title', t('autoGenerated.compText1013', 'الطلاب')), icon: <Users size={20} /> },
                { path: '/admin/manual-enrollment', label: t('nav.adminNav.manualEnrollment', t('autoGenerated.compText1014', 'التسجيل اليدوي')), icon: <UserPlus size={20} /> },
            ]
        },
        {
            title: t('autoGenerated.compText1015', 'المالية والتسجيلات'),
            items: [
                { path: '/admin/payments', label: t('autoGenerated.compText1016', 'المدفوعات'), icon: <CreditCard size={20} /> },
                { path: '/admin/online-enrollments', label: t('nav.adminNav.onlineEnrollments', t('autoGenerated.compText1017', 'تسجيلات أونلاين')), icon: <Wifi size={20} /> },
                { path: '/admin/offline-enrollments', label: t('nav.adminNav.offlineEnrollments', t('autoGenerated.compText1018', 'تسجيلات أوفلاين')), icon: <WifiOff size={20} /> },
                { path: '/admin/enrollment-logs', label: t('nav.adminNav.enrollmentLogs', t('autoGenerated.compText1019', 'سجلات التسجيل')), icon: <FileText size={20} /> },
                { path: '/admin/system-logs', label: t('nav.adminNav.systemLogs', t('autoGenerated.compText1020', 'سجلات النظام')), icon: <Activity size={20} /> },
                { path: '/admin/coupons', label: t('nav.adminNav.coupons', t('autoGenerated.compText1021', 'الكوبونات')), icon: <Ticket size={20} /> },
            ]
        },
        {
            title: t('autoGenerated.compText1022', 'التسويق والنظام'),
            items: [
                { path: '/admin/advertisements', label: t('nav.adminNav.advertisements', t('autoGenerated.compText1023', 'الإعلانات')), icon: <Megaphone size={20} /> },
                { path: '/admin/contact-messages', label: t('nav.adminNav.contactMessages', t('autoGenerated.compText1024', 'رسائل التواصل')), icon: <MessageSquare size={20} /> },
                { path: '/admin/backups', label: t('autoGenerated.compText1025', 'النسخ الاحتياطية'), icon: <Database size={20} /> },
            ]
        }
    ], [t]);

    const isRtl = i18n.language === 'ar';

    return (
        <ProtectedRoute allowedRoles={['admin']}>
            <div dir={isRtl ? 'rtl' : 'ltr'} className={`h-screen flex overflow-hidden font-arabic transition-colors duration-300 ${isDark ? 'dark bg-slate-900 text-slate-100' : 'bg-slate-50 text-slate-900'}`}>
                
                {/* Mobile Sidebar Overlay */}
                {isSidebarOpen && (
                    <div 
                        className="fixed inset-0 bg-slate-900/60 backdrop-blur-sm z-40 lg:hidden" 
                        onClick={() => setIsSidebarOpen(false)}
                    />
                )}

                {/* Sidebar */}
                <aside className={`fixed lg:static inset-y-0 ${isRtl ? 'right-0 border-l' : 'left-0 border-r'} z-50 w-72 bg-white dark:bg-slate-950 border-slate-200 dark:border-slate-800 shadow-2xl lg:shadow-none transform transition-transform duration-300 ease-in-out ${isSidebarOpen ? 'translate-x-0' : (isRtl ? 'translate-x-full lg:translate-x-0' : '-translate-x-full lg:translate-x-0')} flex flex-col h-full`}>
                    
                    {/* Sidebar Header (Logo) */}
                    <div className="h-16 flex items-center justify-between px-6 border-b border-slate-200 dark:border-slate-800">
                        <div className="flex items-center gap-3">
                            <div className="bg-blue-600 p-1.5 rounded-lg">
                                <img src="/assets/logo.png" alt="AEC" className="h-6 object-contain brightness-0 invert" />
                            </div>
                            <span className="font-bold text-lg text-slate-800 dark:text-white tracking-tight">{t('autoGenerated.compText1026', 'لوحة تحكم الإدارة')}</span>
                        </div>
                        <button onClick={() => setIsSidebarOpen(false)} className="lg:hidden text-slate-500 hover:text-slate-800 dark:hover:text-white">
                            <X size={24} />
                        </button>
                    </div>

                    {/* Navigation */}
                    <div className="flex-1 overflow-y-auto py-4 px-3 custom-scrollbar">
                        <nav className="space-y-6">
                            {navigationGroups.map((group, idx) => (
                                <div key={idx}>
                                    <h3 className="px-4 mb-3 text-xs font-bold text-slate-400 dark:text-slate-500 uppercase tracking-wider">
                                        {group.title}
                                    </h3>
                                    <div className="space-y-1">
                                        {group.items.map((item) => {
                                            const isActive = location.pathname === item.path || (item.path !== '/admin/dashboard' && location.pathname.startsWith(item.path + '/'));
                                            return (
                                                <Link
                                                    key={item.path}
                                                    to={item.path}
                                                    onClick={() => setIsSidebarOpen(false)}
                                                    className={`flex items-center gap-3 px-3 py-2.5 rounded-xl transition-all duration-200 ${
                                                        isActive 
                                                            ? 'bg-blue-600 text-white shadow-md shadow-blue-600/20' 
                                                            : 'text-slate-600 dark:text-slate-400 hover:bg-slate-100 dark:hover:bg-slate-900 hover:text-slate-900 dark:hover:text-white'
                                                    }`}
                                                >
                                                    <div className={`${isActive ? 'text-white' : 'text-slate-400 dark:text-slate-500'}`}>
                                                        {item.icon}
                                                    </div>
                                                    <span className="font-semibold text-sm">{item.label}</span>
                                                </Link>
                                            );
                                        })}
                                    </div>
                                </div>
                            ))}
                        </nav>
                    </div>
                </aside>

                {/* Main Content Area */}
                <div className="flex-1 flex flex-col min-w-0 bg-slate-50 dark:bg-slate-900">
                    
                    {/* Top Header */}
                    <header className="h-16 bg-white dark:bg-slate-950 border-b border-slate-200 dark:border-slate-800 shadow-sm flex items-center justify-between px-4 sm:px-6 z-30">
                        {/* Left Side (Menu Toggle on Mobile) */}
                        <div className="flex items-center gap-4">
                            <button 
                                onClick={() => setIsSidebarOpen(true)}
                                className="lg:hidden p-2 rounded-lg text-slate-500 hover:bg-slate-100 dark:hover:bg-slate-900 transition-colors"
                            >
                                <Menu size={24} />
                            </button>
                            <div className="hidden sm:block text-slate-800 dark:text-slate-200 font-bold text-lg">
                                {navigationGroups.flatMap(g => g.items).find(item => location.pathname === item.path || (item.path !== '/admin/dashboard' && location.pathname.startsWith(item.path + '/')))?.label || t('autoGenerated.compText1027', 'الإدارة')}
                            </div>
                        </div>

                        {/* Right Side (Actions) */}
                        <div className="flex items-center gap-2 sm:gap-4">
                            {/* View Site Button */}
                            <Link 
                                to="/"
                                target="_blank"
                                className="hidden sm:flex items-center gap-2 px-3 py-2 rounded-lg bg-slate-100 dark:bg-slate-900 text-slate-700 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-slate-800 transition-colors text-sm font-semibold"
                            >
                                <Globe size={18} />
                                <span>{t('autoGenerated.compText1028', 'عرض الموقع')}</span>
                            </Link>

                            {/* Mobile View Site */}
                            <Link 
                                to="/"
                                target="_blank"
                                className="sm:hidden p-2 rounded-lg text-slate-500 hover:bg-slate-100 dark:hover:bg-slate-900"
                            >
                                <Globe size={20} />
                            </Link>

                            {/* Language Toggle */}
                            <button 
                                onClick={toggleLanguage}
                                className="p-2 rounded-lg text-slate-500 hover:bg-slate-100 dark:hover:bg-slate-900 transition-colors flex items-center justify-center"
                                title={t('autoGenerated.compText1029', 'تغيير اللغة')}
                            >
                                <Languages size={20} />
                            </button>

                            {/* Dark Mode Toggle */}
                            <button 
                                onClick={toggleDarkMode}
                                className="p-2 rounded-lg text-slate-500 hover:bg-slate-100 dark:hover:bg-slate-900 transition-colors"
                                title={t('autoGenerated.compText1030', 'تغيير المظهر')}
                            >
                                {isDark ? <Sun size={20} className="text-yellow-500" /> : <Moon size={20} />}
                            </button>

                            {/* Notification Bell */}
                            <NotificationBell />

                            {/* Divider */}
                            <div className="w-px h-8 bg-slate-200 dark:bg-slate-800 mx-1 sm:mx-2"></div>

                            {/* Admin Profile Dropdown / Logout */}
                            <div className="flex items-center gap-3">
                                <div className="hidden md:block text-right">
                                    <div className="text-sm font-bold text-slate-900 dark:text-white leading-none mb-1">
                                        {user?.firstName} {user?.lastName}
                                    </div>
                                    <div className="text-xs text-blue-600 dark:text-blue-400 font-semibold leading-none">
                                        {t('autoGenerated.compText1031', 'المدير العام')}
                                    </div>
                                </div>
                                <div className="w-10 h-10 rounded-full bg-blue-100 dark:bg-blue-900/50 flex items-center justify-center text-blue-600 dark:text-blue-400 font-bold border border-blue-200 dark:border-blue-800">
                                    {user?.firstName?.[0]}{user?.lastName?.[0]}
                                </div>
                                <button 
                                    onClick={handleLogout}
                                    className="p-2 rounded-lg text-red-500 hover:bg-red-50 dark:hover:bg-red-950/30 transition-colors"
                                    title={t('autoGenerated.compText1032', 'تسجيل الخروج')}
                                >
                                    <LogOut size={20} />
                                </button>
                            </div>
                        </div>
                    </header>

                    {/* Page Content */}
                    <main className="flex-1 overflow-x-hidden overflow-y-auto p-4 sm:p-6 lg:p-8">
                        {/* We add dark mode class directly on Outlet children via context or just relying on global dark class */}
                        <div className="max-w-7xl mx-auto">
                            <Outlet />
                        </div>
                    </main>

                </div>
            </div>
        </ProtectedRoute>
    );
};

export default AdminLayout;
