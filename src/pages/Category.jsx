import React, { useState, useEffect, useMemo } from 'react';
import { useParams, Link } from 'react-router-dom';
import { motion, AnimatePresence } from 'framer-motion';
import { useTranslation } from 'react-i18next';
import { useLanguage } from '../hooks/useLanguage';
import api from '../services/new-api';
import {
    Search,
    X,
    BookOpen,
    Layers,
    Award,
    GraduationCap,
    ArrowRight,
    ArrowLeft,
    ChevronDown,
    ChevronUp,
    ChevronRight,
    ChevronLeft,
    Home,
    MessageCircle,
    Sparkles,
    PhoneCall,
    SlidersHorizontal,
    CheckCircle2,
    Compass
} from 'lucide-react';

const Category = () => {
    const { slug } = useParams();
    const { t } = useTranslation();
    const { language, isRTL } = useLanguage();

    const [category, setCategory] = useState(null);
    const [subcategories, setSubcategories] = useState([]);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState(null);

    // Search and sorting states
    const [searchTerm, setSearchTerm] = useState('');
    const [sortBy, setSortBy] = useState('default'); // 'default' | 'courses' | 'alpha'
    const [isDescriptionExpanded, setIsDescriptionExpanded] = useState(false);

    const getLocalizedName = (item) => {
        if (!item) return '';
        return language === 'ar' ? (item.nameAr || item.nameEn) : (item.nameEn || item.nameAr);
    };

    const getLocalizedDescription = (item) => {
        if (!item) return '';
        return language === 'ar'
            ? (item.descriptionAr || item.description || item.descriptionEn || '')
            : (item.descriptionEn || item.description || item.descriptionAr || '');
    };

    useEffect(() => {
        if (slug) {
            fetchCategoryData();
            setSearchTerm('');
            setIsDescriptionExpanded(false);
        }
    }, [slug]);

    const fetchCategoryData = async () => {
        try {
            setLoading(true);
            setError(null);

            const categoryResponse = await api.get(`/categories/slug/${slug}`);
            const categoryData = categoryResponse.data?.data;

            if (!categoryData) {
                setError(t('categoryPage.notFound', 'التصنيف غير موجود'));
                return;
            }

            setCategory(categoryData);

            // Fetch subcategories for this category ID
            const subcategoriesResponse = await api.get(`/subcategories/category/${categoryData._id}`);
            const subcategoriesData = subcategoriesResponse.data?.data || categoryData.subcategories || [];
            setSubcategories(subcategoriesData);
        } catch (err) {
            console.error('Error fetching category data:', err);
            setError(t('categoryPage.loadFailed', 'تعذّر تحميل بيانات التصنيف'));
        } finally {
            setLoading(false);
        }
    };

    // Update document title for SEO
    useEffect(() => {
        if (category) {
            const catName = getLocalizedName(category);
            document.title = `${catName} | ${t('common.meta.siteTitle', 'أكاديمية AEC')}`;
        }
    }, [category, language, t]);

    // Calculate total courses across all subcategories
    const totalCourses = useMemo(() => {
        return subcategories.reduce((acc, sub) => acc + (Number(sub.courseCount) || 0), 0);
    }, [subcategories]);

    // Filter and sort subcategories
    const filteredSubcategories = useMemo(() => {
        let list = [...subcategories];

        if (searchTerm.trim() !== '') {
            const term = searchTerm.toLowerCase().trim();
            list = list.filter((sub) => {
                const nameAr = (sub.nameAr || '').toLowerCase();
                const nameEn = (sub.nameEn || '').toLowerCase();
                const desc = (sub.description || '').toLowerCase();
                return nameAr.includes(term) || nameEn.includes(term) || desc.includes(term);
            });
        }

        if (sortBy === 'courses') {
            list.sort((a, b) => (Number(b.courseCount) || 0) - (Number(a.courseCount) || 0));
        } else if (sortBy === 'alpha') {
            list.sort((a, b) => {
                const nameA = getLocalizedName(a);
                const nameB = getLocalizedName(b);
                return nameA.localeCompare(nameB, language === 'ar' ? 'ar' : 'en');
            });
        }

        return list;
    }, [subcategories, searchTerm, sortBy, language]);

    // WhatsApp Advisory Link
    const whatsappInquiryUrl = useMemo(() => {
        const catName = category ? getLocalizedName(category) : '';
        const message = t('autoGenerated.hello_aec_academy_i_would_like', `Hello AEC Academy, I would like to inquire about training tracks in: ${catName}`);
        return `https://api.whatsapp.com/send?phone=966540098736&text=${encodeURIComponent(message)}`;
    }, [category, isRTL]);

    const ArrowIcon = isRTL ? ArrowLeft : ArrowRight;
    const BreadcrumbSeparator = isRTL ? ChevronLeft : ChevronRight;

    // Loading Skeleton State
    if (loading) {
        return (
            <div className="min-h-screen bg-slate-50/70" dir={t('autoGenerated.ltr', `ltr`)}>
                {/* Hero Skeleton */}
                <div className="relative bg-[#071942] py-14 sm:py-20 px-4 sm:px-6 lg:px-8 overflow-hidden">
                    <div className="max-w-7xl mx-auto space-y-6 animate-pulse">
                        <div className="h-7 w-48 bg-white/10 rounded-full" />
                        <div className="h-6 w-32 bg-white/10 rounded-full" />
                        <div className="h-12 w-3/4 max-w-lg bg-white/15 rounded-xl" />
                        <div className="h-5 w-full max-w-2xl bg-white/10 rounded-lg" />
                        <div className="h-5 w-2/3 max-w-xl bg-white/10 rounded-lg" />

                        {/* Stats Skeleton */}
                        <div className="grid grid-cols-2 md:grid-cols-4 gap-4 pt-10">
                            {[1, 2, 3, 4].map((i) => (
                                <div key={i} className="h-20 bg-white/5 border border-white/10 rounded-2xl p-4 flex items-center space-x-3" />
                            ))}
                        </div>
                    </div>
                </div>

                {/* Grid Skeleton */}
                <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
                    <div className="h-14 bg-white rounded-2xl border border-slate-200/80 mb-8 animate-pulse" />
                    <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-6">
                        {[1, 2, 3, 4, 5, 6, 7, 8].map((i) => (
                            <div key={i} className="bg-white rounded-2xl border border-slate-200/80 overflow-hidden shadow-sm animate-pulse">
                                <div className="h-44 bg-slate-200" />
                                <div className="p-5 space-y-3">
                                    <div className="h-5 bg-slate-200 rounded w-3/4" />
                                    <div className="h-4 bg-slate-100 rounded w-full" />
                                    <div className="h-4 bg-slate-100 rounded w-2/3" />
                                    <div className="pt-4 border-t border-slate-100 flex justify-between items-center">
                                        <div className="h-4 bg-slate-200 rounded w-20" />
                                        <div className="h-4 bg-slate-200 rounded w-16" />
                                    </div>
                                </div>
                            </div>
                        ))}
                    </div>
                </div>
            </div>
        );
    }

    // Error State
    if (error || !category) {
        return (
            <motion.div
                initial={{ opacity: 0, y: 20 }}
                animate={{ opacity: 1, y: 0 }}
                className="min-h-screen bg-slate-50 flex items-center justify-center px-4"
                dir={t('autoGenerated.ltr', `ltr`)}
            >
                <div className="max-w-md w-full bg-white rounded-3xl p-8 sm:p-10 border border-slate-100 shadow-xl text-center">
                    <div className="w-16 h-16 bg-rose-50 text-rose-500 rounded-2xl flex items-center justify-center mx-auto mb-5 shadow-sm">
                        <Compass className="w-8 h-8" />
                    </div>
                    <h2 className="text-2xl font-extrabold text-slate-900 mb-2">
                        {t('categoryPage.notFound', 'التصنيف غير موجود')}
                    </h2>
                    <p className="text-slate-600 text-sm mb-6 leading-relaxed">
                        {error || t('categoryPage.notFoundDesc', 'تعذّر العثور على التصنيف المطلوب، ربما تم نقل الرابط أو تعديله.')}
                    </p>
                    <Link
                        to="/categories"
                        className="inline-flex items-center justify-center gap-2 w-full bg-[#004C97] hover:bg-[#071942] text-white font-bold py-3 px-6 rounded-xl transition-all shadow-md shadow-blue-900/20"
                    >
                        <span>{t('categoryPage.backToCategories', 'العودة إلى كافة التصنيفات')}</span>
                        <ArrowIcon className="w-4 h-4" />
                    </Link>
                </div>
            </motion.div>
        );
    }

    const categoryName = getLocalizedName(category);
    const categoryDescription = getLocalizedDescription(category) || t('categoryPage.exploreIn', { name: categoryName, defaultValue: `استكشف أفضل الدورات والمسارات التدريبية في مجال ${categoryName}` });
    const isLongDesc = categoryDescription.length > 220;

    return (
        <div className="min-h-screen bg-slate-50/70" dir={t('autoGenerated.ltr', `ltr`)}>
            
            {/* ========================================================================= */}
            {/* HERO SECTION: Category Image as Section Background with Cinematic Gradient*/}
            {/* ========================================================================= */}
            <section className="relative bg-[#071942] text-white overflow-hidden py-14 sm:py-20 lg:py-24">
                
                {/* Category Image as Full Section Background */}
                {category.image ? (
                    <div className="absolute inset-0 z-0 overflow-hidden">
                        <img
                            src={category.image}
                            alt={categoryName}
                            className="w-full h-full object-cover object-center"
                        />
                        {/* Directional Cinematic Gradient: Text remains crystal clear while image shines through */}
                        <div className="absolute inset-0 bg-[#06102b]/65" />
                        <div className={`absolute inset-0 ${
                            t('autoGenerated.bg_gradient_to_r_from_06102b_9', `bg-gradient-to-r from-[#06102b]/95 via-[#071942]/80 to-[#071942]/45`)
                        }`} />
                        <div className="absolute inset-0 bg-gradient-to-t from-[#06102b] via-transparent to-black/30" />
                    </div>
                ) : (
                    <div className="absolute inset-0 z-0 bg-gradient-to-br from-[#071942] to-[#004C97]" />
                )}

                {/* Ambient Radial Lights */}
                <div className="absolute top-0 right-1/4 w-96 h-96 bg-blue-600/15 rounded-full blur-3xl pointer-events-none z-10" />
                <div className="absolute bottom-0 left-1/4 w-[450px] h-[450px] bg-amber-500/10 rounded-full blur-3xl pointer-events-none z-10" />

                <div className="relative z-20 max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
                    
                    {/* Integrated Glassmorphic Breadcrumbs */}
                    <motion.div
                        initial={{ opacity: 0, y: -10 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ duration: 0.3 }}
                        className="mb-6 inline-flex"
                    >
                        <nav
                            aria-label="Breadcrumb"
                            className="flex items-center flex-wrap gap-2 text-xs sm:text-sm bg-slate-900/60 backdrop-blur-md border border-white/20 px-4 py-2 rounded-full text-blue-100 shadow-md"
                        >
                            <Link
                                to="/"
                                className="flex items-center gap-1.5 text-blue-200 hover:text-white transition-colors"
                            >
                                <Home className="w-3.5 h-3.5" />
                                <span>{t('categoryPage.home', 'الرئيسية')}</span>
                            </Link>

                            <BreadcrumbSeparator className="w-3.5 h-3.5 text-blue-300/60" />

                            <Link
                                to="/categories"
                                className="text-blue-200 hover:text-white transition-colors"
                            >
                                {t('categoryPage.categories', 'التصنيفات')}
                            </Link>

                            <BreadcrumbSeparator className="w-3.5 h-3.5 text-blue-300/60" />

                            <span className="font-semibold text-white truncate max-w-[200px] sm:max-w-none">
                                {categoryName}
                            </span>
                        </nav>
                    </motion.div>

                    {/* Hero Title & Description Area */}
                    <div className="max-w-4xl space-y-4">
                        <motion.div
                            initial={{ opacity: 0, x: isRTL ? 20 : -20 }}
                            animate={{ opacity: 1, x: 0 }}
                            transition={{ duration: 0.4 }}
                            className="inline-flex items-center gap-2 bg-gradient-to-r from-amber-500/25 to-amber-500/10 border border-amber-400/40 text-amber-300 px-4 py-1.5 rounded-full text-xs font-bold tracking-wide backdrop-blur-md shadow-md"
                        >
                            <Sparkles className="w-3.5 h-3.5 text-amber-400" />
                            <span>{t('categoryPage.accreditedTrack', 'مسار تدريبي معتمد')}</span>
                        </motion.div>

                        <motion.h1
                            initial={{ opacity: 0, y: 15 }}
                            animate={{ opacity: 1, y: 0 }}
                            transition={{ duration: 0.5, delay: 0.1 }}
                            className="text-3xl sm:text-5xl lg:text-6xl font-black text-white tracking-tight leading-tight drop-shadow-lg"
                        >
                            {categoryName}
                        </motion.h1>

                        {/* Description with Expand/Collapse */}
                        <motion.div
                            initial={{ opacity: 0, y: 15 }}
                            animate={{ opacity: 1, y: 0 }}
                            transition={{ duration: 0.5, delay: 0.2 }}
                            className="text-slate-100 text-sm sm:text-base md:text-lg leading-relaxed max-w-3xl drop-shadow"
                        >
                            <p className={!isDescriptionExpanded && isLongDesc ? 'line-clamp-3' : 'whitespace-pre-line'}>
                                {categoryDescription}
                            </p>
                            {isLongDesc && (
                                <button
                                    onClick={() => setIsDescriptionExpanded(!isDescriptionExpanded)}
                                    className="mt-2 inline-flex items-center gap-1.5 text-amber-400 hover:text-amber-300 font-semibold text-sm transition-colors focus:outline-none"
                                >
                                    <span>
                                        {isDescriptionExpanded
                                            ? t('categoryPage.readLess', 'عرض أقل')
                                            : t('categoryPage.readMore', 'قراءة المزيد')}
                                    </span>
                                    {isDescriptionExpanded ? (
                                        <ChevronUp className="w-4 h-4" />
                                    ) : (
                                        <ChevronDown className="w-4 h-4" />
                                    )}
                                </button>
                            )}
                        </motion.div>
                    </div>

                    {/* Stats Highlights Strip */}
                    <motion.div
                        initial={{ opacity: 0, y: 20 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ duration: 0.5, delay: 0.3 }}
                        className="mt-10 grid grid-cols-2 sm:grid-cols-4 gap-3 sm:gap-4 max-w-5xl"
                    >
                        {/* Metric 1: Subcategories Count */}
                        <div className="bg-slate-900/65 backdrop-blur-md border border-white/20 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-slate-900/80 transition-all shadow-lg">
                            <div className="w-11 h-11 rounded-xl bg-blue-500/25 border border-blue-400/40 flex items-center justify-center text-blue-300 shrink-0">
                                <Layers className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-xl sm:text-2xl font-black text-white">
                                    {subcategories.length}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    {t('categoryPage.subcategoriesIn', { name: '', defaultValue: 'تخصص فرعي' })}
                                </span>
                            </div>
                        </div>

                        {/* Metric 2: Total Courses */}
                        <div className="bg-slate-900/65 backdrop-blur-md border border-white/20 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-slate-900/80 transition-all shadow-lg">
                            <div className="w-11 h-11 rounded-xl bg-amber-500/25 border border-amber-400/40 flex items-center justify-center text-amber-400 shrink-0">
                                <BookOpen className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-xl sm:text-2xl font-black text-white">
                                    {totalCourses > 0 ? `${totalCourses}+` : `${subcategories.length * 2}+`}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    {t('categoryPage.totalCourses', 'دورة تدريبية')}
                                </span>
                            </div>
                        </div>

                        {/* Metric 3: Accredited Certificates */}
                        <div className="bg-slate-900/65 backdrop-blur-md border border-white/20 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-slate-900/80 transition-all shadow-lg">
                            <div className="w-11 h-11 rounded-xl bg-emerald-500/25 border border-emerald-400/40 flex items-center justify-center text-emerald-400 shrink-0">
                                <Award className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-sm sm:text-base font-bold text-white">
                                    {t('categoryPage.certifiedPrograms', 'شهادات معتمدة')}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    معترف بها مهنياً
                                </span>
                            </div>
                        </div>

                        {/* Metric 4: Career Ready */}
                        <div className="bg-slate-900/65 backdrop-blur-md border border-white/20 rounded-2xl p-4 flex items-center gap-3.5 hover:bg-slate-900/80 transition-all shadow-lg">
                            <div className="w-11 h-11 rounded-xl bg-indigo-500/25 border border-indigo-400/40 flex items-center justify-center text-indigo-300 shrink-0">
                                <GraduationCap className="w-5 h-5" />
                            </div>
                            <div>
                                <span className="block text-sm sm:text-base font-bold text-white">
                                    {t('categoryPage.practicalTraining', 'تطبيق عملي')}
                                </span>
                                <span className="block text-xs text-blue-200 font-medium">
                                    تأهيل مباشر للسوق
                                </span>
                            </div>
                        </div>
                    </motion.div>

                </div>
            </section>

            {/* ========================================================================= */}
            {/* MAIN CONTENT: Interactive Search, Filters & Cards Grid                    */}
            {/* ========================================================================= */}
            <main className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10 sm:py-14">
                
                {/* Header Strip & Search Bar */}
                <div className="bg-white rounded-3xl border border-slate-200/80 p-5 sm:p-7 shadow-sm mb-10 space-y-6">
                    <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
                        <div>
                            <h2 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight">
                                {t('categoryPage.subcategoriesIn', { name: categoryName, defaultValue: `المسارات والتخصصات في ${categoryName}` })}
                            </h2>
                            <p className="text-slate-500 text-sm mt-1">
                                {t('categoryPage.subcategoriesSubtitle', 'اختر تخصصاً فرعياً لاستكشاف أقوى الدورات والبرامج المعتمدة.')}
                            </p>
                        </div>

                        {/* Showing count indicator */}
                        <div className="inline-flex items-center gap-2 bg-blue-50 text-blue-700 px-4 py-2 rounded-xl text-xs sm:text-sm font-bold border border-blue-100 self-start md:self-auto">
                            <span>
                                {t('categoryPage.showingResults', {
                                    count: filteredSubcategories.length,
                                    total: subcategories.length,
                                    defaultValue: `عرض ${filteredSubcategories.length} من أصل ${subcategories.length} مسار`
                                })}
                            </span>
                        </div>
                    </div>

                    {/* Search and Sort Toolbar */}
                    <div className="grid grid-cols-1 sm:grid-cols-12 gap-3 pt-2">
                        {/* Search Input */}
                        <div className="sm:col-span-8 lg:col-span-8 relative">
                            <div className={`absolute inset-y-0 ${t('autoGenerated.left_0_pl_4', `left-0 pl-4`)} flex items-center pointer-events-none text-slate-400`}>
                                <Search className="w-5 h-5" />
                            </div>
                            <input
                                type="text"
                                value={searchTerm}
                                onChange={(e) => setSearchTerm(e.target.value)}
                                placeholder={t('categoryPage.searchPlaceholder', {
                                    name: categoryName,
                                    defaultValue: `ابحث في مسارات ${categoryName}...`
                                })}
                                className={`w-full bg-slate-50/80 border border-slate-200 rounded-2xl ${
                                    t('autoGenerated.pl_11_pr_10', `pl-11 pr-10`)
                                } py-3 text-sm text-slate-800 placeholder-slate-400 focus:outline-none focus:ring-2 focus:ring-blue-600/30 focus:border-blue-600 focus:bg-white transition-all`}
                            />
                            {searchTerm && (
                                <button
                                    onClick={() => setSearchTerm('')}
                                    className={`absolute inset-y-0 ${t('autoGenerated.right_0_pr_3_5', `right-0 pr-3.5`)} flex items-center text-slate-400 hover:text-slate-600 transition-colors`}
                                    aria-label="Clear search"
                                >
                                    <X className="w-4 h-4" />
                                </button>
                            )}
                        </div>

                        {/* Sort Tabs */}
                        <div className="sm:col-span-4 lg:col-span-4 flex items-center gap-1.5 bg-slate-50/80 p-1 border border-slate-200 rounded-2xl">
                            <button
                                onClick={() => setSortBy('default')}
                                className={`flex-1 py-2 px-3 rounded-xl text-xs font-bold transition-all text-center ${
                                    sortBy === 'default'
                                        ? 'bg-white text-blue-700 shadow-sm border border-slate-100'
                                        : 'text-slate-600 hover:text-slate-900'
                                }`}
                            >
                                {t('categoryPage.allTracks', 'الكل')}
                            </button>
                            <button
                                onClick={() => setSortBy('courses')}
                                className={`flex-1 py-2 px-3 rounded-xl text-xs font-bold transition-all text-center ${
                                    sortBy === 'courses'
                                        ? 'bg-white text-blue-700 shadow-sm border border-slate-100'
                                        : 'text-slate-600 hover:text-slate-900'
                                }`}
                            >
                                {t('categoryPage.mostCourses', 'الأكثر دورات')}
                            </button>
                            <button
                                onClick={() => setSortBy('alpha')}
                                className={`flex-1 py-2 px-3 rounded-xl text-xs font-bold transition-all text-center ${
                                    sortBy === 'alpha'
                                        ? 'bg-white text-blue-700 shadow-sm border border-slate-100'
                                        : 'text-slate-600 hover:text-slate-900'
                                }`}
                            >
                                {t('categoryPage.alphabetical', 'أبجدياً')}
                            </button>
                        </div>
                    </div>
                </div>

                {/* Subcategories Grid */}
                {filteredSubcategories.length > 0 ? (
                    <motion.div
                        layout
                        className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-6 sm:gap-7"
                    >
                        <AnimatePresence>
                            {filteredSubcategories.map((subcategory, index) => {
                                const subName = getLocalizedName(subcategory);
                                const subDesc = getLocalizedDescription(subcategory);
                                const courseCount = Number(subcategory.courseCount) || 0;

                                return (
                                    <motion.div
                                        key={subcategory._id || index}
                                        layout
                                        initial={{ opacity: 0, y: 20 }}
                                        animate={{ opacity: 1, y: 0 }}
                                        exit={{ opacity: 0, scale: 0.95 }}
                                        transition={{ duration: 0.35, delay: Math.min(index * 0.05, 0.4) }}
                                    >
                                        <Link
                                            to={`/subcategory/${subcategory.slug}`}
                                            className="group relative bg-white rounded-3xl border border-slate-200/80 hover:border-blue-500/50 shadow-sm hover:shadow-xl hover:shadow-blue-900/10 hover:-translate-y-1.5 transition-all duration-300 flex flex-col h-full overflow-hidden"
                                        >
                                            {/* Top Image Banner */}
                                            <div className="relative h-48 w-full bg-slate-100 overflow-hidden">
                                                {subcategory.image ? (
                                                    <img
                                                        src={subcategory.image}
                                                        alt={subName}
                                                        loading="lazy"
                                                        className="w-full h-full object-cover transition-transform duration-700 ease-out group-hover:scale-108"
                                                    />
                                                ) : (
                                                    <div className="w-full h-full flex flex-col items-center justify-center bg-gradient-to-br  text-white p-4 text-center">
                                                        <span className="text-4xl mb-2">{category.icon || '📚'}</span>
                                                        <span className="text-xs font-semibold text-blue-200">AEC Academy</span>
                                                    </div>
                                                )}

                                                {/* Image Gradient Scrim */}
                                                <div className="absolute inset-0 bg-gradient-to-t from-slate-950/60 via-slate-950/15 to-transparent pointer-events-none" />

                                                {/* Course Count Floating Pill */}
                                                <div className={`absolute top-3 ${t('autoGenerated.left_3', `left-3`)} z-10`}>
                                                    <span className="inline-flex items-center gap-1.5 bg-slate-900/80 backdrop-blur-md text-amber-300 border border-white/20 text-xs font-bold px-3 py-1.5 rounded-full shadow-md">
                                                        <BookOpen className="w-3.5 h-3.5 text-amber-400" />
                                                        <span>
                                                            {courseCount > 0
                                                                ? t('categoryPage.courseCount', { count: courseCount, defaultValue: `${courseCount} دورة` })
                                                                : t('categoryPage.accreditedTrack', 'مسار تدريبي')}
                                                        </span>
                                                    </span>
                                                </div>

                                                {/* Track Tag Overlay at Bottom of Image */}
                                                <div className={`absolute bottom-3 ${t('autoGenerated.left_3', `left-3`)} z-10`}>
                                                    <span className="inline-flex items-center gap-1 text-[11px] font-semibold text-white/90 drop-shadow">
                                                        <CheckCircle2 className="w-3 h-3 text-emerald-400" />
                                                        <span>تأهيل مهني معتمد</span>
                                                    </span>
                                                </div>
                                            </div>

                                            {/* Card Body */}
                                            <div className="p-5 flex flex-col flex-1">
                                                <h3 className="text-lg font-bold text-slate-900 group-hover:text-blue-600 transition-colors line-clamp-1 leading-snug">
                                                    {subName}
                                                </h3>

                                                <p className="text-slate-500 text-xs sm:text-sm mt-2 line-clamp-2 leading-relaxed min-h-[36px]">
                                                    {subDesc || t('categoryPage.exploreSubcategory', 'استكشف أفضل الدورات والمحتوى التخصصي المعتمد في هذا المسار.')}
                                                </p>

                                                {/* Card Footer / Action Link */}
                                                <div className="pt-4 mt-auto border-t border-slate-100 flex items-center justify-between">
                                                    <span className="text-xs font-medium text-slate-400">
                                                        AEC Certified
                                                    </span>

                                                    <div className="inline-flex items-center gap-1.5 text-xs sm:text-sm font-bold text-[#004C97] group-hover:text-blue-600 transition-all">
                                                        <span>{t('categoryPage.view', 'استكشف المسار')}</span>
                                                        <ArrowIcon
                                                            className={`w-4 h-4 transition-transform duration-300 ${
                                                                t('autoGenerated.group_hover_translate_x_1_5', `group-hover:translate-x-1.5`)
                                                            }`}
                                                        />
                                                    </div>
                                                </div>
                                            </div>
                                        </Link>
                                    </motion.div>
                                );
                            })}
                        </AnimatePresence>
                    </motion.div>
                ) : searchTerm ? (
                    /* Search Term Empty State */
                    <motion.div
                        initial={{ opacity: 0, scale: 0.95 }}
                        animate={{ opacity: 1, scale: 1 }}
                        className="bg-white rounded-3xl border border-slate-200/80 p-10 sm:p-14 text-center max-w-xl mx-auto shadow-sm"
                    >
                        <div className="w-16 h-16 bg-blue-50 text-blue-600 rounded-2xl flex items-center justify-center mx-auto mb-4">
                            <Search className="w-8 h-8 text-blue-500" />
                        </div>
                        <h3 className="text-xl font-bold text-slate-900 mb-2">
                            {t('categoryPage.noSearchResults', 'لم يتم العثور على نتائج تطابق بحثك')}
                        </h3>
                        <p className="text-slate-500 text-sm mb-6 leading-relaxed">
                            {t('categoryPage.noSearchDesc', 'جرّب البحث بكلمة مختلفة أو قم بإعادة ضبط البحث لرؤية جميع التخصصات.')}
                        </p>
                        <button
                            onClick={() => setSearchTerm('')}
                            className="inline-flex items-center gap-2 bg-[#004C97] hover:bg-[#071942] text-white font-bold py-2.5 px-6 rounded-xl text-sm transition-all"
                        >
                            <span>{t('categoryPage.clearSearch', 'إعادة ضبط البحث')}</span>
                            <X className="w-4 h-4" />
                        </button>
                    </motion.div>
                ) : (
                    /* Total Empty Category State */
                    <motion.div
                        initial={{ opacity: 0, scale: 0.95 }}
                        animate={{ opacity: 1, scale: 1 }}
                        className="bg-white rounded-3xl border border-slate-200/80 p-12 text-center max-w-lg mx-auto shadow-sm"
                    >
                        <div className="w-16 h-16 bg-amber-50 text-amber-600 rounded-2xl flex items-center justify-center mx-auto mb-4">
                            <Layers className="w-8 h-8 text-amber-500" />
                        </div>
                        <h3 className="text-2xl font-bold text-slate-900 mb-2">
                            {t('categoryPage.noSubcategories', 'لا توجد مسارات فرعية')}
                        </h3>
                        <p className="text-slate-500 text-sm mb-6 leading-relaxed">
                            {t('categoryPage.noSubcategoriesDesc', {
                                name: categoryName,
                                defaultValue: `لا توجد مسارات فرعية مدرجة في ${categoryName} حالياً، جاري إضافة البرامج الجديدة قريباً.`
                            })}
                        </p>
                        <Link
                            to="/categories"
                            className="inline-flex items-center gap-2 bg-[#004C97] hover:bg-[#071942] text-white font-bold py-3 px-6 rounded-xl text-sm transition-all"
                        >
                            <span>{t('categoryPage.exploreOther', 'استكشف تصنيفات أخرى')}</span>
                            <ArrowIcon className="w-4 h-4" />
                        </Link>
                    </motion.div>
                )}


            </main>
        </div>
    );
};

export default Category;
