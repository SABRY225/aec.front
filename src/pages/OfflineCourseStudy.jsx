import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { useTranslation } from 'react-i18next';
import { toast } from 'react-toastify';
import {
  FaMapMarkerAlt,
  FaCalendarAlt,
  FaClock,
  FaUser,
  FaDownload,
  FaTicketAlt,
  FaExternalLinkAlt,
  FaFileAlt,
  FaCheckCircle,
  FaArrowLeft,
} from 'react-icons/fa';
import { enrollmentService } from '../services/new-api';
import { formatDate } from '../utils/formatDate';
import RichTextDisplay from '../components/RichTextDisplay/RichTextDisplay';

const FileLink = ({ file, t }) => {
  const label = file.name || t('course.study.downloadDefault', 'Download');
  return (
    <a
      href={file.url}
      target="_blank"
      rel="noopener noreferrer"
      className="flex items-center gap-3 p-3 bg-gray-50 hover:bg-gray-100 rounded-xl border border-gray-100 transition"
    >
      <FaFileAlt className="w-5 h-5 text-blue-600 shrink-0" />
      <span className="flex-1 text-gray-900 truncate text-sm font-medium">{label}</span>
      <FaDownload className="w-4 h-4 text-gray-500 shrink-0" />
    </a>
  );
};

/**
 * Offline (onsite) course student view — venue, schedule, enrollment ticket, materials.
 */
const OfflineCourseStudy = ({ studyData, language, isRTL }) => {
  const { t } = useTranslation();
  const navigate = useNavigate();
  const [downloading, setDownloading] = useState(false);
  const course = studyData.course;
  const enrollment = studyData.enrollment || {};
  const materials = course.additionalFiles || [];

  const scheduleLine = [
    Array.isArray(course.scheduleDays) && course.scheduleDays.length
      ? course.scheduleDays.map((d) => t(`instructor.courseCreation.day.${d}`, d)).join(', ')
      : null,
    course.sessionStartTime && course.sessionEndTime
      ? `${course.sessionStartTime} – ${course.sessionEndTime}`
      : null,
  ]
    .filter(Boolean)
    .join(' · ');

  const handleDownloadTicket = async () => {
    try {
      setDownloading(true);
      const blob = await enrollmentService.downloadEnrollmentPDF(course._id);
      const url = window.URL.createObjectURL(new Blob([blob], { type: 'application/pdf' }));
      const link = document.createElement('a');
      link.href = url;
      link.download = `enrollment-${enrollment.serialNumber || course._id}.pdf`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      window.URL.revokeObjectURL(url);
      toast.success(t('course.study.offline.ticketDownloaded', 'Enrollment ticket downloaded'));
    } catch (error) {
      console.error(error);
      toast.error(t('course.study.offline.ticketFailed', 'Failed to download enrollment ticket'));
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div className="min-h-screen bg-gray-50" dir={t('autoGenerated.ltr', `ltr`)}>
      <div className="bg-white border-b border-gray-200">
        <div className="max-w-6xl mx-auto px-4 sm:px-6 py-4 flex flex-wrap items-center justify-between gap-3">
          <button
            type="button"
            onClick={() => navigate('/student/my-courses')}
            className="inline-flex items-center gap-2 text-sm text-gray-600 hover:text-blue-600 transition"
          >
            <FaArrowLeft className={`w-4 h-4 ${t('autoGenerated.text_plqwa', ``)}`} />
            {t('course.study.backToMyCourses')}
          </button>
          <span className="inline-flex items-center px-3 py-1 rounded-full text-xs font-bold tracking-wide bg-green-100 text-green-800">
            OFFLINE
          </span>
        </div>
      </div>

      <div className="max-w-6xl mx-auto px-4 sm:px-6 py-6 md:py-10">
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
          {/* Main column */}
          <div className="lg:col-span-2 space-y-6">
            {/* Hero / ticket card */}
            <div className="bg-white rounded-2xl shadow-sm border border-gray-100 overflow-hidden">
              {course.thumbnail && (
                <div className="aspect-[21/9] bg-gray-100 overflow-hidden">
                  <img
                    src={course.thumbnail}
                    alt={course.title}
                    className="w-full h-full object-cover"
                  />
                </div>
              )}
              <div className="p-5 sm:p-8">
                <p className="text-sm font-semibold text-green-700 mb-2">
                  {t('course.study.offline.enrollmentConfirmed', 'Enrollment confirmed')}
                </p>
                <h1 className="text-2xl sm:text-3xl font-bold text-gray-900 mb-4">{course.title}</h1>

                <div className="flex flex-col sm:flex-row sm:items-center gap-3 sm:gap-4 mb-6">
                  <button
                    type="button"
                    onClick={handleDownloadTicket}
                    disabled={downloading}
                    className="inline-flex items-center justify-center gap-2 px-5 py-3 rounded-xl bg-gradient-to-r from-blue-600 to-purple-600 text-white font-semibold shadow-md shadow-blue-500/20 hover:opacity-95 disabled:opacity-60 transition"
                  >
                    <FaTicketAlt className="w-5 h-5" />
                    {downloading
                      ? t('common.loading', 'Loading...')
                      : t('course.study.offline.downloadTicket', 'Download Enrollment Ticket')}
                  </button>
                  {enrollment.serialNumber && (
                    <div className="text-sm text-gray-600">
                      <span className="text-gray-500">{t('course.study.offline.serial', 'Serial')}: </span>
                      <span className="font-mono font-semibold text-gray-900">{enrollment.serialNumber}</span>
                    </div>
                  )}
                </div>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                  {(course.startDate || course.endDate) && (
                    <div className="flex items-start gap-3 p-3 rounded-xl bg-gray-50 border border-gray-100">
                      <FaCalendarAlt className="w-4 h-4 text-blue-600 mt-1 shrink-0" />
                      <div>
                        <p className="text-xs text-gray-500 mb-0.5">{t('course.preview.startDate', 'Dates')}</p>
                        <p className="text-sm font-medium text-gray-900">
                          {course.startDate ? formatDate(course.startDate, language) : '—'}
                          {course.endDate ? ` – ${formatDate(course.endDate, language)}` : ''}
                        </p>
                      </div>
                    </div>
                  )}
                  {scheduleLine && (
                    <div className="flex items-start gap-3 p-3 rounded-xl bg-gray-50 border border-gray-100">
                      <FaClock className="w-4 h-4 text-blue-600 mt-1 shrink-0" />
                      <div>
                        <p className="text-xs text-gray-500 mb-0.5">{t('course.preview.schedule', 'Schedule')}</p>
                        <p className="text-sm font-medium text-gray-900 capitalize">{scheduleLine}</p>
                      </div>
                    </div>
                  )}
                  {course.location && (
                    <div className="flex items-start gap-3 p-3 rounded-xl bg-gray-50 border border-gray-100 sm:col-span-2">
                      <FaMapMarkerAlt className="w-4 h-4 text-green-600 mt-1 shrink-0" />
                      <div className="min-w-0">
                        <p className="text-xs text-gray-500 mb-0.5">{t('course.preview.location', 'Location')}</p>
                        <p className="text-sm font-medium text-gray-900">{course.location}</p>
                        {course.address && <p className="text-sm text-gray-600 mt-0.5">{course.address}</p>}
                        {course.governorate && (
                          <p className="text-sm text-gray-500 mt-0.5">{course.governorate}</p>
                        )}
                        {course.mapsUrl && (
                          <a
                            href={course.mapsUrl}
                            target="_blank"
                            rel="noreferrer"
                            className="inline-flex items-center gap-1 text-sm text-blue-600 hover:underline mt-1"
                          >
                            {t('course.preview.viewOnMap', 'View on map')}
                            <FaExternalLinkAlt className="w-3 h-3" />
                          </a>
                        )}
                      </div>
                    </div>
                  )}
                </div>
              </div>
            </div>

            {/* Instructions */}
            {course.additionalInstructions && (
              <div className="bg-white rounded-2xl shadow-sm border border-gray-100 p-5 sm:p-6">
                <h2 className="text-lg font-semibold text-gray-900 mb-3">
                  {t('course.preview.instructions', 'Important instructions')}
                </h2>
                <p className="text-sm text-gray-700 whitespace-pre-wrap leading-relaxed">
                  {course.additionalInstructions}
                </p>
              </div>
            )}

            {/* Description */}
            {course.description && (
              <div className="bg-white rounded-2xl shadow-sm border border-gray-100 p-5 sm:p-6">
                <h2 className="text-lg font-semibold text-gray-900 mb-3">
                  {t('course.preview.aboutThisCourse', 'About this course')}
                </h2>
                <RichTextDisplay content={course.description} showFull className="text-sm text-gray-700" />
              </div>
            )}

            {/* Materials */}
            {materials.length > 0 && (
              <div className="bg-white rounded-2xl shadow-sm border border-gray-100 p-5 sm:p-6">
                <h2 className="text-lg font-semibold text-gray-900 mb-1">
                  {t('course.study.courseMaterials', 'Course materials')}
                </h2>
                <p className="text-sm text-gray-500 mb-4">
                  {t('course.study.materialsCount', { count: materials.length })}
                </p>
                <div className="space-y-2">
                  {materials.map((file, index) => (
                    <FileLink key={`${file.url}-${index}`} file={file} t={t} />
                  ))}
                </div>
              </div>
            )}
          </div>

          {/* Side column */}
          <div className="space-y-6">
            <div className="bg-white rounded-2xl shadow-sm border border-gray-100 p-5">
              <h3 className="text-lg font-semibold text-gray-900 mb-4">
                {t('course.study.instructor', 'Instructor')}
              </h3>
              <div className="flex items-center gap-3">
                <div className="w-12 h-12 bg-blue-600 rounded-full flex items-center justify-center shrink-0 overflow-hidden">
                  {course.instructor?.photo || course.instructor?.avatar ? (
                    <img
                      src={course.instructor.photo || course.instructor.avatar}
                      alt=""
                      className="w-full h-full object-cover"
                    />
                  ) : (
                    <FaUser className="w-6 h-6 text-white" />
                  )}
                </div>
                <div>
                  <div className="font-medium text-gray-900">
                    {course.instructor?.firstName} {course.instructor?.lastName}
                  </div>
                  <div className="text-sm text-gray-600">
                    {t('course.study.courseInstructor', 'Course Instructor')}
                  </div>
                </div>
              </div>
            </div>

            <div className="bg-white rounded-2xl shadow-sm border border-gray-100 p-5">
              <h3 className="text-lg font-semibold text-gray-900 mb-4">
                {t('course.study.offline.enrollmentDetails', 'Enrollment details')}
              </h3>
              <div className="space-y-3 text-sm">
                <div className="flex justify-between gap-3">
                  <span className="text-gray-500">{t('course.study.offline.status', 'Status')}</span>
                  <span className="inline-flex items-center gap-1 font-medium text-green-700">
                    <FaCheckCircle className="w-3.5 h-3.5" />
                    {enrollment.status || 'enrolled'}
                  </span>
                </div>
                <div className="flex justify-between gap-3">
                  <span className="text-gray-500">{t('course.study.offline.payment', 'Payment')}</span>
                  <span className="font-semibold text-green-700">{enrollment.paymentStatus || 'PAID'}</span>
                </div>
                {enrollment.serialNumber && (
                  <div className="flex justify-between gap-3">
                    <span className="text-gray-500">{t('course.study.offline.serial', 'Serial')}</span>
                    <span className="font-mono font-medium text-gray-900">{enrollment.serialNumber}</span>
                  </div>
                )}
                {enrollment.accessCode && (
                  <div className="flex justify-between gap-3">
                    <span className="text-gray-500">{t('course.study.offline.accessCode', 'Access code')}</span>
                    <span className="font-mono font-medium text-gray-900">{enrollment.accessCode}</span>
                  </div>
                )}
                {enrollment.enrolledAt && (
                  <div className="flex justify-between gap-3">
                    <span className="text-gray-500">{t('course.study.offline.enrolledAt', 'Enrolled')}</span>
                    <span className="text-gray-900">{formatDate(enrollment.enrolledAt, language)}</span>
                  </div>
                )}
              </div>

              <button
                type="button"
                onClick={handleDownloadTicket}
                disabled={downloading}
                className="mt-5 w-full inline-flex items-center justify-center gap-2 px-4 py-2.5 rounded-xl border border-green-200 bg-green-50 text-green-800 font-semibold hover:bg-green-100 disabled:opacity-60 transition"
              >
                <FaDownload className="w-4 h-4" />
                {t('course.study.offline.downloadTicket', 'Download Enrollment Ticket')}
              </button>
            </div>

            <div className="bg-white rounded-2xl shadow-sm border border-gray-100 p-5">
              <h3 className="text-lg font-semibold text-gray-900 mb-4">
                {t('course.study.courseInfo', 'Course info')}
              </h3>
              <div className="space-y-3 text-sm text-gray-700">
                {course.language && (
                  <div className="flex justify-between gap-2">
                    <span className="text-gray-500">{t('course.preview.language', 'Language')}</span>
                    <span className="capitalize">{course.language}</span>
                  </div>
                )}
                {course.courseLevel && (
                  <div className="flex justify-between gap-2">
                    <span className="text-gray-500">{t('course.preview.level', 'Level')}</span>
                    <span className="capitalize">{course.courseLevel}</span>
                  </div>
                )}
                {course.duration != null && (
                  <div className="flex justify-between gap-2">
                    <span className="text-gray-500">{t('course.preview.duration', 'Duration')}</span>
                    <span>{t('course.study.minutesCount', { count: course.duration })}</span>
                  </div>
                )}
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};

export default OfflineCourseStudy;
