import { useState, useEffect, useMemo } from 'react';
import { useTranslation } from 'react-i18next';
import { Link } from 'react-router-dom';
import { useLanguage } from '../../hooks/useLanguage';
import { useAuth } from '../../context/AuthContext';
import { enrollmentService } from '../../services/new-api';
import { toast } from 'react-toastify';
import {
    CreditCard,
    Receipt,
    Download,
    Calendar,
    DollarSign,
    CheckCircle2,
    Clock,
    ShieldCheck,
    AlertCircle,
    Search,
    BookOpen,
    ExternalLink,
    Filter,
    RefreshCw,
    Loader2,
    Copy,
    Check,
    Sparkles,
    Lock,
    HelpCircle,
    ChevronRight,
    FileText
} from 'lucide-react';

const PaymentSettings = () => {
    const { t } = useTranslation();
    const { isRTL } = useLanguage();
    const { user } = useAuth();

    const [loading, setLoading] = useState(true);
    const [courses, setCourses] = useState([]);
    const [searchQuery, setSearchQuery] = useState('');
    const [typeFilter, setTypeFilter] = useState('all');
    const [pdfLoading, setPdfLoading] = useState({});
    const [copiedSerial, setCopiedSerial] = useState(null);
    const [activeTab, setActiveTab] = useState('history'); // 'history' | 'methods' | 'policies'

    // Load enrollment payment transactions
    useEffect(() => {
        loadTransactions();
    }, []);

    const loadTransactions = async () => {
        try {
            setLoading(true);
            const data = await enrollmentService.getMyCourses();
            setCourses(data.courses || []);
        } catch (error) {
            console.error('Error loading payment transactions:', error);
            toast.error(t('student.settings.payment.loadFailed', 'تعذّر تحميل سجل المدفوعات'));
        } finally {
            setLoading(false);
        }
    };

    // Calculate Financial Overview Metrics
    const stats = useMemo(() => {
        const totalAmount = courses.reduce((sum, c) => sum + (c.paymentAmount || 0), 0);
        const totalCourses = courses.length;
        const lastTransaction = courses[0] || null;

        return {
            totalAmount,
            totalCourses,
            lastTransaction
        };
    }, [courses]);

    // Download PDF Receipt
    const handleDownloadPDF = async (courseId, courseTitle) => {
        try {
            setPdfLoading(prev => ({ ...prev, [courseId]: true }));
            const response = await enrollmentService.downloadEnrollmentPDF(courseId);

            const blob = new Blob([response], { type: 'application/pdf' });
            const url = window.URL.createObjectURL(blob);
            const link = document.createElement('a');
            link.href = url;
            link.download = `AEC-Receipt-${courseId}.pdf`;
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);
            window.URL.revokeObjectURL(url);

            toast.success(t('student.settings.payment.downloadSuccess', 'تم تحميل إيصال الدفع بنجاح!'));
        } catch (error) {
            console.error('Error downloading invoice:', error);
            toast.error(t('student.settings.payment.downloadFailed', 'تعذّر تحميل إيصال الدفع'));
        } finally {
            setPdfLoading(prev => ({ ...prev, [courseId]: false }));
        }
    };

    // Copy Serial / Invoice Number
    const handleCopySerial = (serial) => {
        if (!serial) return;
        navigator.clipboard.writeText(serial);
        setCopiedSerial(serial);
        toast.info(t('student.settings.payment.copied', 'تم نسخ رقم الإيصال'));
        setTimeout(() => setCopiedSerial(null), 2500);
    };

    // Filter transactions
    const filteredTransactions = useMemo(() => {
        return courses.filter((item) => {
            const matchesSearch =
                !searchQuery ||
                item.title?.toLowerCase().includes(searchQuery.toLowerCase()) ||
                item.serialNumber?.toLowerCase().includes(searchQuery.toLowerCase()) ||
                item.instructor?.firstName?.toLowerCase().includes(searchQuery.toLowerCase());

            const matchesType = typeFilter === 'all' || item.courseType === typeFilter;

            return matchesSearch && matchesType;
        });
    }, [courses, searchQuery, typeFilter]);

    // Format Date helper
    const formatDate = (dateString) => {
        if (!dateString) return '—';
        try {
            return new Date(dateString).toLocaleDateString(t('autoGenerated.en_us', `en-US`), {
                year: 'numeric',
                month: 'short',
                day: 'numeric'
            });
        } catch {
            return dateString;
        }
    };

    return (
        <div className="max-w-6xl mx-auto px-4 sm:px-6 py-6 sm:py-8 space-y-8" dir={t('autoGenerated.ltr', `ltr`)}>
            
            {/* PAGE HEADER */}
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
                <div className="space-y-1">
                    <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-bold bg-blue-50 dark:bg-blue-950/50 text-blue-600 dark:text-blue-400 border border-blue-200/50 dark:border-blue-900/40">
                        <CreditCard className="w-3.5 h-3.5" />
                        <span>{t('student.settings.payment.badge', 'المركز المالي للطالب')}</span>
                    </div>
                    <h1 className="text-2xl sm:text-3xl font-extrabold text-slate-900 dark:text-white tracking-tight">
                        {t('student.settings.payment.title', 'المدفوعات وسجل الفواتير')}
                    </h1>
                    <p className="text-sm text-slate-500 dark:text-slate-400">
                        {t('student.settings.payment.subtitle', 'متابعة مدفوعاتك، تحميل إيصالات الدورات وتفاصيل المعاملات المالية المعتمدة')}
                    </p>
                </div>

                <div className="flex items-center gap-2">
                    <button
                        onClick={loadTransactions}
                        disabled={loading}
                        className="p-2.5 rounded-xl border border-slate-200 dark:border-slate-800 text-slate-600 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors"
                        title={t('common.refresh', 'تحديث البيانات')}
                    >
                        <RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin text-blue-600' : ''}`} />
                    </button>
                    <Link
                        to="/student/help"
                        className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl text-xs font-bold text-slate-700 dark:text-slate-200 bg-slate-100 hover:bg-slate-200 dark:bg-slate-800 dark:hover:bg-slate-700/80 transition-colors"
                    >
                        <HelpCircle className="w-4 h-4 text-blue-500" />
                        <span>{t('student.settings.payment.needHelp', 'مساعدة في الفوترة')}</span>
                    </Link>
                </div>
            </div>

            {/* FINANCIAL OVERVIEW STATS */}
            <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4 sm:gap-6">
                
                {/* Total Spend */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs flex items-center gap-4">
                    <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-blue-600 to-indigo-600 text-white flex items-center justify-center shrink-0 shadow-md shadow-blue-500/20">
                        <DollarSign className="w-6 h-6" />
                    </div>
                    <div>
                        <span className="text-xs font-semibold text-slate-400 block">
                            {t('student.settings.payment.totalSpent', 'إجمالي المدفوعات')}
                        </span>
                        <div className="text-xl sm:text-2xl font-black text-slate-900 dark:text-white mt-0.5">
                            {stats.totalAmount.toLocaleString()} <span className="text-xs font-bold text-blue-600 dark:text-blue-400">ر.س</span>
                        </div>
                    </div>
                </div>

                {/* Total Paid Courses */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs flex items-center gap-4">
                    <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-emerald-500 to-teal-600 text-white flex items-center justify-center shrink-0 shadow-md shadow-emerald-500/20">
                        <BookOpen className="w-6 h-6" />
                    </div>
                    <div>
                        <span className="text-xs font-semibold text-slate-400 block">
                            {t('student.settings.payment.enrolledCourses', 'الدورات المسجلة')}
                        </span>
                        <div className="text-xl sm:text-2xl font-black text-slate-900 dark:text-white mt-0.5">
                            {stats.totalCourses} <span className="text-xs font-bold text-emerald-600 dark:text-emerald-400">دورة</span>
                        </div>
                    </div>
                </div>

                {/* Last Transaction */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs flex items-center gap-4">
                    <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-purple-500 to-indigo-600 text-white flex items-center justify-center shrink-0 shadow-md shadow-purple-500/20">
                        <Calendar className="w-6 h-6" />
                    </div>
                    <div className="min-w-0">
                        <span className="text-xs font-semibold text-slate-400 block truncate">
                            {t('student.settings.payment.lastPayment', 'آخر عملية شراء')}
                        </span>
                        <div className="text-sm font-bold text-slate-900 dark:text-white mt-0.5 truncate">
                            {stats.lastTransaction ? formatDate(stats.lastTransaction.enrolledAt) : 'لا توجد بعد'}
                        </div>
                    </div>
                </div>

                {/* Payment Security */}
                <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-5 shadow-xs flex items-center gap-4">
                    <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-amber-500 to-orange-600 text-white flex items-center justify-center shrink-0 shadow-md shadow-amber-500/20">
                        <ShieldCheck className="w-6 h-6" />
                    </div>
                    <div>
                        <span className="text-xs font-semibold text-slate-400 block">
                            {t('student.settings.payment.securityLevel', 'مستوى الأمان')}
                        </span>
                        <div className="text-sm font-bold text-slate-900 dark:text-white mt-0.5">
                            تشفير 256-bit SSL
                        </div>
                    </div>
                </div>

            </div>

            {/* TAB SELECTOR */}
            <div className="flex border-b border-slate-200 dark:border-slate-800 gap-2 sm:gap-4 overflow-x-auto custom-scrollbar pb-px">
                <button
                    onClick={() => setActiveTab('history')}
                    className={`flex items-center gap-2 px-5 py-3 font-bold text-sm rounded-t-2xl transition-all duration-200 border-b-2 whitespace-nowrap cursor-pointer ${
                        activeTab === 'history'
                            ? 'border-blue-600 text-blue-600 dark:text-blue-400 bg-blue-50/50 dark:bg-blue-950/20'
                            : 'border-transparent text-slate-500 hover:text-slate-800 dark:hover:text-slate-200 hover:bg-slate-50 dark:hover:bg-slate-900/50'
                    }`}
                >
                    <Receipt className="w-4 h-4" />
                    <span>{t('student.settings.payment.tabInvoices', 'سجل الفواتير والإيصالات')}</span>
                    <span className="px-2 py-0.5 rounded-full text-xs bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-400 font-semibold">
                        {courses.length}
                    </span>
                </button>
            </div>

            {/* TAB 1: TRANSACTIONS & INVOICE HISTORY */}
            {activeTab === 'history' && (
                <div className="space-y-6">
                    {/* Search & Filter Controls */}
                    <div className="flex flex-col sm:flex-row gap-3 items-center justify-between">
                        {/* Search Input */}
                        <div className="relative w-full sm:w-80">
                            <Search className="w-4 h-4 absolute start-3.5 top-1/2 -translate-y-1/2 text-slate-400" />
                            <input
                                type="text"
                                value={searchQuery}
                                onChange={(e) => setSearchQuery(e.target.value)}
                                placeholder={t('student.settings.payment.searchPlaceholder', 'بحث باسم الدورة أو رقم الإيصال...')}
                                className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl ps-10 pe-4 py-2 text-sm text-slate-900 dark:text-white placeholder:text-slate-400 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-600 transition-all shadow-xs"
                            />
                        </div>

                        {/* Type Filters */}
                        <div className="flex items-center gap-1.5 w-full sm:w-auto overflow-x-auto custom-scrollbar">
                            {[
                                { id: 'all', label: 'الكل' },
                                { id: 'recorded', label: 'مسجلة' },
                                { id: 'live', label: 'مباشرة' },
                                { id: 'onsite', label: 'حضورية' }
                            ].map((f) => (
                                <button
                                    key={f.id}
                                    onClick={() => setTypeFilter(f.id)}
                                    className={`px-3.5 py-1.5 rounded-xl text-xs font-bold transition-colors cursor-pointer ${
                                        typeFilter === f.id
                                            ? 'bg-blue-600 text-white shadow-xs'
                                            : 'bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 text-slate-600 dark:text-slate-400 hover:bg-slate-50 dark:hover:bg-slate-800'
                                    }`}
                                >
                                    {f.label}
                                </button>
                            ))}
                        </div>
                    </div>

                    {/* Loading State */}
                    {loading ? (
                        <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-12 text-center space-y-4">
                            <Loader2 className="w-8 h-8 animate-spin text-blue-600 mx-auto" />
                            <p className="text-sm font-semibold text-slate-500">جاري تحميل سجل الفواتير والمعاملات...</p>
                        </div>
                    ) : filteredTransactions.length === 0 ? (
                        /* Empty State */
                        <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 p-12 text-center space-y-4">
                            <div className="w-16 h-16 rounded-2xl bg-blue-50 dark:bg-blue-950/50 text-blue-600 dark:text-blue-400 flex items-center justify-center mx-auto">
                                <Receipt className="w-8 h-8" />
                            </div>
                            <div className="space-y-1">
                                <h3 className="text-base font-bold text-slate-900 dark:text-white">
                                    {t('student.settings.payment.noTransactions', 'لا توجد فواتير أو معاملات مسجلة')}
                                </h3>
                                <p className="text-xs text-slate-500 dark:text-slate-400 max-w-sm mx-auto">
                                    {t('student.settings.payment.noTransactionsDesc', 'عند اشتراكك في أي دورة تدريبية، ستظهر هنا جميع الإيصالات الرسمية وتفاصيل الدفع.')}
                                </p>
                            </div>
                            <Link
                                to="/explore"
                                className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-blue-600 hover:bg-blue-700 text-white font-bold text-xs shadow-md shadow-blue-500/20 transition-all"
                            >
                                <BookOpen className="w-4 h-4" />
                                <span>{t('student.settings.payment.browseCourses', 'تصفح الدورات المتاحة')}</span>
                            </Link>
                        </div>
                    ) : (
                        /* Transactions Table / Cards List */
                        <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200/80 dark:border-slate-800 overflow-hidden shadow-xs">
                            <div className="overflow-x-auto">
                                <table className="w-full text-start text-xs sm:text-sm">
                                    <thead>
                                        <tr className="border-b border-slate-100 dark:border-slate-800 bg-slate-50/75 dark:bg-slate-800/40 text-slate-500 dark:text-slate-400 font-bold uppercase tracking-wider text-[11px]">
                                            <th className="px-5 py-4 text-start">{t('student.settings.payment.course', 'الدورة التدريبية')}</th>
                                            <th className="px-5 py-4 text-start">{t('student.settings.payment.receiptNo', 'رقم الإيصال / السريال')}</th>
                                            <th className="px-5 py-4 text-start">{t('student.settings.payment.date', 'تاريخ العملية')}</th>
                                            <th className="px-5 py-4 text-start">{t('student.settings.payment.amount', 'المبلغ المدفوع')}</th>
                                            <th className="px-5 py-4 text-center">{t('student.settings.payment.status', 'الحالة')}</th>
                                            <th className="px-5 py-4 text-end">{t('student.settings.payment.action', 'الإجراء')}</th>
                                        </tr>
                                    </thead>
                                    <tbody className="divide-y divide-slate-100 dark:divide-slate-800/80 font-medium">
                                        {filteredTransactions.map((tx) => (
                                            <tr key={tx.enrollmentId || tx.courseId} className="hover:bg-slate-50/60 dark:hover:bg-slate-800/40 transition-colors">
                                                
                                                {/* Course Title & Instructor */}
                                                <td className="px-5 py-4">
                                                    <div className="flex items-center gap-3">
                                                        <div className="w-11 h-11 rounded-xl bg-slate-100 dark:bg-slate-800 overflow-hidden shrink-0 border border-slate-200/60 dark:border-slate-700">
                                                            {tx.thumbnail ? (
                                                                <img src={tx.thumbnail} alt={tx.title} className="w-full h-full object-cover" />
                                                            ) : (
                                                                <div className="w-full h-full flex items-center justify-center text-slate-400">
                                                                    <BookOpen className="w-5 h-5" />
                                                                </div>
                                                            )}
                                                        </div>
                                                        <div className="min-w-0 max-w-xs sm:max-w-sm">
                                                            <h4 className="font-bold text-slate-900 dark:text-white truncate text-sm">
                                                                {tx.title}
                                                            </h4>
                                                            <div className="flex items-center gap-2 mt-0.5 text-xs text-slate-400">
                                                                <span>{tx.instructor ? `${tx.instructor.firstName} ${tx.instructor.lastName}` : 'AEC Academy'}</span>
                                                                <span>•</span>
                                                                <span className="capitalize">{tx.courseType}</span>
                                                            </div>
                                                        </div>
                                                    </div>
                                                </td>

                                                {/* Serial / Receipt No */}
                                                <td className="px-5 py-4 whitespace-nowrap">
                                                    {tx.serialNumber ? (
                                                        <button
                                                            type="button"
                                                            onClick={() => handleCopySerial(tx.serialNumber)}
                                                            className="group flex items-center gap-1.5 font-mono text-xs text-slate-600 dark:text-slate-300 hover:text-blue-600 dark:hover:text-blue-400"
                                                            title="نسخ الرقم"
                                                        >
                                                            <span>{tx.serialNumber}</span>
                                                            {copiedSerial === tx.serialNumber ? (
                                                                <Check className="w-3.5 h-3.5 text-emerald-500" />
                                                            ) : (
                                                                <Copy className="w-3.5 h-3.5 opacity-0 group-hover:opacity-100 transition-opacity" />
                                                            )}
                                                        </button>
                                                    ) : (
                                                        <span className="text-slate-400 font-mono text-xs">—</span>
                                                    )}
                                                </td>

                                                {/* Date */}
                                                <td className="px-5 py-4 whitespace-nowrap text-xs text-slate-600 dark:text-slate-300">
                                                    {formatDate(tx.enrolledAt)}
                                                </td>

                                                {/* Amount */}
                                                <td className="px-5 py-4 whitespace-nowrap">
                                                    <span className="font-extrabold text-slate-900 dark:text-white text-sm">
                                                        {(tx.paymentAmount || 0).toLocaleString()}
                                                    </span>
                                                    <span className="text-xs text-slate-500 dark:text-slate-400 ms-1 font-bold">
                                                        ر.س
                                                    </span>
                                                </td>

                                                {/* Status */}
                                                <td className="px-5 py-4 text-center whitespace-nowrap">
                                                    <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-full text-xs font-bold bg-emerald-50 dark:bg-emerald-950/40 text-emerald-600 dark:text-emerald-400 border border-emerald-200 dark:border-emerald-800">
                                                        <CheckCircle2 className="w-3 h-3 text-emerald-500" />
                                                        <span>{t('student.settings.payment.paid', 'مكتمل (PAID)')}</span>
                                                    </span>
                                                </td>

                                                {/* Actions */}
                                                <td className="px-5 py-4 text-end whitespace-nowrap">
                                                    <button
                                                        type="button"
                                                        onClick={() => handleDownloadPDF(tx.courseId, tx.title)}
                                                        disabled={pdfLoading[tx.courseId]}
                                                        className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-slate-100 hover:bg-slate-200 dark:bg-slate-800 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-200 font-bold text-xs transition-colors cursor-pointer disabled:opacity-50"
                                                    >
                                                        {pdfLoading[tx.courseId] ? (
                                                            <>
                                                                <Loader2 className="w-3.5 h-3.5 animate-spin" />
                                                                <span>جاري التجهيز...</span>
                                                            </>
                                                        ) : (
                                                            <>
                                                                <Download className="w-3.5 h-3.5 text-blue-600 dark:text-blue-400" />
                                                                <span>تحميل الإيصال</span>
                                                            </>
                                                        )}
                                                    </button>
                                                </td>

                                            </tr>
                                        ))}
                                    </tbody>
                                </table>
                            </div>
                        </div>
                    )}
                </div>
            )}


        </div>
    );
};

export default PaymentSettings;
