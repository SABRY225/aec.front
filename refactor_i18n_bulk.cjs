const fs = require('fs');
const path = require('path');

const walkSync = function(dir, filelist) {
    let files = fs.readdirSync(dir);
    filelist = filelist || [];
    files.forEach(function(file) {
        if (fs.statSync(path.join(dir, file)).isDirectory()) {
            filelist = walkSync(path.join(dir, file), filelist);
        } else {
            if (file.endsWith('.jsx')) {
                filelist.push(path.join(dir, file));
            }
        }
    });
    return filelist;
};

const targetDir = process.argv[2];

if (!targetDir) {
    console.error('Please provide a target directory');
    process.exit(1);
}

const files = walkSync(targetDir);
const regex = /(isRtl|isRTL)\s*\?\s*(['"`])((?:(?!\2)[^\\]|\\.)*?)\2\s*:\s*(['"`])((?:(?!\4)[^\\]|\\.)*?)\4/g;

let totalMatchCount = 0;
const translations = [];

files.forEach(targetFile => {
    let content = fs.readFileSync(targetFile, 'utf8');
    let matchCount = 0;
    
    let newContent = content.replace(regex, (match, p1, q1, arText, q2, enText) => {
        matchCount++;
        let key = enText
            .toLowerCase()
            .replace(/[^a-z0-9]+/g, '_')
            .replace(/^_+|_+$/g, '')
            .substring(0, 30);
        
        if (!key) {
            key = 'text_' + Math.random().toString(36).substr(2, 5);
        }
        
        translations.push({ key, ar: arText, en: enText });

        return `t('autoGenerated.${key}', \`${enText.replace(/`/g, "\\`")}\`)`;
    });

    if (matchCount > 0) {
        fs.writeFileSync(targetFile, newContent, 'utf8');
        console.log(`Replaced ${matchCount} matches in ${targetFile}`);
        totalMatchCount += matchCount;
    }
});

console.log(`Total replacements: ${totalMatchCount}`);

let existingTranslations = [];
try {
    existingTranslations = JSON.parse(fs.readFileSync('translations_dump.json', 'utf8'));
} catch (e) {
    // Ignore if not exists
}

existingTranslations = existingTranslations.concat(translations);

// Remove duplicates based on key
const uniqueTranslations = [];
const seenKeys = new Set();
for (const t of existingTranslations) {
    if (!seenKeys.has(t.key)) {
        seenKeys.add(t.key);
        uniqueTranslations.push(t);
    }
}

fs.writeFileSync('translations_dump.json', JSON.stringify(uniqueTranslations, null, 2), 'utf8');
