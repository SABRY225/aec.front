const fs = require('fs');
const path = require('path');

const targetFile = process.argv[2];

if (!targetFile) {
    console.error('Please provide a target file');
    process.exit(1);
}

let content = fs.readFileSync(targetFile, 'utf8');

// We are looking for: isRtl ? 'ARABIC_TEXT' : 'ENGLISH_TEXT'
// Or: isRTL ? 'ARABIC_TEXT' : 'ENGLISH_TEXT'
// We also have to handle template literals if any.
// Regex to match: /(isRtl|isRTL)\s*\?\s*(['"`])(.*?)\2\s*:\s*(['"`])(.*?)\4/g

const regex = /(isRtl|isRTL)\s*\?\s*(['"`])((?:(?!\2)[^\\]|\\.)*?)\2\s*:\s*(['"`])((?:(?!\4)[^\\]|\\.)*?)\4/g;

let match;
let matchCount = 0;
const translations = [];

let newContent = content.replace(regex, (match, p1, q1, arText, q2, enText) => {
    matchCount++;
    // We need to generate a key for this translation.
    // Let's use a cleaned up version of the English text.
    let key = enText
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '_')
        .replace(/^_+|_+$/g, '')
        .substring(0, 30);
    
    if (!key) {
        key = 'text_' + Math.random().toString(36).substr(2, 5);
    }
    
    // Add to our list to update locale files later
    translations.push({ key, ar: arText, en: enText });

    // Assuming `t` function is available in the scope
    // Return: t('autoGenerated.' + key, 'English Text')
    // Note: since i18next can accept default value as the second argument.
    // Wait, if it has variables, like `${mins}m ago`, we should handle it better, but let's just do standard strings first.
    return `t('autoGenerated.${key}', '${enText.replace(/'/g, "\\'")}')`;
});

fs.writeFileSync(targetFile, newContent, 'utf8');

console.log(`Replaced ${matchCount} matches in ${targetFile}`);
fs.writeFileSync('translations_dump.json', JSON.stringify(translations, null, 2), 'utf8');
